/**
 * src/core/almanac/lunar-mansions.js —— 二十八宿（自研，零依赖）
 *
 * 大白话：二十八宿是把周天恒星分成 28 组，每天有一宿「值日」，
 * 黄历上用来标注当天星宿与吉凶。
 * 口径：星期四（角宿）起，按「角亢氐房心尾箕（东方七宿）→ 斗牛女虚危室壁（北方）→
 * 奎娄胃昴毕觜参（西方）→ 井鬼柳星张翼轸（南方）」循环，
 * 每 28 天一周，以已知星期四=角宿锚定（通例：星期四值角宿）。
 *
 * 文献状态（如实标注，三项分开算账）：
 *
 *   ① **五行（七政所属）有直证**。《钦定协纪辨方书·卷一·二十八宿配日》按语引库外《吉凶时日善恶宿曜经》：
 *      「虚昴星房属日，危毕张心属月，室觜翼尾属火，壁参轸箕属水，奎井角斗属木，娄鬼亢牛属金，
 *      胃柳氐女属土」——二十八宿的五行（日月火水木金土）即从此来，本表逐宿与之一致。
 *   ② **动物（禽象）大体有证**。《协纪·卷一》引库外《考原》逐宫推「子鼠丑牛……」的禽象来源：
 *      「虚星居中故为鼠之本象，女为蝠、危为燕……胃为雉、毕为乌……角居其旁则取蛟为龙之类」，
 *      本表二十八宿禽象逐宿与之一致（仅「壁」一宿底本字形残缺，取通行写法的近似字）。
 *   ③ **吉凶定性 2026-10-31 已获通书底本直证**。《玉匣記·二十八宿值日吉凶歌》逐宿列出吉凶与断语
 *      （角亢房尾箕斗室壁娄胃毕参井张轸为吉，亢氐心牛女虚危奎昴觜鬼柳星翼为凶），与本表 28 宿逐条
 *      对拍**全部相符**，故由「通书通例」升为「底本直证（通书系统）」。
 *      另一路意见仍须并存：《钦定协纪辨方书·卷一》按语明说时宪书「以角亢房斗牛虚壁奎娄鬼张翼轸
 *      十三宿日为宜裁衣，亦无取义，**应一并删去**」，并质疑配日之法「七政安得与二十八宿相配耶」。
 *      两说并列写入输出，不强行统一。起例（星期四值角）仍取通书通行锚点，属结构自洽、锚点不可考。
 *   另：二十八宿纪日本是西域历法（宿曜经），《协纪》说「厯家存此可使绝域殊方同晓某日是何甲子」，
 *      保留它是因为通用，不是因为吉凶有据——这一层意思已经写进输出口径。
 */

