/**
 * 某日值宿。
 * 锚定：2024-02-10 = 氐宿（公开万年历多源一致）；由此可反推 2024-02-08（星期四）=角宿，
 *   与通书「星期四值角宿」的说法自洽。（此前文件里还留着一张 WEEK_START 表，是早期写法，
 *   与本锚点并不相符、且从未被调用，已删——留着只会让人以为有两套起例。）
 * @returns {{宿, 五行, 吉凶, 动物}}
 */
export function xiu28Of(y, m, d) {
  const dn = Math.floor(Date.UTC(y, m - 1, d) / 86400000);
  const idx = ((dn + 7) % 28 + 28) % 28; // dn%28 + 7 ≡ 氐(2) 当 dn=19763(2024-02-10)
  const name = XIU28_NAMES[idx];
  return { 宿: name, ...XIU_META[name] };
}
