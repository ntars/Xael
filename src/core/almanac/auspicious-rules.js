/**
 * 季节（四立分季）：寅卯辰春、巳午未夏、申酉戌秋、亥子丑冬。
 * 依据《协纪辨方书·义例》各条均以「春/夏/秋/冬」与月建对应，
 * 而四季月（辰未戌丑）在该书体系里归入**前季**（如「春木王」含辰月土旺未至）。
 */
export function seasonOfBranch(zhi) {
  if (['寅', '卯', '辰'].includes(zhi)) return '春';
  if (['巳', '午', '未'].includes(zhi)) return '夏';
  if (['申', '酉', '戌'].includes(zhi)) return '秋';
  return '冬';
}

