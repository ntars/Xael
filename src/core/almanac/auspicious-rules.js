export function godsByRule(monthZhi, dayGz) {
  const mi = miOf(monthZhi);
  const gz = String(dayGz || '');
  const gan = gz.slice(0, 1);
  const zhi = gz.slice(1, 2);
  const season = seasonOfBranch(monthZhi);
  const 吉神 = [];
  const 凶煞 = [];
  const 依据 = {};
  if (mi < 0 || gz.length < 2) return { 吉神, 凶煞, 依据 };

  // 天赦
  if (gz === TIAN_SHE[season]) 吉神.push('天赦');
  // 月恩（正月＝寅，故月支序 2 对应表首项，用 (mi-2) mod 12）
  const enGan = YUE_EN[((mi - 2) % 12 + 12) % 12];
  if (gan === enGan) 吉神.push('月恩');
  // 四相
  if ((SI_XIANG[season] || []).includes(gan)) 吉神.push('四相');
  // 天医：「正月起戌顺行十二辰」→ 建寅之月天医在戌，逐月顺进一辰
  if (fwd(mi, 8) === zhi) 吉神.push('天医');
  // 生气：「常居月建后二辰」
  if (back(mi, 2) === zhi) 吉神.push('生气');
  // 时阳：「常居月建后二辰」（与生气同位，两神并存，原文两条各自成条）
  if (back(mi, 2) === zhi) 吉神.push('时阳');
  // 天喜：「正月戌、二月亥、三月子、四月丑，顺轮十二月」→ 建寅在戌，顺进一辰
  if (fwd(mi, 8) === zhi) 吉神.push('天喜');
  // 福德：「常居月建前二辰」
  if (fwd(mi, 2) === zhi) 吉神.push('福德');
  // 天巫：「常居月建前二辰」
  if (fwd(mi, 2) === zhi) 吉神.push('天巫');
  // 吉期：「常居月建前一辰」
  if (fwd(mi, 1) === zhi) 吉神.push('吉期');


  // 天德：按月支查，值为天干则查日干，值为地支则查日支（四仲月用四维卦位之支）
  const tianDe = TIAN_DE[monthZhi] || '';
  if (tianDe && (tianDe === gan || tianDe === zhi)) 吉神.push('天德');
  // 天德合：天德为干取其合干，为支取其六合
  const tianDeHe = GAN_HE[tianDe] || ZHI_HE[tianDe] || '';
  if (tianDeHe && (tianDeHe === gan || tianDeHe === zhi)) 吉神.push('天德合');
  // 月德：寅午戌见丙、申子辰见壬、亥卯未见甲、巳酉丑见庚
  if (gan === YUE_DE[monthZhi]) 吉神.push('月德');
  // 月德合：月德之合干
  if (gan === GAN_HE[YUE_DE[monthZhi]]) 吉神.push('月德合');
  // 月空：月德之冲干
  if (gan === YUE_KONG[monthZhi]) 吉神.push('月空');
  // 不将：逐月照录的干支表
  if ((BU_JIANG[monthZhi] || '').indexOf(gz) >= 0 && gzList(BU_JIANG[monthZhi]).indexOf(gz) >= 0) 吉神.push('不将');

  // ── 日神取一定干支者（卷九·立成 原表）：只查表，不推公式 ──
  const fixed = (k) => (FIXED_GZ[k] || '').indexOf(gz) >= 0;
  if (fixed('天恩')) 吉神.push('天恩');
  if (fixed('鸣吠')) 吉神.push('鸣吠');
  if (fixed('鸣吠对')) 吉神.push('鸣吠对');
  // 宝日/义日/制日/专日/伐日/无禄 六神《协纪》立成虽有定干支，但通书「吉神宜趋/凶煞宜忌」
  // 两栏从不列它们（本仓 2024 全量实测 0 次），故只保留表数据、不进历例输出，避免比对时误判。
  if (fixed('八专')) 凶煞.push('八专');
  if (fixed('触水龙')) 凶煞.push('触水龙');
  if (fixed('重日')) 凶煞.push('重日');
  // 五合（寅卯日）为吉；五离（申酉日）为凶——原文「五离者五合之冲」，通书另名「除神」列吉神
  if (WU_HE_ZHI.indexOf(zhi) >= 0) 吉神.push('五合');
  if (WU_LI_ZHI.indexOf(zhi) >= 0) { 吉神.push('除神'); 凶煞.push('五离'); }
  // 解神（吉神）：正二月申、三四月戌、五六月子、七八月寅、九十月辰、十一十二月午
  if (JIE_SHEN[monthZhi] === zhi) 吉神.push('解神');

  // 死气：「常居月建前四辰」（即生气之冲）
  if (fwd(mi, 4) === zhi) 凶煞.push('死气');
  // 天狗：「常居月建前二辰」
  if (fwd(mi, 2) === zhi) 凶煞.push('天狗');
  // 月厌：「正月在戌逆行十二辰」→ 建寅在戌，逐月逆退一辰
  if (Z[((10 - (mi - 2)) % 12 + 12) % 12] === zhi) 凶煞.push('月厌');
  // 六仪：「正月起辰逆行十二辰」→ 建寅在辰，逐月逆退一辰（六仪为吉神）
  if (Z[((4 - (mi - 2)) % 12 + 12) % 12] === zhi) 吉神.push('六仪');
  // 要安：逐月固定支（正月寅、二月申…）
  if (YAO_AN[((mi - 2) % 12 + 12) % 12] === zhi) 吉神.push('要安');
  // 五虚：春巳酉丑…
  if ((WU_XU[season] || []).includes(zhi)) 凶煞.push('五虚');

  const mon = ((mi - 2) % 12 + 12) % 12 + 1; // 正月＝建寅 → 月序 1..12
  // 金堂（吉）：逐月固定支
  if (JIN_TANG[mon - 1] === zhi) 吉神.push('金堂');
  // 复日（凶）：按月序取日干
  if ((FU_RI[mon] || []).includes(gan)) 凶煞.push('复日');
  // 守日（吉）：春酉夏子秋卯冬午
  if (SHOU_RI[season] === zhi) 吉神.push('守日');
  // 王日/官日/相日/民日（吉）：原书春秋冬四时各一支
  if (WANG_RI[season] === zhi) 吉神.push('王日');
  if (GUAN_RI[season] === zhi) 吉神.push('官日');
  if (XIANG_RI[season] === zhi) 吉神.push('相日');
  if (MIN_RI[season] === zhi) 吉神.push('民日');
  // 九坎、九焦（凶）：同一起例，正月在辰逆退
  if (JIU_KAN_SEQ[mon - 1] === zhi) { 凶煞.push('九坎'); 凶煞.push('九焦'); }
  // 九空（凶）：正月在辰逆行四季
  if (JIU_KONG_SEQ[mon - 1] === zhi) 凶煞.push('九空');
  // 厌对（凶）：「正月起辰逆行十二辰」，与月厌同宫相冲
  if (Z[((4 - (mi - 2)) % 12 + 12) % 12] === zhi) 凶煞.push('厌对');

  依据.天医 = '正月起戌顺行十二辰';
  依据.生气 = '常居月建后二辰';
  依据.福德 = '常居月建前二辰';
  依据.月厌 = '正月在戌逆行十二辰';
  return { 吉神, 凶煞, 依据 };
}

