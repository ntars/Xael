/**
 * 平、收二位的天罡/河魁归属：阳月（建寅至建巳、建申至建亥？不——）
 * 按《协纪辨方书·卷七》原文目次所述「平【阳月天罡 阴月河魁】」「收【阳月河魁 阴月天罡】」，
 * 即阳月（月支为阳辰：子寅辰午申戌）时天罡在平、河魁在收；阴月反之。
 * @param {string} 值星 '平' 或 '收'
 * @param {number} 月支序 0=子
 * @returns {string} 该位当月的具体异名
 */
/**
 * 取某位值星当日的实体异名清单（在 JIANCHU_ALIAS 基础上做条件筛除）。
 *
 * ★「满【福德 天巫 天狗】」里的天狗是有条件的。《协纪辨方书·卷七·义例四》在「天狗」条下辨：
 *   「疑同一满日也，忽又谓之天狗……详考其义，盖**天狗者戌日值满也**……故又谓之天狗，
 *    而谓不宜祷祀，**非谓凡为满日皆天狗也**。」又自注：「又按天狗为申建之戌，止一位，
 *    故不入图。」
 *   → 即：满日恰逢戌日（戌日值满，只剩建申之月一位）才叫天狗，别的满日不是。
 * 平、收二位的天罡/河魁按当月阴阳取一个（见 jianchuAliasOf）。
 * @param {string} 值星 '建'…'闭'
 * @param {number} 月支序 0=子
 * @param {number} [日支序] 0=子；缺省时不筛天狗（保持原目全列）
 * @returns {string[]}
 */
export function jianchuAliasesOf(值星, 月支序, 日支序) {
  const list = (JIANCHU_ALIAS[值星] || []).slice();
  const one = jianchuAliasOf(值星, 月支序);
  const out = [];
  for (const a of list) {
    if (a.includes('/')) { if (one) out.push(one); continue; } // 天罡/河魁 二选一
    if (a === '天狗' && 日支序 != null && 日支序 !== 10) continue; // 天狗须戌日（戌序10）
    out.push(a);
  }
  return out;
}

export function jianchuAliasOf(值星, 月支序) {
  if (值星 !== '平' && 值星 !== '收') return '';
  const 阳月 = 月支序 % 2 === 0;
  if (值星 === '平') return 阳月 ? '天罡' : '河魁';
  return 阳月 ? '河魁' : '天罡';
}

