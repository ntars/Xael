/**
 * src/core/almanac/twelve-officers.js —— 建除十二神（值星）（自研，零依赖）
 *
 * 大白话：建除十二神是「建、除、满、平、定、执、破、危、成、收、开、闭」十二个字，
 * 轮流值日，用来概括当天宜做/不宜做的事的大类。
 * 规则：月建（月支）当日为「建」，往后逐日顺排十二字循环。
 * 口径：以节气换月（与月柱同界）；按公历日序取模即可，无需额外表。
 */

import { daySexagenaryIndex, monthBranchIndex } from '../calendar/sexagenary.js';
import { BRANCHES } from '../common/constants.js';

export const JIANCHU_NAMES = ['建', '除', '满', '平', '定', '执', '破', '危', '成', '收', '开', '闭'];

/**
 * 某日的建除十二神。
 * 规则：月支「建」位起建。如寅月（正月）：寅日=建、卯日=除……
 * 通用：值星序 = (日支序 − 月支序 + 12) % 12。
 */
export function jianchuOf(y, m, d) {
  // 值星序 = (日支序 − 月支序 + 12) % 12：月支所对应的那个地支日为「建」
  // 《协纪辨方书·建除十二神》：「其法从月建上起建，与斗杓所指相应，
  //   如正月建寅则寅日起建，顺行十二辰是也。」
  const dayZhi = daySexagenaryIndex(y, m, d) % 12; // 六十甲子序 → 支序
  const monthZhi = monthBranchIndex(y, m, d);
  return JIANCHU_NAMES[((dayZhi - monthZhi) % 12 + 12) % 12];
}

/**
 * 交节日的「叠两值日」。
 *
 * 《钦定协纪辨方书·卷七·义例四》引库外历书：「历家以建除满平定执破危成收开闭凡十二日周而复始，
 * 观所值以定吉凶，**每月交节则叠两值日**。其法从月建上起建，与斗杓所指相应，
 * 如正月建寅则寅日起建，顺行十二辰是也。」
 * 即：交节当天，旧月的值星与新月的值星**同时**当值（库外历书两行并列），不是换月就整日只算新的。
 * 本函数返回当日全部当值之神：平日一日一值，交节日两值（旧月在前、新月在后）。
 * @returns {string[]} 长度 1 或 2
 */
export function jianchuStackOf(y, m, d) {
  const dayZhi = daySexagenaryIndex(y, m, d) % 12;
  const now = monthBranchIndex(y, m, d);
  const stacked = [JIANCHU_NAMES[((dayZhi - now) % 12 + 12) % 12]];
  // 当日是否为交节日：monthBranchIndex 是「整日粒度」（交节当日整天已算新月），
  // 故只要前一日的月支与今日不同，今日就是交节日，前一日之值星与今日之值星并列。
  const prev = new Date(Date.UTC(y, m - 1, d));
  prev.setUTCDate(prev.getUTCDate() - 1);
  const py = prev.getUTCFullYear();
  const pm = prev.getUTCMonth() + 1;
  const pd = prev.getUTCDate();
  const prevMonthZhi = monthBranchIndex(py, pm, pd);
  if (prevMonthZhi !== now) {
    // 两值都用「今日日支」算：旧月建一套、新月建一套（库外历书当日两行并列）
    stacked.unshift(JIANCHU_NAMES[((dayZhi - prevMonthZhi) % 12 + 12) % 12]);
  }
  return stacked;
}

