/**
 * src/core/almanac/day-officers.js —— 每日天神（黄道黑道）与吉凶（自研，零依赖）
 *
 * 大白话：黄历里的「黄道吉日/黑道凶日」来自当天值日的天神。
 *
 * 口径依据：《钦定协纪辨方书·卷七·义例五·黄道黑道》引库外《神枢经》——
 *   「青龙、明堂、金匮、天德、玉堂、司命皆月内天黄道之神也，所值之日皆宜兴众务……
 *    天刑、朱雀、白虎、天牢、元武、勾陈者月中黑道也，所理之方所值之日皆不可兴土功」；
 *   同卷引李鼎祚：「青龙正月起子，金匮正月起辰，司命正月起戌，皆顺行六阳辰也；
 *    明堂正月起丑，天德正月起巳，玉堂正月起未，皆顺行六阴辰也……」。
 *   即：正月（寅月）子日为青龙，此后逐日按「青龙明堂天刑朱雀金匮天德白虎玉堂天牢
 *   玄武司命勾陈」十二神顺行；换月时青龙所临之辰进二位（子→寅→辰→午→申→戌）。
 *   等价公式：某月青龙临支 = ((月支序 − 2) × 2) mod 12，当日天神 = ORDER[(日支序 − 青龙临支) mod 12]。
 *
 * 本文件保留 144 格查表（便于逐格核对），并已用上述公式做全表校验（tests 内有断言）。
 */

import { daySexagenaryIndex } from '../calendar/sexagenary.js';
