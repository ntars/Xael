/**
 * 当日值日天神及吉凶。
 * @returns {{天神, 类:'黄道'|'黑道', 吉凶:'吉'|'凶', 断语}}
 */
export function tianshenOf(y, m, d) {
  const monthZhi = monthZhiWholeDay(y, m, d);
  const dayZhi = daySexagenaryIndex(y, m, d) % 12;
  const god = TIANSHEN_TABLE[BRANCHES[monthZhi].z][BRANCHES[dayZhi].z];
  const isHuang = HUANGDAO.includes(god);
  return {
    天神: god,
    类: isHuang ? '黄道' : '黑道',
    吉凶: isHuang ? '吉' : '凶',
    断语: TIANSHEN_MEANING[god],
    别名: TIANSHEN_ALIAS[god] || '',
  };
}
