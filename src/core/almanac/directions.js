/**
 * 某日的方位、百忌、胎神全集。
 */
export function positionOf(y, m, d) {
  const gzIdx = daySexagenaryIndex(y, m, d);
  const gan = STEMS[gzIdx % 10].z;
  const zhi = BRANCHES[gzIdx % 12].z;
  return {
    方位: { 喜神: xiShenOf(STEMS[gzIdx % 10].z), 财神: CAISHEN[gzIdx % 10], 福神: FUSHEN[gzIdx % 10], 阳贵: YANGGUI[gzIdx % 10], 阴贵: YINGUI[gzIdx % 10] },
    彭祖百忌: {
      干: PENGZU_GAN[gan],
      支: PENGZU_ZHI[zhi],
      // 底本异文（仅 壬/酉/戌 三处有异，其余不列）
      异文: [PENGZU_VARIANT[gan], PENGZU_VARIANT[zhi]].filter(Boolean).map((v) => `底本作「${v.底本}」，通行本作「${v.通行}」`),
    },
    胎神: TAISHEN[SEXAGENARY[gzIdx].join('')] || '',
  };
}
