/**
 * 喜神方位：不再用硬编码表，按《钦定协纪辨方书·卷九·辨讹》原文所定的推法现算——
 *   「喜神乃取时干见丙，如甲日丙寅时则以寅时为喜神，论方向则以寅属艮即以艮方为喜神，
 *    是方向原从时起，通书以丑寅皆属艮，误以甲日丑时亦为喜神，逐日皆误，俱宜改正。」
 * 即：先以五鼠遁求该日「时干为丙」的那个时辰，再取其时支所在卦位为喜神方位
 * （寅艮、申坤、午离、戌乾、辰巽）。逐干验算：甲寅→艮、己寅→艮、丙申→坤、辛申→坤、
 * 丁午→离、壬午→离、戊辰→巽、癸辰→巽——与通行表逐一相符。
 * 乙、庚二日丙时两见（丙子时与丙戌时），通行表取戌（乾），本层同取戌，此处置取已如实注明。
 */
const PILLAR_OF = { 寅: '东北', 申: '西南', 午: '正南', 戌: '西北', 辰: '东南' };
/** 五鼠遁：日干 → 子时天干序（甲己还加甲、乙庚丙作初…） */
const WUZI = { 甲: 0, 己: 0, 乙: 2, 庚: 2, 丙: 4, 辛: 4, 丁: 6, 壬: 6, 戊: 8, 癸: 8 };

/** 喜神方位（日干 → 方位）：按协纪「时干见丙」现推，乙庚二日丙时两见取戌 */
export function xiShenOf(gan) {
  const base = WUZI[gan];
  if (base === undefined) return '';
  const hits = [];
  for (let h = 0; h < 12; h++) if ((base + h) % 10 === 2) hits.push(BRANCHES[h].z);
  const zhi = hits.length > 1 ? (hits.includes('戌') ? '戌' : hits[0]) : hits[0];
  return PILLAR_OF[zhi] || '';
}

