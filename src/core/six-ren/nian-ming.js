/**
 * src/core/six-ren/nian-ming.js —— 大六壬「年命」判（自研，零依赖）
 *
 * 大白话：三传四课讲的是「这件事」怎么样，年命讲的是「这件事落到我身上」怎么样。
 *   同一个盘，三十岁的人与六十岁的人，行年不同，吉凶可能相反——所以年命不能省。
 *
 * 依据（库内原文，refs-texts/《六壬大全》-明·佚名（四库本）.md）：
 *   · 《六壬大全·轩辕肘后经》第 2148 行——
 *     「日辰大体已分明，**更看行年合事情。行年克日为不及，日克年神失节名**」
 *     注：「行年克日上神者，名曰不及也。日克行年上神者，名曰失节。假令占人三十七岁，行年在寅，
 *       今日丙上见大吉土，是行年寅克日上大吉土，是名不及也。」
 *   · 同经第 2143 行——
 *     「**事神年上两相生，此主所为皆得成。事神年上两相克，此主所为皆不得**」
 *     注：「事神者，上用主事之神也。」
 *   · 同经第 2140 行——「**如还年上吉神临，遥克凶神何必怖**」（年上神遥克凶神即为救）
 *   · 同经第 2153 行——「**日鬼为用生行年本命者，主迁官之兆**」
 *   · 《六壬大全·毕法赋》（卷十一·上）占讼条——「亦要人行年上神**不落空亡**」
 *
 * 不做的事（不臆造）：
 *   · 不给年命判打分、不把「救神」折算成「减几成凶」——原文只给定性；
 *   · 不把「年上神克日」也塞进「不及」：原文的「不及」专指**行年（支）克日上神**，两者主体不同；
 *   · 未给本命/性别/虚岁时整块不出（返回空数组），不默认任何年命。
 */

import {
  WX_NAME, GAN_WX, ZHI_WX, KE_BY, SHENG_BY, GAN_Z, ZHI_Z,
} from './tables.js';

const ganWx = (g) => {
  const i = GAN_Z.indexOf(g);
  return i < 0 ? -1 : GAN_WX[i];
};
const zhiWx = (z) => {
  const i = ZHI_Z.indexOf(z);
  return i < 0 ? -1 : ZHI_WX[i];
};
const wxName = (i) => (i >= 0 ? WX_NAME[i] : '');
const sheng = (a, b) => a >= 0 && b >= 0 && SHENG_BY[a] === b;
const ke = (a, b) => a >= 0 && b >= 0 && KE_BY[a] === b;
const keMe = (b) => (b >= 0 ? Object.keys(KE_BY).map(Number).find((k) => KE_BY[k] === b) : -1);

/**
 * 六壬「年命判」。
 * @param {object} c sixRenChart 的返回对象（需含 本命/行年/命上/年上/干支/三传/旬空/天地盘）
 * @returns {Array<{判:string, 类:string, 吉凶:string, 说明:string, 依据:string}>}
 */
export function nianMingVerdicts(c) {
  const out = [];
  if (!c || !c.行年 || !c.年上) return out;

  const 日干 = c.干支.日[0];
  const 日支 = c.干支.日[1];
  const 日干Wx = ganWx(日干);
  const 年支Wx = zhiWx(c.行年.支);
  const 年上Wx = zhiWx(c.年上);

  // 日上神：以日支为地盘位，取天盘所加
  const cell = (c.天地盘 || []).find((x) => x.地盘 === 日支);
  const 日上 = cell ? cell.天盘 : '';
  const 日上Wx = zhiWx(日上);

  // ① 不及：行年（支）克日上神
  if (ke(年支Wx, 日上Wx)) {
    out.push({
      判: '不及', 类: '年命', 吉凶: '凶',
      说明: `行年${c.行年.支}（${wxName(年支Wx)}）克日上神${日上}（${wxName(日上Wx)}），原文名曰「不及」`,
      依据: '《六壬大全·轩辕肘后经》——「行年克日为不及」',
    });
  }

  // ② 失节：日干克年上神
  if (ke(日干Wx, 年上Wx)) {
    out.push({
      判: '失节', 类: '年命', 吉凶: '凶',
      说明: `日干${日干}（${wxName(日干Wx)}）克年上神${c.年上}（${wxName(年上Wx)}），原文名曰「失节」`,
      依据: '《六壬大全·轩辕肘后经》——「日克年神失节名」',
    });
  }

  const 初 = (c.三传 || []).find((x) => x.传 === '初');
  if (初) {
    const 事Wx = zhiWx(初.支);

    // ③ 事神（初传）与年上神相生 / 相克
    if (sheng(事Wx, 年上Wx) || sheng(年上Wx, 事Wx) || (事Wx >= 0 && 事Wx === 年上Wx)) {
      out.push({
        判: '事神与年上相生', 类: '年命', 吉凶: '吉',
        说明: `事神${初.支}（${wxName(事Wx)}）与年上神${c.年上}（${wxName(年上Wx)}）相生比和，原文「所为皆得成」`,
        依据: '《六壬大全·轩辕肘后经》——「事神年上两相生，此主所为皆得成」',
      });
    } else if (ke(事Wx, 年上Wx) || ke(年上Wx, 事Wx)) {
      out.push({
        判: '事神与年上相克', 类: '年命', 吉凶: '凶',
        说明: `事神${初.支}（${wxName(事Wx)}）与年上神${c.年上}（${wxName(年上Wx)}）相克，原文「所为皆不得」`,
        依据: '《六壬大全·轩辕肘后经》——「事神年上两相克，此主所为皆不得」',
      });
    }

    const 鬼Wx = keMe(日干Wx);

    // ④ 年上遥克凶神为救：初传为日干之鬼而年上神克之
    if (事Wx >= 0 && 事Wx === 鬼Wx && ke(年上Wx, 事Wx)) {
      out.push({
        判: '年上遥克凶神', 类: '年命', 吉凶: '吉',
        说明: `初传${初.支}为日干${日干}之鬼（${wxName(鬼Wx)}），而年上神${c.年上}（${wxName(年上Wx)}）克之，原文「遥克凶神何必怖」，此即救神`,
        依据: '《六壬大全·轩辕肘后经》——「如还年上吉神临，遥克凶神何必怖」',
      });
    }

    // ⑤ 日鬼为用而生年命 → 迁官之兆
    if (事Wx >= 0 && 事Wx === 鬼Wx && sheng(事Wx, 年上Wx)) {
      out.push({
        判: '日鬼为用生年上', 类: '年命', 吉凶: '吉',
        说明: `初传${初.支}为日鬼而反生年上神${c.年上}，原文「日鬼为用生行年本命者，主迁官之兆」`,
        依据: '《六壬大全·轩辕肘后经》——「日鬼为用生行年本命者，主迁官之兆」',
      });
    }
  }

  // ⑥ 年上神落旬空
  const 空 = c.旬空 || [];
  if (c.年上 && 空.includes(c.年上)) {
    out.push({
      判: '年上落空', 类: '年命', 吉凶: '凶',
      说明: `年上神${c.年上}正落旬空（${空.join('')}），占讼求事皆不宜——原文「亦要人行年上神不落空亡」`,
      依据: '《六壬大全·毕法赋》占讼条——「亦要人行年上神不落空亡」',
    });
  }

  return out;
}
