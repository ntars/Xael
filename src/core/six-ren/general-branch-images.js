/**
 * 取某将临某支的取象。
 * @param {string} 将 天将名
 * @param {string} 支 地支字
 * @returns {{将,支,名,断}|null}
 */
export function imageOf(将, 支) {
  const row = GENERAL_BRANCH_IMAGES[将];
  if (!row || !row[支]) return null;
  return { 将, 支, 名: row[支][0], 断: row[支][1] };
}

/**
 * 按盘上三传所乘天将与其所临之支，逐位取象。
 * @param {object} c 六壬盘（需 c.三传[{支,天将}]）
 * @returns {{项:Array, 依据:string, 说明:string}|null}
 */
export function generalBranchImagesOf(c) {
  const 项 = [];
  for (const x of (c && c.三传) || []) {
    if (!x || !x.天将 || !x.支) continue;
    const im = imageOf(x.天将, x.支);
    if (!im) continue;
    项.push({ ...im, 传: x.传, 位: `第${['初', '中', '末'].indexOf(x.传) + 1}传${x.支}` });
  }
  if (!项.length) return null;
  return {
    项,
    依据: '《六壬大全·十二将释》各将「赋」及赋后释文（十二将临十二支取象）',
    说明: '取象名与断语照录底本用字；原书未给吉凶分级，故只列取象、不折轻重。',
  };
}
