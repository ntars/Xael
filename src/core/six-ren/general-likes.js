/**
 * 按盘上实际出现的天将，列出「所喜得见」「所畏同现」「临不宜之支」。
 * @param {object} c 六壬盘（需 c.三传[{支,天将}]、c.四课[{上}]、c.十二天将.将）
 * @returns {{喜:Array, 畏:Array, 不立:Array, 依据:string, 说明:string}|null}
 */
export function generalLikesOf(c) {
  const 将盘 = (c && c.十二天将 && c.十二天将.将) || {};
  // 盘上出现的天将：三传所乘 + 四课四上神所乘（同一将不重复计）
  const spots = [];
  for (const x of c.三传 || []) if (x && x.天将) spots.push({ 将: x.天将, 支: x.支, 位: `第${['初', '中', '末'].indexOf(x.传) + 1}传${x.支}` });
  for (const k of c.四课 || []) if (k && k.上 && 将盘[k.上]) spots.push({ 将: 将盘[k.上], 支: k.上, 位: `第${k.课}课上${k.上}` });
  if (!spots.length) return null;
  const names = [...new Set(spots.map((s) => s.将))];

  const 喜 = [];
  const 畏 = [];
  const 不立 = [];
  for (const self of names) {
    const row = GENERAL_LIKES[self];
    if (!row) continue;                       // 白虎不在表内
    const meets = row.爱.filter((x) => names.includes(x));
    if (meets.length) {
      喜.push({ 将: self, 见: meets, 位: spots.filter((s) => s.将 === self).map((s) => s.位) });
    }
    const foes = row.畏.filter((x) => names.includes(x));
    if (foes.length) {
      畏.push({ 将: self, 见: foes, 位: spots.filter((s) => s.将 === self).map((s) => s.位) });
    }
    // 「不立某支」按将该将所临之支（三传的支；四课上神即是其所临之支）判
    for (const s of spots.filter((x) => x.将 === self)) {
      if (row.不立.includes(s.支)) 不立.push({ 将: self, 支: s.支, 位: s.位, 备注: row.备注 });
    }
  }
  if (!喜.length && !畏.length && !不立.length) return null;
  return {
    喜, 畏, 不立,
    依据: '《六壬大全·十二将释》各将「论」段末句（爱某将、畏某将、不立某支）',
    说明: '原文只给「爱／畏」的取舍倾向，未给轻重分数，故本项只列实际同现者，不折算吉凶；'
      + '白虎在此书无爱畏之句，不列。',
  };
}
