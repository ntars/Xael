/**
 * src/core/six-ren/general-likes.js —— 大六壬·十二天将的「所喜所畏」
 *
 * 大白话：每个天将都有它爱见的将、怕见的将，还有它不宜临的支位。这是原书
 *   《六壬大全·十二将释》每将「论」段末尾一句给的（「爱龙常合」「畏蛇空」），
 *   不是后人归纳。本模块把这一句做成表，再按盘上实际出现的天将给提示。
 *
 * 文献出处：refs-texts/《六壬大全》-明·佚名（四库本）.md「十二将释」（第 1745–2010 行）
 *   · 贵人：「爱龙常合，不立魁罡。在卯酉为关，子午为格」
 *   · 螣蛇：「爱阴、虎、龙、玄、后，畏戍」
 *   · 朱雀：「爱虎、阴，畏后、空，不立亥、子、戍」
 *   · 六合：「爱龙、常，畏后、阴、虎、空，不利四仲」
 *   · 勾陈：「爱玄、空，畏龙、后，不立四孟」
 *   · 青龙：「畏阴、虎，爱、后、合，不立申酉」
 *   · 天空：「爱元、后，畏龙、合、阴、雀，不立四孟」
 *   · 太常：「爱贵、合、后，畏蛇、空」
 *   · 玄武：「爱龙、蛇、雀，畏空、勾，恶立魁罡」
 *   · 太阴：「爱龙、常、后，畏雀、蛇、空，不立夘、午、子」
 *   · 天后：「爱龙、常、贵、合，畏勾、空土神，不立四季」
 *
 * ★ 白虎没有这一句：原书白虎「论」段只给性情、所主与占病、占官之用（「最爱虎空，附德神者吉」
 *   是占病语，不是将性爱畏），故本表不收白虎，不替它编一套。
 * ★ 「不立某支」「为关为格」原书只作提示语，未给吉凶轻重，本模块只照录、不折算成吉凶。
 */

