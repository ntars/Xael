/**
 * src/core/six-ren/heavenly-generals.js —— 大六壬天将布法（自研，零依赖）
 *
 * 大白话：十二天将（贵人、螣蛇、朱雀……）围着天盘排布。
 * 贵人按日干+昼夜定（干合推贵，见 NOBLEMAN 注释）；贵人落位后，
 * 临亥子丑寅卯辰顺布、临巳午未申酉戌逆布。
 */

/**
 * 天将序（自贵人起顺数）。
 * 《六壬大全·卷一·十二将释》：「天乙居中，后六前五」——即贵人为中，其后（逆数）六将，
 * 其前（顺数）五将；十二将自贵人起顺布为：贵人、螣蛇、朱雀、六合、勾陈、青龙、
 * 天空、白虎、太常、玄武、太阴、天后。本表与之逐位一致。
 */
export const JIANG = ['贵人', '螣蛇', '朱雀', '六合', '勾陈', '青龙', '天空', '白虎', '太常', '玄武', '太阴', '天后'];

/**
 * 天乙贵人：按「干合推贵」立表（官修派）。
 *
 * 依据：《钦定协纪辨方书》卷首引库外《蠡海集》——
 *   「阳贵起于子而顺，阴贵起于申而逆」，阳贵「以甲加子，甲与己合，所以己用子为贵人」……
 *   推出阳贵（昼贵）：甲未、乙申、丙酉、丁亥、戊丑、己子、庚丑、辛寅、壬卯、癸巳；
 *   阴贵（夜贵）逆取：甲丑、乙子、丙亥、丁酉、戊未、己申、庚未、辛午、壬巳、癸卯。
 * 《六壬大全》四库提要（卷一前列）说得最明白，且给出两处先秦古占佐证：
 *   ①「先天之徳起于子，后天之德起于未，以五干徳合神取贵」；
 *   ②「我圣祖仁皇帝库外《御定星历考原》一书……以订曹震圭昼丑夜未之讹，实足立千古之标凖」；
 *   ③「谨按库外《呉越春秋》所载子胥之占，三月甲戌，时加鸡鸣，而以为青龙在酉，是**甲日丑为阴贵**也；
 *      范蠡石室之占，十二月戊寅，时加日出，而亦以为青龙临酉、功曹为螣蛇，是**戊日丑为阳贵**也」；
 *   ④ 提要并直指本书正文之失：「**是书所取天乙尚沿俗例**，卷中仅载先天贵人一图而不用，
 *      未免失之舛漏」——即四库馆臣认为正文用俗诀是错的，以官修派为准。
 *   本模块从提要所主（官修派），正文「贵人歌」一章的俗诀只作对照记录。
 *
 * 派别说明（不合并，如实标注）：通书通行诀「甲戊庚牛羊／乙己鼠猴乡／丙丁猪鸡位／
 *   壬癸兔蛇藏／六辛逢马虎」在甲、庚、辛、壬、癸五干上与官修派昼夜互换，
 *   遇此五干若按通行诀起贵，天将整盘顺逆会反——这是六壬最容易出错的一步。
 */
// ★ 顺序是 [昼贵, 夜贵]（支序：子0 丑1 寅2 卯3 辰4 巳5 午6 未7 申8 酉9 戌10 亥11）
const NOBLEMAN = {
  甲: [7, 1], 乙: [8, 0], 丙: [9, 11], 丁: [11, 9], 戊: [1, 7],
  己: [0, 8], 庚: [1, 7], 辛: [2, 6], 壬: [3, 5], 癸: [5, 3],
};

/*
 * 贵人落辰戌的换神（已并入）：《六壬大全·卷一·十二将释》——
 *   「贵人独不居辰、戌之地，以辰为宰杀、戌为牢狱也」；
 *   「贵人临辰戌者，以冲为神：临辰冲申，临戌冲寅，乃天乙所临之位，诸将并随天乙顺逆、前后取之」。
 *   故贵人落辰（4）以申（8）为神、落戌（10）以寅（2）为神，再按该位判顺逆与前后。
 *   《六壬大全·卷一·十二将释》另录「太乙起子逆后寻」一法（「贵人若临辰戌上者，则巳上起子、辰上起丑……」），
 *   与「以冲为神」是两种细节，本实现取前者（以冲为神），后者仅记录不并用。
 */

/**
 * 取贵人支序。
 * @param {String} dayGan 日干
 * @param {Boolean} isNight 夜占（酉~寅时）
 */
export function guirenIdx(dayGan, isNight) {
  const t = NOBLEMAN[dayGan];
  return isNight ? t[1] : t[0];
}

/**
 * 贵人落辰戌时以冲为神：辰→申(8)、戌→寅(2)，其余原位。
 * 注：官修派贵表按「干合推贵」生成，十干昼夜二十个取位中本就不含辰(4)、戌(10)
 * （即原文所谓「贵人独不居辰戌之地」），故本函数是防御性兜底；
 * 若将来改用别的贵表落到辰戌，天将顺逆才不会排反。
 */
export function nobleSeat(guiZhi) {
  if (guiZhi === 4) return 8;   // 临辰冲申
  if (guiZhi === 10) return 2;  // 临戌冲寅
  return guiZhi;
}

/** 取昼贵、夜贵两支序（供毕法「两贵」类判定用） */
export function guirenBoth(dayGan) {
  const t = NOBLEMAN[dayGan];
  return t ? { 昼: t[0], 夜: t[1] } : null;
}

/**
 * 布十二天将：返回 {天盘神支序 → 天将名}。
 * 顺逆按「以冲为神」后的天乙位判：临亥子丑寅卯辰(11,0..4)顺布，临巳午未申酉戌逆布。
 */
export function placeHeavenlyGenerals(guiZhi) {
  // 「以冲为神」后，天乙所临之位即其冲位，诸将从该位顺逆排布
  const seat = nobleSeat(guiZhi);
  const shun = [11, 0, 1, 2, 3, 4].includes(seat);
  const out = {};
  for (let i = 0; i < 12; i++) {
    const pos = shun ? (seat + i) % 12 : ((seat - i) % 12 + 12) % 12;
    out[pos] = JIANG[i];
  }
  return out;
}
