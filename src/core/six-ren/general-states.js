const WX = ['木', '火', '土', '金', '水'];
const SHENG = { 木: '火', 火: '土', 土: '金', 金: '水', 水: '木' };
const KE = { 木: '土', 土: '水', 水: '火', 火: '金', 金: '木' };

/**
 * 月建所属季节的旺相死囚休：
 *   旺＝当令；相＝旺者所生；休＝生旺者；囚＝克旺者；死＝旺者所克。
 * 对照《六壬大全·十二将释》例：春木旺、火相、水休、金囚、土死。
 */
export function seasonStateOf(月支序) {
  // 寅卯辰春(木旺)、巳午未夏(火旺)、申酉戌秋(金旺)、亥子丑冬(水旺)；
  // 辰戌丑未为四季土旺之月，但原文以春/夏/秋/冬四时为纲，故仍按四时分。
  const z = ((月支序 % 12) + 12) % 12;
  const 旺 = z >= 2 && z <= 4 ? '木' : z >= 5 && z <= 7 ? '火' : z >= 8 && z <= 10 ? '金' : '水';
  const state = {};
  state[旺] = '旺';
  state[SHENG[旺]] = '相';
  for (const k of WX) if (SHENG[k] === 旺) state[k] = '休';
  for (const k of WX) if (KE[k] === 旺) state[k] = '囚';
  state[KE[旺]] = '死';
  return { 旺五行: 旺, 态: state };
}

/**
 * 按盘上三传所乘天将，给每将的当月状态与所主。
 * @param {object} c 六壬盘（需 c.三传[{支,天将}]、c.月建或由入参推）
 * @param {number} 月支序 0=子 … 11=亥
 */
export function generalStatesOf(c, 月支序) {
  const { 旺五行, 态 } = seasonStateOf(月支序);
  const seen = [];
  for (const x of (c && c.三传) || []) {
    if (!x || !x.天将 || seen.some((s) => s.将 === x.天将)) continue;
    const 将 = x.天将;
    const wx = JIANG_WX[将];
    const st = 态[wx] || '';
    const row = JIANG_STATE[将];
    let 所主 = '';
    let 分法 = '五态';
    if (row) {
      所主 = row[st] || '';
    } else if (JIANG_TWO_WAY[将]) {
      分法 = '两分（原书只有诗诀两句）';
      所主 = st === '旺' || st === '相' ? JIANG_TWO_WAY[将].有气 : JIANG_TWO_WAY[将].死囚;
    }
    seen.push({ 将, 五行: wx, 态: st, 分法, 所主, 位: `第${['初', '中', '末'].indexOf(x.传) + 1}传${x.支}` });
  }
  if (!seen.length) return null;
  return {
    月令旺五行: 旺五行,
    将: seen,
    依据: '《六壬大全·十二将释》各将「论」段末句（旺相死囚休五态所主）；将之五行取各将本命干支',
    说明: '旺相死囚休按月建四时定（春木旺、火相、水休、金囚、土死，余季同例）；原文只给所主事项、未给轻重分数，故只列所主不折吉凶。',
  };
}
