/** 旬空：六甲旬首后两位 */
const XUNKONG = {
  甲子: ['戌', '亥'], 甲戌: ['申', '酉'], 甲申: ['午', '未'],
  甲午: ['辰', '巳'], 甲辰: ['寅', '卯'], 甲寅: ['子', '丑'],
};
/** 由日干支（'甲子'）求旬空两支 */
export function xunKongOf(日干支) {
  if (!日干支 || 日干支.length !== 2) return [];
  const gan = '甲乙丙丁戊己庚辛壬癸';
  const zhi = ZHI_Z;
  const gi = gan.indexOf(日干支.charAt(0));
  const zi = zhi.indexOf(日干支.charAt(1));
  if (gi < 0 || zi < 0) return [];
  // 逆推回本旬的甲某日
  const back = gi;
  const xunZhi = zhi[((zi - back) % 12 + 12) % 12];
  return XUNKONG[`甲${xunZhi}`] || [];
}

