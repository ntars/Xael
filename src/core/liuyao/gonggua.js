/**
 * src/core/liuyao/gonggua.js —— 八宫卦序（京房八宫六十四卦）（自研，零依赖）
 *
 * 大白话：六十四卦按京房分入八个「宫」，每宫以一个纯卦（八纯卦）为首，
 * 按一世～五世、游魂、归魂变出八个卦。每卦记录：卦名、宫、世爻位、应爻位。
 * 爻的阴阳用二进制表示（1=阳爻、0=阴爻，初爻为最低位）。
 *
 * 口径：八宫顺序 乾坎艮震巽离坤兑；每宫八卦次序
 *   本宫(世6) 一世(1) 二世(2) 三世(3) 四世(4) 五世(5) 游魂(4) 归魂(3)，应爻=世±3。
 */

/** 八纯卦（爻象：自初爻到上爻，1=阳；先天卦画自下而上）
 *  乾☰111 兑☱110 离☲101 震☳100 巽☴011 坎☵010 艮☶001 坤☷000 */
export const PURE = {
  乾: [1, 1, 1, 1, 1, 1],
  坎: [0, 1, 0, 0, 1, 0],
  艮: [0, 0, 1, 0, 0, 1],
  震: [1, 0, 0, 1, 0, 0],
  巽: [0, 1, 1, 0, 1, 1],
  离: [1, 0, 1, 1, 0, 1],
  坤: [0, 0, 0, 0, 0, 0],
  兑: [1, 1, 0, 1, 1, 0],
};

/** 爻象转键（上卦名+下卦名 需要卦名表）——这里直接用 八宫序生成全部 64 卦 */
export const GONG_ORDER = ['乾', '坎', '艮', '震', '巽', '离', '坤', '兑'];

/** 八宫五行：乾金 坎水 艮土 震木 巽木 离火 坤土 兑金 */
export const GONG_WX = { 乾: '金', 坎: '水', 艮: '土', 震: '木', 巽: '木', 离: '火', 坤: '土', 兑: '金' };

/**
 * 由本宫爻象按变爻规则生成一宫八卦。
 * 变法：一世=初爻变、二世=二爻变……五世=五爻变；游魂=五世卦四爻变；归魂=游魂卦内卦复原为本宫内卦。
 */
function deriveGong(gongName) {
  const base = PURE[gongName];
  const flip = (arr, i) => arr.map((v, j) => (j === i ? 1 - v : v));
  const yi = flip(base, 0);
  const er = flip(yi, 1);
  const san = flip(er, 2);
  const si = flip(san, 3);
  const wu = flip(si, 4);
  const youHun = flip(wu, 3); // 游魂：四爻复变
  const guiHun = [...base.slice(0, 3), ...youHun.slice(3)]; // 归魂：内卦复原为本宫内卦
  return [
    { 爻: base, 世: 5 }, { 爻: yi, 世: 0 }, { 爻: er, 世: 1 }, { 爻: san, 世: 2 },
    { 爻: si, 世: 3 }, { 爻: wu, 世: 4 }, { 爻: youHun, 世: 3 }, { 爻: guiHun, 世: 2 },
  ].map((x, i) => ({ 宫: gongName, 序: i, 爻: x.爻, 世: x.世, 应: (x.世 + 3) % 6, 宫序: i === 0 ? '本宫' : ['一世', '二世', '三世', '四世', '五世', '游魂', '归魂'][i - 1] }));
}

/** 全部 64 卦（键=上卦+下卦：上下卦由爻象拆出——上卦=爻[3..5]、下卦=爻[0..2]，经 TRIGRAM 反查） */
export const TRIGRAM = {
  '111': '乾', '010': '坎', '001': '艮', '100': '震',
  '011': '巽', '101': '离', '000': '坤', '110': '兑',
};

function trigramOf(bits) { return TRIGRAM[bits.join('')]; }

/** 64 卦全表：键 = 上卦名 + 下卦名（如 天风姤 键=姤？——用「上卦+下卦」键：姤=乾上巽下→'乾巽'） */
export const GUA64 = {};
for (const gong of GONG_ORDER) {
  for (const g of deriveGong(gong)) {
    const upper = trigramOf(g.爻.slice(3));
    const lower = trigramOf(g.爻.slice(0, 3));
    const key = upper + lower;
    GUA64[key] = { ...g, 键: key, 上卦: upper, 下卦: lower };
  }
}

/** 按爻象查卦 */
export function guaByBits(bits) {
  const key = trigramOf(bits.slice(3)) + trigramOf(bits.slice(0, 3));
  return GUA64[key] || null;
}

