/**
 * src/core/liuyao/wangshuai.js —— 六爻·旺衰进阶与分门断语（自研，零依赖）
 *
 * 大白话：装卦只是把卦摆出来，断卦要看每一爻「旺不旺」。这一层做七件事：
 *   ① 生旺墓绝（长生/帝旺/墓/绝）② 月建日辰旺衰档 ③ 日冲 → 暗动 / 日破 / 冲散
 *   ④ 动爻化变（回头生克 / 化进神退神 / 化墓化绝 / 化空化破 / 伏吟反吟）
 *   ⑤ 三合局成局与虚一待用 ⑥ 六冲卦·六合卦·游魂归魂 ⑦ 用神·原神·忌神·仇神定位
 *   再加一层「分门断语」（《黄金策》用神生克体系的形式化）。
 *
 * 依据：
 *   · 生旺墓绝——《卜筮正宗·生旺墓绝章》：金长生巳旺酉墓丑绝寅；木长生亥旺卯墓未绝申；
 *     火长生寅旺午墓戌绝亥；水、土长生申旺子墓辰绝巳。
 *     觉醒子原注三条例外（本模块内建）：金虽长生在巳须旺相方论生；金虽墓于丑得未冲或土多则论生；
 *     土绝于巳须休囚方论绝。
 *     流派差异（不合并、如实标注）：土之长生另有「寅」说（《易冒》），本模块取申。
 *   · 月建日辰——《增删卜易·月建章/日辰章》：月建司一月之权为提纲，日辰司一日之权为主宰。
 *     月建冲爻为月破；日辰冲爻，旺相为暗动、休囚为日破。
 *     流派差异：月建冲「临日辰」之静爻，一派作暗动（本模块择此并标注）。
 *   · 旺衰档——《增删卜易》日月权衡表，只出定性档位，不打分。
 *   · 进退神——《卜筮正宗·进退神论》7 组：进 亥→子/寅→卯/巳→午/申→酉/丑→辰/辰→未/未→戌；
 *     退为反向。戌化丑另有流派作进神，单列提示不并入主判。
 *   · 三合局——《卜筮正宗·三合章》：申子辰水、寅午戌火、亥卯未木、巳酉丑金。
 *     成局四法：三爻齐动 / 两爻动连变爻 / 两爻动日月凑 / 中神动日月凑；两爻动而日月无第三支为「虚一待用」。
 *   · 反吟伏吟——《卜筮正宗·反吟伏吟论》：卦之反吟乾↔巽、坎↔离、震↔兑、坤↔艮；爻之反吟为动变六冲；
 *     卦之伏吟为变卦与本卦同支；爻之伏吟为动爻化同支。
 *   · 六冲卦十、六合卦八为占筮通用定论。
 *   · 六亲生克链（京房纳甲）：原神=生用神者，忌神=克用神者，仇神=克原神者。
 */

