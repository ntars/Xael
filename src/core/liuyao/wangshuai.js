/* ============================== ①② 月建 / 日辰关系 ============================== */
export function 月关系(爻支, 爻五行, 月支) {
  if (!月支) return { 类: '未定', 分: 0, 说明: '未给月建，旺衰未定。' };
  const 月Wx = ZHI_WX[月支];
  if (爻支 === 月支) return { 类: '临月建', 分: 2, 说明: '爻支与月建同支，得月建之权，一月内最旺。' };
  if (支冲(爻支, 月支)) return { 类: '月破', 分: -2, 说明: '月建冲爻为月破；出月、逢合、值日可解。' };
  if (SHENG[月Wx] === 爻五行) return { 类: '月生', 分: 1.2, 说明: '月建五行生爻，得生为旺相。' };
  if (月Wx === 爻五行) return { 类: '月扶', 分: 1.2, 说明: '月建与爻同五行，得扶为旺相。' };
  if (SHENG[爻五行] === 月Wx) return { 类: '月泄', 分: -0.6, 说明: '爻生月建，泄气，力减。' };
  if (KE[爻五行] === 月Wx) return { 类: '月耗', 分: -0.6, 说明: '爻克月建，耗力，力减。' };
  if (KE[月Wx] === 爻五行) return { 类: '月克', 分: -1.2, 说明: '月建克爻，休囚无根。' };
  return { 类: '未定', 分: 0, 说明: '' };
}

export function 日关系(爻支, 爻五行, 日支) {
  if (!日支) return { 类: '未定', 分: 0, 说明: '未给日辰，旺衰未定。' };
  const 日Wx = ZHI_WX[日支];
  if (爻支 === 日支) return { 类: '临日辰', 分: 2, 说明: '爻支与日辰同支，得日辰之权，当日最旺。' };
  if (支冲(爻支, 日支)) return { 类: '日冲', 分: 0, 说明: '日辰冲爻：旺相为暗动，休囚为日破（见下判定）。' };
  if (SHENG[日Wx] === 爻五行) return { 类: '日生', 分: 1.2, 说明: '日辰生爻，有气得力。' };
  if (日Wx === 爻五行) return { 类: '日扶', 分: 1.2, 说明: '日辰与爻同五行，得扶得力。' };
  if (SHENG[爻五行] === 日Wx) return { 类: '日泄', 分: -0.6, 说明: '爻生日辰，泄气。' };
  if (KE[爻五行] === 日Wx) return { 类: '日耗', 分: -0.6, 说明: '爻克日辰，耗力。' };
  if (KE[日Wx] === 爻五行) return { 类: '日克', 分: -1.2, 说明: '日辰克爻，受损。' };
  return { 类: '未定', 分: 0, 说明: '' };
}

/** ③ 旺衰档（《增删卜易》日月权衡表直接落地，只出定性档位） */
export function 旺衰档(月类, 日类) {
  if (月类 === '月破' && (日类 === '日克' || 日类 === '日耗' || 日类 === '日泄')) return '衰败已极';
  if (月类 === '月破' && 日类 === '临日辰') return '月破反作暗动（值日不破）';
  if (月类 === '月破') return '月破失力';
  if (月类 === '月克' && 日类 === '日克') return '休囚无救';
  if (月类 === '月克' && (日类 === '日生' || 日类 === '日扶' || 日类 === '临日辰')) return '休囚有气（有救）';
  if (月类 === '临月建' && 日类 === '临日辰') return '旺上加旺';
  if (月类 === '临月建' && (日类 === '日生' || 日类 === '日扶')) return '旺（有根有力）';
  if ((月类 === '月生' || 月类 === '月扶') && 日类 === '临日辰') return '得时得地';
  if (月类 === '临月建') return '旺（有根）';
  if (月类 === '月生' || 月类 === '月扶') return '相（有气）';
  if (日类 === '临日辰' || 日类 === '日生' || 日类 === '日扶') return '平（得日辰之助）';
  if (月类 === '未定' && 日类 === '未定') return '未定';
  return '休囚（无根无助）';
}

/** 档位 → 强弱分档（定性，不打分） */
export function 档强弱(档) {
  if (/旺上加旺|有根有力|得时得地/.test(档)) return '旺';
  if (/旺（有根）|相（有气）/.test(档)) return '相';
  if (/平（/.test(档)) return '平';
  if (/休囚有气/.test(档)) return '弱有救';
  if (/休囚无救|无根无助|月破失力|衰败已极/.test(档)) return '衰';
  if (/冲散|日破/.test(档)) return '衰';
  if (/暗动/.test(档)) return '暗动（力增）';
  return '未定';
}

/* ============================== ④ 动爻化变 ============================== */
export function 变爻关系(本支, 变支, 月支, 日支, 空亡) {
  if (!变支) return null;
  const 本Wx = ZHI_WX[本支]; const 变Wx = ZHI_WX[变支];
  const S = SHENG12[本Wx] || null;
  const tags = [];

  // 4.1 爻之伏吟 / 爻之反吟（地支层面，最优先取象）
  if (变支 === 本支) {
    tags.push({ 名: '伏吟', 级: '凶', 断: '动爻化出同支，为爻之伏吟：主呻吟迟滞、事多反复、进退两难。' });
  } else if (支冲(本支, 变支)) {
    tags.push({ 名: '反吟', 级: '凶', 断: '动爻化出冲支，为爻之反吟：主反复不安、成而复败、去而复返。' });
  }

  // 4.2 化墓 / 化绝 / 化长生 / 化帝旺（象层；墓绝须兼看旺衰）
  if (S) {
    if (变支 === S.墓) tags.push({ 名: '化墓', 级: '凶', 断: `动爻化入本五行之墓（${本Wx}墓在${S.墓}）：主困住难出、事入坟墓之象。`, 注: '觉子原注：爻旺相得生扶或墓支被冲，则论生不论墓。' });
    else if (变支 === S.绝) tags.push({ 名: '化绝', 级: '凶', 断: `动爻化入本五行之绝（${本Wx}绝在${S.绝}）：主气尽势终。`, 注: '觉子原注：土绝于巳须休囚方论绝，旺相则巳火反生土，论生不论绝。' });
    else if (变支 === S.长生) tags.push({ 名: '化长生', 级: '吉', 断: `动爻化出本五行长生（${本Wx}长生在${S.长生}）：主生机渐长。` });
    else if (变支 === S.帝旺) tags.push({ 名: '化帝旺', 级: '吉', 断: `动爻化出本五行帝旺（${本Wx}旺在${S.帝旺}）：主势力到顶。` });
  }

  // 4.3 进神 / 退神
  if (JIN[本支] === 变支) tags.push({ 名: '化进神', 级: '吉', 断: `动爻化进神（${本支}→${变支}）：势增，吉事倍增其势，凶事亦加其凶。` });
  if (TUI[本支] === 变支) tags.push({ 名: '化退神', 级: '凶', 断: `动爻化退神（${本支}→${变支}）：势减，吉凶皆渐减其威，虎头蛇尾。` });
  if (本支 === '戌' && 变支 === '丑') tags.push({ 名: '戌化丑（流派进神）', 级: '？', 断: '戌化丑：部分书作「土气一周复始」之进神，《卜筮正宗》原文未列，本功能单列提示，不并入主判。' });

  // 4.4 生克（力层，与象层并行给出）
  if (SHENG[变Wx] === 本Wx) tags.push({ 名: '回头生', 级: '吉', 断: '变爻五行生本爻：回头生，得后续支援，谋事易成。' });
  else if (KE[变Wx] === 本Wx) tags.push({ 名: '回头克', 级: '凶', 断: '变爻五行克本爻：回头克，半路折损，功败垂成。野鹤云「不论用神衰旺，皆以凶推」。' });
  else if (SHENG[本Wx] === 变Wx) tags.push({ 名: '化泄', 级: '平', 断: '本爻生变爻：我去生他，泄气，力减而不凶。' });
  else if (KE[本Wx] === 变Wx) tags.push({ 名: '化耗', 级: '平', 断: '本爻克变爻：我去克他，耗力，不为凶。' });
  else tags.push({ 名: '化比和', 级: '平', 断: '本爻与变爻同五行：比和，力持平。' });

  // 4.5 化空 / 化破
  if (空亡 && 空亡.length && 空亡.indexOf(变支) >= 0) tags.push({ 名: '化空', 级: '凶', 断: '变爻落旬空：有动作无结果，待出旬填实方应。' });
  if (月支 && 支冲(变支, 月支)) tags.push({ 名: '化破', 级: '凶', 断: '变爻被月建冲：化破，变化落空，出月方应。' });

  // 4.6 化刑
  if (支刑(本支, 变支)) tags.push({ 名: '化刑', 级: '凶', 断: '变爻与本爻相刑：主纠缠刑伤、事多枝节。' });

  // 主判：凶象优先（回头克 > 化墓化绝 > 反吟伏吟 > 化破化空 > 化刑 > 退神），吉象次之
  const 序 = { 回头克: 1, 化墓: 2, 化绝: 2, 反吟: 3, 伏吟: 3, 化破: 4, 化空: 4, 化刑: 5, 化退神: 6, 化长生: 7, 回头生: 8, 化进神: 9, 化帝旺: 10 };
  let 主 = null;
  tags.forEach((t) => { const n = 序[t.名] || 99; if (!主 || n < (序[主.名] || 99)) 主 = t; });
  return { 本支, 变支, 本五行: 本Wx, 变五行: 变Wx, 项: tags, 主判: 主 };
}

/* ============================== ⑤ 三合局 ============================== */
/**
 * 成局四法：三爻齐动 / 两爻动连变爻 / 两爻动＋日月凑 / 中神动＋日月凑。
 * 两爻动而日月又无第三支 → 不成局，为「虚一待用」。
 * @param 动 [{爻, 本支, 变支}]
 */
export function 三合局(动, 月支, 日支, 空亡) {
  const pool = [];
  (动 || []).forEach((d) => {
    if (d.本支) pool.push({ 支: d.本支, 源: `第${d.爻}爻动`, 动: true });
    if (d.变支) pool.push({ 支: d.变支, 源: `第${d.爻}爻变`, 动: true });
  });
  if (月支) pool.push({ 支: 月支, 源: '月建', 动: false });
  if (日支) pool.push({ 支: 日支, 源: '日辰', 动: false });

  const out = [];
  SAN_HE.forEach((g) => {
    const hit = [];
    g.支.forEach((z) => {
      const f = pool.filter((p) => p.支 === z)[0];
      if (f) hit.push(f);
    });
    const 动数 = hit.filter((h) => h.动).length;
    if (hit.length === 3 && 动数 >= 1) {
      const 空 = hit.filter((h) => 空亡 && 空亡.indexOf(h.支) >= 0);
      out.push({
        局: `${g.局}局`, 支: g.支.join(''), 中神: g.中神,
        来源: hit.map((h) => `${h.支}（${h.源}）`).join(' + '),
        成立: true,
        缺: '', 空破: 空.map((h) => h.支),
        说明: `三合${g.局}局成（${g.支.join('')}，中神${g.中神}）。`
          + (空.length ? `局中${空.map((h) => h.支).join('、')}旬空，待填实之日成局。` : ''),
      });
    } else if (hit.length === 2 && 动数 >= 2) {
      const 缺 = g.支.filter((z) => !pool.some((p) => p.支 === z))[0];
      out.push({
        局: `${g.局}局`, 支: g.支.join(''), 中神: g.中神,
        来源: hit.map((h) => `${h.支}（${h.源}）`).join(' + '),
        成立: false, 缺, 空破: [],
        说明: `两爻动而缺「${缺}」，不成局，为「虚一待用」；待${缺}日月补凑方成。`,
      });
    }
  });
  return out;
}

