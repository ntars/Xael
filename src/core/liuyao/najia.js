/**
 * src/core/liuyao/najia.js —— 京房纳甲与六亲六神（自研，零依赖）
 *
 * 大白话：六爻要把八卦的六个爻配上干支（纳甲）、再以本宫五行定「六亲」
 * （父母/兄弟/子孙/妻财/官鬼），并按日干排「六神」（青龙……玄武）。
 *
 * 口径（京房纳甲，内卦三爻/外卦三爻）：
 *   乾 内甲子甲寅甲辰 外壬午壬申壬戌；坤 内乙未乙巳乙卯 外壬子壬寅壬辰（内外逆）
 *   震 内庚子庚寅庚辰 外庚午庚申庚戌；巽 内辛丑辛亥辛酉 外辛未辛巳辛卯
 *   坎 内戊寅戊辰戊午 外戊申戊戌戊子；离 内己卯己丑己亥 外己酉己未己巳
 *   艮 内丙辰丙午丙申 外丙戌丙子丙寅；兑 内丁巳丁卯丁丑 外丁亥丁酉丁未
 * 六亲：以卦宫五行为「我」——生我父母/我生子孙/克我官鬼/我克妻财/同我兄弟。
 * 六神：甲乙起青龙、丙丁朱雀、戊勾陈、己螣蛇、庚辛白虎、壬癸玄武，自初爻顺排。
 */

import { ZHI } from '../common/constants.js';

/** 纳甲表：[内卦三爻干支, 外卦三爻干支]（自初爻起） */
const NAJIA = {
  乾: [['甲子', '甲寅', '甲辰'], ['壬午', '壬申', '壬戌']],
  坤: [['乙未', '乙巳', '乙卯'], ['壬子', '壬寅', '壬辰']],
  震: [['庚子', '庚寅', '庚辰'], ['庚午', '庚申', '庚戌']],
  巽: [['辛丑', '辛亥', '辛酉'], ['辛未', '辛巳', '辛卯']],
  坎: [['戊寅', '戊辰', '戊午'], ['戊申', '戊戌', '戊子']],
  离: [['己卯', '己丑', '己亥'], ['己酉', '己未', '己巳']],
  艮: [['丙辰', '丙午', '丙申'], ['丙戌', '丙子', '丙寅']],
  兑: [['丁巳', '丁卯', '丁丑'], ['丁亥', '丁酉', '丁未']],
};

/** 干支五行 */
const GAN_WX = { 甲: '木', 乙: '木', 丙: '火', 丁: '火', 戊: '土', 己: '土', 庚: '金', 辛: '金', 壬: '水', 癸: '水' };
const ZHI_WX = { 子: '水', 丑: '土', 寅: '木', 卯: '木', 辰: '土', 巳: '火', 午: '火', 未: '土', 申: '金', 酉: '金', 戌: '土', 亥: '水' };
const ZHI_WU = { 子: '水', 寅: '木', 卯: '木', 巳: '火', 午: '火', 申: '金', 酉: '金', 辰: '土', 戌: '土', 丑: '土', 未: '土', 亥: '水' };

/** 六亲推导 */
function liuQin(gongWX, zhiWX) {
  const SHENG = { 木: '火', 火: '土', 土: '金', 金: '水', 水: '木' };
  const KE = { 木: '土', 土: '水', 水: '火', 火: '金', 金: '木' };
  if (gongWX === zhiWX) return '兄弟';
  if (SHENG[gongWX] === zhiWX) return '子孙';
  if (SHENG[zhiWX] === gongWX) return '父母';
  if (KE[gongWX] === zhiWX) return '妻财';
  if (KE[zhiWX] === gongWX) return '官鬼';
  return '';
}

/** 六神起位：日干 → 初爻神 */
const LIUSHEN_START = { 甲: '青龙', 乙: '青龙', 丙: '朱雀', 丁: '朱雀', 戊: '勾陈', 己: '螣蛇', 庚: '白虎', 辛: '白虎', 壬: '玄武', 癸: '玄武' };
const LIUSHEN_SEQ = ['青龙', '朱雀', '勾陈', '螣蛇', '白虎', '玄武'];

/**
 * 卦装纳甲：给定卦（含宫、爻象），返回六爻数组。
 * @param {Object} gua gonggua.js 的卦对象（含 宫/爻/世/应）
 * @param {String} dayGan 日干（排六神）
 */
export function zhuangGua(gua, dayGan) {
  // 纳甲按「下卦」取内三爻、「上卦」取外三爻
  const inner = NAJIA[gua.下卦][0];
  const outer = NAJIA[gua.上卦][1];
  const gongWX = { 乾: '金', 坎: '水', 艮: '土', 震: '木', 巽: '木', 离: '火', 坤: '土', 兑: '金' }[gua.宫];
  const start = LIUSHEN_START[dayGan];
  const startIdx = LIUSHEN_SEQ.indexOf(start);
  const rows = [];
  for (let i = 0; i < 6; i++) {
    const gz = i < 3 ? inner[i] : outer[i - 3];
    const zhi = gz[1];
    rows.push({
      位: i + 1,
      阴阳: gua.爻[i] === 1 ? '阳' : '阴',
      纳甲: gz,
      六亲: liuQin(gongWX, ZHI_WU[zhi]),
      六神: LIUSHEN_SEQ[(startIdx + i) % 6],
      世应: i === gua.世 ? '世' : i === gua.应 ? '应' : '',
    });
  }
  return { 卦名: gua.象名 || '', 宫: gua.宫, 五行: gongWX, 爻: rows };
}

function trigramKey(gua) { return gua.上卦 + gua.下卦; }
