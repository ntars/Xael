/**
 * src/core/four-pillars/patterns.js —— 八字格局·喜用神（自研，零依赖）
 *
 * 大白话：格局是给八字「定主调」——月令（出生月的地支）里藏着哪几个天干，
 * 哪一个透到了天干上，就以它为格；再据此判断成格条件、破格之忌，配合调候与
 * 通关给出喜用神。本模块只做结构化判定，不作吉凶断语。
 *
 * 取格口径（《子平真诠》「八字用神，专求月令」）：
 *   ① 月令本气透干 → 取该十神为格（正官格、偏财格…）；
 *   ② 本气未透而所藏中气/余气透干 → 取透出者；
 *   ③ 藏干皆不透 → 取月令本气十神为格（标注「不透」）；
 *   ④ 比劫不取格：本气为比劫时，月令是日主禄位 → 建禄格；是阳干帝旺 → 阳刃格、
 *      是阴干帝旺 → 月劫格；否则继续看中气余气，仍无则归外格。
 *
 * 旺衰口径（三要素定性，不打分；详见 wangShuai 段内注释与 docs/CALIBER-NOTES.md）：
 *   得令 = 日主五行在月令的旺相休囚死属「旺」或「相」（《三命通会·论五行旺相休囚死》）；
 *   得地 = 通根：地支本气同类、或阳干在该支居长生/临官/帝旺为重根；
 *          藏干含同五行、或该支为本五行墓库为轻根（《滴天髓·衰旺》）；
 *   得势 = 年/月/时三干中比劫或印星（《滴天髓》「天干得一比肩，不如地支得一余气墓库」）。
 *   判定按三要素组合出七档（定性），不设权重算式。
 *
 * 其余部件：调候（《穷通宝鉴》十干十二月）、通关（两行相战取泄者）、
 * 扶抑（旺则克泄、弱则生扶）、外格提示（从格/专旺/化气，依《滴天髓》）。
 */

