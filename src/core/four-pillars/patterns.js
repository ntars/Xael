/**
 * 格局综合分析：取格 + 成败 + 旺衰 + 调候 + 通关 + 扶抑 → 喜忌。
 * @param {object} input {y,m,d,h,minute,gender,name}
 * @returns {object}
 */
export function chartPatternsOf(input) {
  const c = fourPillarsChart(input);
  const P = c.pillars;
  const dm = c.日主.干;
  const dmw = c.日主.五行;
  const mz = P.月.支;

  const ge = quge(P, dm, c.月令司令);
  // 把「当月司令」并进取格依据末尾（只作说明，不覆盖透干取格结论）
  if (c.月令司令) {
    const cs = shiShen(dm, c.月令司令.司令);
    // 拼接前先摘掉上一句的句末标点，避免出现「。，」这类双标点
    ge.依据 = String(ge.依据 || '').replace(/[。；;]\s*$/, '')
      + `；当月司令为${c.月令司令.司令}（${cs}，${c.月令司令.节}后第${c.月令司令.节后天数}日，第${c.月令司令.段}段）。`;
  }
  const cb = (ge.类别 === '外格' && ge.禄刃) ? WAIGE_CB[ge.禄刃] : (CHENGBAI[ge.name.replace('格', '')] || null);
  const ws = wangShuai(c);
  const th = (TIAOHOU[dm] && TIAOHOU[dm][mz]) || [];
  const tg = tongGuan(P);

  // 扶抑（《子平真诠·论用神》「日元强者抑之，日元弱者扶之」）
  //   身强 → 抑之：首取克我者（官杀），次取我生者（食伤泄）
  //   身弱 → 扶之：首取生我者（印），次取同我者（比劫帮）
  const strong = ws.强;
  const fuYi = strong ? KE_WO[dmw] : SHENG_WO[dmw];
  // 喜忌：身强「抑之」——喜官杀克身、食伤泄秀、财耗身；忌印星生身、比劫助旺。
  //       身弱「扶之」——喜印星生身、比劫帮身；忌官杀攻身、食伤泄身、财耗身。
  // 用神（fuYi）必在喜神之中，不再出现「用神取火、喜神却写水」这种自相矛盾。
  const xi = strong ? [KE_WO[dmw], SHENG[dmw], KE[dmw]] : [SHENG_WO[dmw], dmw];
  const ji = strong ? [SHENG_WO[dmw], dmw] : [KE_WO[dmw], SHENG[dmw], KE[dmw]];

  // 格局派（《子平真诠》顺逆用）：善神顺用、不善神逆用
  const sn = shunNiYong(ge.name);

  // 综合：调候为急（《穷通宝鉴》主张调候先于扶抑）
  const 主用 = th[0] || fuYi;
  const 冲突 = (th[0] && GAN_WX[th[0]] !== fuYi)
    ? `调候取${th[0]}（${GAN_WX[th[0]]}）与扶抑取${fuYi}不一致；《穷通宝鉴》主张「调候为急」，故并列标注、不合并。`
    : '';

  // 月令司令（人元司事当值）：当月不是所有藏干同时当家，而是按日分段轮值
  //   《三命通会·论人元司事》逐月列日数（正月寅：己七日、丙五日、甲十八日……）
  const cmd = c.月令司令 || null;
  const cmdSs = cmd ? shiShen(dm, cmd.司令) : '';

  return {
    命主: input.name || '命主',
    四柱: { 年: P.年.干支, 月: P.月.干支, 日: P.日.干支, 时: P.时.干支 },
    日主: `${dm}（${dmw}）`,
    月令: `${mz}（${ZHI_WX[mz]}）`,
    月令司令: cmd ? { ...cmd, 十神: cmdSs } : null,
    格局: ge,
    格局成败: cb ? { 成格要: cb.成, 破格忌: cb.破 } : { 成格要: '（此格未收录成败条目）', 破格忌: '—' },
    外格提示: waiGeHint(P, dm, ws, c.月令司令),
    身强弱: {
      判: ws.判, 得令: ws.得令, 月令气象: ws.月令气象,
      得地: ws.得地, 重根: ws.重根, 轻根: ws.轻根, 得势: ws.得势,
      强: ws.强, 弱: ws.弱,
    },
    调候: {
      月令: mz, 第一用神: th[0] || '', 佐: th.slice(1), 全表次第: th,
      note: th.length ? `《穷通宝鉴》${dm}日干生于${mz}月调候：${th.join('、')}（首项为主）。` : '（本日干月令无调候条目）',
    },
    通关: tg,
    三派取用: threeSchoolsOf(c, ge, ws, th, waiGeHint(P, dm, ws, c.月令司令)),
    用神: {
      扶抑: fuYi,
      调候: th[0] || '',
      通关: tg.length ? tg[0].通关 : '',
      格局: sn ? { 顺逆: sn.顺逆, 喜: sn.喜, 忌: sn.忌, 依据: sn.依据 } : null,
      综合主用: 主用,
      冲突提示: 冲突,
    },
    喜忌: {
      喜神五行: xi.join('、'), 忌神五行: ji.join('、'),
      喜神列表: xi, 忌神列表: ji,
      参考: `身${strong ? '强' : '弱'}：${strong ? '抑之——喜官杀克身、食伤泄秀、财耗身，忌印星与比劫' : '扶之——喜印星生身、比劫帮身，忌官杀攻身、食伤泄身、财耗身'}（扶抑派口径，《子平真诠》「强者抑之、弱者扶之」）。`,
    },
    缺口: [
      '喜用神无唯一标准：扶抑派 / 调候派（穷通宝鉴）/ 格局派（子平真诠）/ 新派（五行分数）结论常不一致；本功能并列三路用神并标注冲突，不合并成单一断言。',
      '专旺/从格按《滴天髓·形象（独象）》《滴天髓·顺逆》立判据、化气按《滴天髓·化象》立判据（争合妒合一项按任注视为谬论，不作门槛），但各派门槛仍不一（如从格是否要求「四柱无一点印比」），未做逐派裁定。',
      '格局成败为条件式提示，不等于完整命理批断（需结合大运流年、干支刑冲合会、神煞等）。',
      '禄刃取格双口径：本模块主判「透干优先」；另有实务口径「月令见禄见刃即为禄刃格，不论透否」，遇此情形结果中并列标注禄刃位。',
    ].join('\n'),
  };
}

