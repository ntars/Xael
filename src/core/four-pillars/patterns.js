/**
 * 取格：八格 / 外格。
 * @param {object} P fourPillarsChart 的 pillars
 * @param {string} dm 日主天干
 * @returns {{name:string,类别:string,透干:string,禄刃:string,依据:string}}
 */
export function quge(P, dm, cmd = null) {
  const mz = P.月.支;
  const cang = YUE_LING_CANG[mz] || [];
  const stems = [P.年.干, P.月.干, P.时.干]; // 天干（不含日主）
  const hint = luRenHint(dm, mz);
  const lw = hint ? hint.name : '';
  const tail = lw ? `（注：月令${mz}亦为日主${lw}位，另有古籍口径直取${lw}格，本模块按「透干优先」并列标注）` : '';
  // 月令司令（《三命通会·论人元司事》「以命术言之为月令用神」）：当月当值之神。
  //   与《子平真诠》「透干取格」并列——司令说「谁在当令」，透干说「谁在天干露头」，
  //   两者可能不是同一个字，故只作说明、不覆盖取格结果。

  // ① 月令藏干透干 → 取为格（当令之神优先，其次本气→中气→余气）
  //   为什么要让「当令」优先：《三命通会·论人元司事》「以命术言之为月令用神」——
  //   一个月里三个藏干不是同时当家，是分日当值；两个藏干同时透干时，当值那个才是「用神」。
  //   旧写法一律取本气，等于把分日司事这套直接抹掉，故本轮改为「司令优先」。
  const 次序 = cmd && cang.indexOf(cmd.司令) >= 0
    ? [cmd.司令].concat(cang.filter((g) => g !== cmd.司令))
    : cang;
  const 位名 = (g) => {
    const i = cang.indexOf(g);
    return i === 0 ? '本气' : i === 1 ? '中气' : '余气';
  };
  for (let i = 0; i < 次序.length; i++) {
    const g = 次序[i];
    const ss = shiShen(dm, g);
    if (!ss || ss === '比肩' || ss === '劫财') continue;
    if (stems.indexOf(g) >= 0) {
      const 当令 = cmd && g === cmd.司令 && cang.indexOf(g) !== 0;
      return {
        name: ss + '格', 类别: '八格', 透干: g, 禄刃: lw,
        依据: `月令${mz}藏${g}（${位名(g)}）透于天干，${ss}取格`
          + (当令 ? `；该字正为当令司令（${cmd.节}后第${cmd.节后天数}日），依《三命通会·论人元司事》「月令用神」优先于本气` : '')
          + `。${tail}`,
      };
    }
  }

  // ② 皆不透 → 看当月司令（当值之神即月令用神），无司令信息时退回本气
  const bq = cmd && cang.indexOf(cmd.司令) >= 0 ? cmd.司令 : cang[0];
  const ss0 = shiShen(dm, bq);
  if (!ss0 || ss0 === '比肩' || ss0 === '劫财') {
    // 本气比劫 → 禄刃不在八格，归外格
    if (LU[dm] === mz) return { name: '建禄格', 类别: '外格', 透干: '', 禄刃: '建禄', 依据: WAIGE.建禄 };
    if (DIWANG[dm] === mz) {
      const yang = GAN_YY[dm] === 0;
      return {
        name: yang ? '阳刃格' : '月劫格', 类别: '外格', 透干: '', 禄刃: yang ? '阳刃' : '月劫',
        依据: WAIGE[yang ? '阳刃' : '月劫'],
      };
    }
    // 本气比劫但非禄刃（辰戌丑未藏戊己、巳午藏丙丁等）→ 继续取中气/余气
    for (let j = 1; j < cang.length; j++) {
      const g2 = cang[j];
      const ss2 = shiShen(dm, g2);
      if (ss2 && ss2 !== '比肩' && ss2 !== '劫财') {
        return {
          name: ss2 + '格', 类别: '八格', 透干: '', 禄刃: hint ? hint.name : '',
          依据: `月令${mz}本气${bq}为${ss0}（比劫不取格），改取所藏${g2}为${ss2}格。`,
        };
      }
    }
    return {
      name: ss0 + '（比劫不取格）', 类别: '外格', 透干: '', 禄刃: hint ? hint.name : '',
      依据: `月令${mz}藏干皆比劫，八格无取，归外格另论。`,
    };
  }

  // ③ 藏干皆不透 → 取本气
  return {
    name: ss0 + '格', 类别: '八格', 透干: '', 禄刃: hint ? hint.name : '',
    依据: `月令${mz}藏干皆不透，取${bq === cang[0] ? '本气' : '当月司令'}${bq}为${ss0}格。`
      + (bq === cang[0] ? '' : `（${cmd.节}后第${cmd.节后天数}日，依《三命通会·论人元司事》「月令用神」不取本气）`),
  };
}

