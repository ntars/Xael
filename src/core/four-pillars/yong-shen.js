/**
 * src/core/four-pillars/yong-shen.js —— 三派取用并列（自研，零依赖）
 *
 * 大白话：算八字最要紧的一步是「取用神」——定下这一局该扶什么、该压什么。
 *   可这一步偏偏是三本书三种说法，谁也不服谁：
 *     · 《子平真诠》讲**扶抑**：日元强就压它、弱就扶它；
 *     · 《穷通宝鉴》讲**调候**：先看这命生得是冷是燥，把气候调顺了再说别的；
 *     · 《滴天髓》讲**顺逆**：气势成了局就顺着它走，硬压反出祸。
 *   本仓的态度是：**三派并列摆出来、各注条件、讲清它们在哪一步会打架，不合成一句自造结论**。
 *   合成一句看着干净，其实是拿我们的取舍冒充古人的定论。
 *
 * 各派条件（原文都在 refs-texts/ 内）：
 *   扶抑 —— 《子平真诠·论用神》「日元强者抑之，日元弱者扶之」。任何命局都成立，
 *           故它是**底线**：另两派都说不上话时，按它取。
 *   调候 —— 《穷通宝鉴》十干十二月各有「某日干生某月，用某干」的专门条目。
 *           原文只说这一月这一干该用什么，**没有说「凡调候皆优先于扶抑」**；
 *           「调候为急」是后世对这一派的概括，故此处标注为「派内主张」而非原书原话。
 *   顺逆 —— 《滴天髓·顺逆》「不可逆者，其气势而已矣……当令得势之神，宜从其意向」。
 *           它只在**气势成局**（专旺、从格、化气）时才另立用神；寻常命局无「独旺可顺之势」，
 *           此派**不出用神**（不硬造一个来凑三派齐全）。
 *
 * 与「缺口」字段的分工：本模块只负责「三派各自怎么取、彼此怎么打架」；
 *   不负责判定哪种说法更对——那是流派之争，不是算错。
 */

const SHENG_WO = { 木: '水', 火: '木', 土: '火', 金: '土', 水: '金' };
const KE_WO = { 木: '金', 火: '水', 土: '木', 金: '火', 水: '土' };
const SHENG = { 木: '火', 火: '土', 土: '金', 金: '水', 水: '木' };
const KE = { 木: '土', 土: '水', 水: '火', 火: '金', 金: '木' };

/**
 * 扶抑派（《子平真诠·论用神》）。
 * 身强取「克我」为用（官杀制身），身弱取「生我」为用（印星生身）——
 * 这是最简的一层，原文本身也只给了这一句纲领，细分（食伤泄秀、比劫帮身）属后学推演，
 * 故「用神」只给一个五行，其余作「喜」并列，不排先后。
 */
export function fuYiOf(dmw, strong) {
  const yong = strong ? KE_WO[dmw] : SHENG_WO[dmw];
  const xi = strong ? [KE_WO[dmw], SHENG[dmw], KE[dmw]] : [SHENG_WO[dmw], dmw];
  const ji = strong ? [SHENG_WO[dmw], dmw] : [KE_WO[dmw], SHENG[dmw], KE[dmw]];
  return {
    派: '扶抑',
    用神: yong,
    喜: xi.filter((x, i) => xi.indexOf(x) === i),
    忌: ji.filter((x, i) => ji.indexOf(x) === i),
    成立: true,
    条件: `日主${strong ? '强' : '弱'} → ${strong ? '抑之' : '扶之'}`,
    依据: '《子平真诠·论用神》「日元强者抑之，日元弱者扶之」',
  };
}

/**
 * 调候派（《穷通宝鉴》十干十二月）。
 * 表里没有条目 = 该日干在该月原书未列，此时本派**不作声**，不拿扶抑的结果冒充调候结论。
 */
export function tiaoHouOf(gan, monthZhi, row) {
  // 入参直接给「该日干该月」那一行（取法在 patterns.js 里已按 干→月支 查好），
  // 此处不再套表查询——早先传成 {干: 行} 的嵌套形状，取不到值、静默判「无条目」。
  if (!row || !row.length) {
    return { 派: '调候', 用神: '', 佐: [], 成立: false, 条件: '《穷通宝鉴》本日干本月的条目', 依据: '《穷通宝鉴》十干十二月调候表（本日干本月无条目）' };
  }
  return {
    派: '调候',
    用神: row[0],
    佐: row.slice(1),
    成立: true,
    条件: `${gan}日干生于${monthZhi}月，原书专条`,
    依据: '《穷通宝鉴》十干十二月调候用神',
  };
}

/**
 * 顺逆派（《滴天髓·顺逆》）。
 *
 * 触发条件是**气势成局**，而「成局」这件事在本仓由 waiGeHint() 判定并返回成句说明
 *   （形如「从格：日主无根无助、金独旺……作从杀论」/「专旺成方局……」/「化气……」），
 *   并不体现在「格局」那一栏——禄刃虽同属外格类，却是「得令」而非「成局」，不可顺。
 *   故此处从成句里取关键字，取不到就明说取不到，不臆补五行。
 *
 * @param {string[]} hints waiGeHint() 的返回（成句数组）
 * @param {string} dmw 日主五行
 */
export function shunNiOf(hints, dmw, ge = null) {
  const list = Array.isArray(hints) ? hints : [];
  const txt = list.join('');
  const 依据 = '《滴天髓·顺逆》「不可逆者，其气势而已矣……当令得势之神，宜从其意向」';
  const luRen = ge && (ge.禄刃 === '建禄' || ge.禄刃 === '羊刃' || ge.禄刃 === '月劫') ? ge.禄刃 : '';
  if (!txt || !/从格|专旺|化气|从象|独旺/.test(txt)) {
    return {
      派: '顺逆', 用神: '', 成立: false,
      条件: luRen
        ? `月令${luRen}属「得令」而非「成局」，顺逆派不适用`
        : '须气势成局（专旺 / 从格 / 化气）',
      依据,
      说明: '寻常格局（含禄刃得令）无独旺可顺之势，本派不另出用神。',
    };
  }
  if (/专旺/.test(txt)) {
    return { 派: '顺逆', 用神: dmw, 成立: true, 条件: '专旺成方成局', 依据, 说明: '方局全而日主得令，顺其本气，不必抑。' };
  }
  if (/化气/.test(txt)) {
    const m = txt.match(/化([木火土金水])/);
    if (m) return { 派: '顺逆', 用神: m[1], 成立: true, 条件: '化气成象', 依据, 说明: `化气已成，顺化神${m[1]}。` };
  }
  const m2 = txt.match(/([木火土金水])独旺/);
  if (m2) {
    return { 派: '顺逆', 用神: m2[1], 成立: true, 条件: '从格（日主无根，一行独旺）', 依据, 说明: `日主无根，${m2[1]}独旺成势，顺之而不逆。` };
  }
  return {
    派: '顺逆', 用神: '', 成立: false,
    条件: '成句里已见「独旺」但未取到独旺之五行',
    依据,
    说明: '外格已提示成势，但成句未含五行字，本派暂不出用神（不臆补）。',
  };
}

/**
 * 三派汇总 + 打架处。返回 {扶抑, 调候, 顺逆, 次序, 异同[], 主用, 说明}
 *
 * 「次序」只说明本仓的默认取法（调候→顺逆→扶抑，遵循「有专条者先用专条」），
 * 并明写这是**本仓的排列**、非三书共同结论。
 */
export function threeSchoolsOf(c, ge, ws, th, hints) {
  const dmw = c.日主.五行;
  const mz = c.pillars.月.支;
  const fu = fuYiOf(dmw, ws.强);
  const tiao = tiaoHouOf(c.日主.干, mz, th);
  const shun = shunNiOf(hints, dmw, ge);

  const 异同 = [];
  if (tiao.成立) {
    // 用神是「天干」，比较时转五行
    const tiaoWx = GAN_WX_OF[tiao.用神] || '';
    if (tiaoWx && tiaoWx !== fu.用神) {
      异同.push(`调候取${tiao.用神}（${tiaoWx}）、扶抑取${fu.用神}（${fu.用神}）——两派指向不同五行，不可合并成一句。`);
    } else if (tiaoWx) {
      异同.push(`调候取${tiao.用神}（${tiaoWx}），与扶抑所取同属${fu.用神}，两派一致。`);
    }
  }
  if (shun.成立 && shun.用神 && shun.用神 !== fu.用神) {
    异同.push(`顺逆派顺${shun.用神}（气势已成局，不可逆），扶抑派取${fu.用神}——成局之命不宜再按扶抑硬压。`);
  }
  if (shun.成立 && shun.用神 && tiao.成立) {
    const twx = GAN_WX_OF[tiao.用神] || '';
    if (twx && twx !== shun.用神) {
      异同.push(`调候取${tiao.用神}（${twx}）、顺逆派顺${shun.用神}——成局之命不宜调候硬扭，本仓以顺逆为先，调候降为旁参。`);
    }
  }
  if (!tiao.成立 && !shun.成立) {
    异同.push('调候无专条、气势未成局，三派中只有扶抑派能出结论。');
  }

  // 顺序不是随手排的：成局之命「不可逆」（《滴天髓·顺逆》），故顺逆派在成局时**压过**另两派；
  //   未成局时才轮到「有专条者先用专条」（调候），最后才是扶抑的底线。
  const 主用 = (shun.成立 && shun.用神) ? shun.用神 : (tiao.成立 ? tiao.用神 : fu.用神);

  return {
    扶抑: fu,
    调候: tiao,
    顺逆: shun,
    次序: '顺逆（成局时）→ 调候 → 扶抑（三书并无共同次序，此为本仓取法：成局不可逆，其余「有专条者先用专条」）',
    异同,
    主用,
    说明: (shun.成立 && 主用 === shun.用神)
      ? `主用顺${shun.用神}（气势已成局，从其所向，《滴天髓·顺逆》）`
      : (tiao.成立 && 主用 === tiao.用神
        ? `主用取调候${tiao.用神}（《穷通宝鉴》对本日干本月有专条）`
        : `主用取扶抑${fu.用神}（《子平真诠》「${ws.强 ? '强者抑之' : '弱者扶之'}」）`),
  };
}

/** 天干五行（本地表，避免为一个查表再牵一条依赖） */
const GAN_WX_OF = {
  甲: '木', 乙: '木', 丙: '火', 丁: '火', 戊: '土', 己: '土', 庚: '金', 辛: '金', 壬: '水', 癸: '水',
};
