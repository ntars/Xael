/**
 * 命卦：出生年份 → 卦名。
 * @param {Number} year 出生年（按公历；立春前后出生者口径差异由调用方处理）
 * @param {String} gender '男'|'女'
 */
export function mingGua(year, gender) {
  let n = String(year).split('').reduce((s, c) => s + Number(c), 0);
  while (n > 9) n = String(n).split('').reduce((s, c) => s + Number(c), 0);
  let v = gender === '男' ? 11 - n : n + 4;
  if (v === 5) v = gender === '男' ? 8 : 2; // 五寄：男艮女坤
  if (v === 10) v = 9;
  if (v > 9) v = v - 9;
  const NAMES = { 1: '坎', 2: '坤', 3: '震', 4: '巽', 6: '乾', 7: '兑', 8: '艮', 9: '离' };
  return NAMES[v];
}

/**
 * 八宅排布：命卦 → 八方位吉凶。
 * @returns {Object} {命卦, 东西四命, 方位: [{方位, 卦, 星, 吉凶, 五行}]}
 */
export function bazhaiChart(year, gender) {
  const gua = mingGua(year, gender);
  const dayou = DAYOU[gua];
  const rows = Object.entries(dayou).map(([star, fangGua]) => ({
    星: star,
    吉凶: XING_LUCK[star].吉凶,
    五行: XING_LUCK[star].五行,
    方位: GONG[fangGua].方位,
    卦: fangGua,
  }));
  return {
    出生年: year,
    性别: gender,
    命卦: gua,
    东西四命: GONG[gua].归 + '四命',
    八方: rows.sort((a, b) => (a.方位 < b.方位 ? -1 : 1)),
    口径: '通例命卦算法；大游年自伏位起排；四吉四凶八星',
  };
}
