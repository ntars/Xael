/**
 * 命卦：出生年份 → {命卦数, 卦, 方位, 东西命, 年数字}。
 * 「年数字」取后两位反复相加至一位数（与参照实现一致）。
 */
export function mingGua(year, gender) {
  const male = gender === '男' || gender === 'male';
  let s = year % 100;
  while (s >= 10) s = Math.floor(s / 10) + (s % 10);
  let r;
  if (male) {
    r = (11 - s) % 10;
    if (r === 0) r = 10;
    if (r === 5) r = 8;  // 男寄艮
    if (r === 10) r = 9; // 男得 10 寄离
  } else {
    r = (s + 4) % 10;
    if (r === 0) r = 10;
    if (r === 5) r = 2;  // 女寄坤
    if (r === 10) r = 1; // 女得 10 寄坎
  }
  const g = GONG[r] || { 卦: '中', 方位: '中央', 归: '' };
  return { 命卦数: r, 卦: g.卦, 方位: g.方位, 东西命: g.归, 年数字: s };
}

/** 游年：命卦 → 八星落宫数表 */
export function younian(gua) { return YOU[gua] || null; }

/**
 * 八宅排布：命卦 → 八方位吉凶。
 * 兼容两种调用：bazhaiChart(1985, '男') 与 bazhaiChart({ y: 1985, gender: '男' })。
 * @returns {Object} {出生年, 性别, 命卦, 东西四命, 八方: [{星, 吉凶, 五行, 方位, 卦}], 口径}
 */
export function bazhaiChart(year, gender) {
  if (year && typeof year === 'object') {
    gender = year.gender || year['性别'] || '男';
    year = year.y || year.year || year['出生年'];
  }
  if (!Number.isFinite(Number(year))) throw new Error('bazhaiChart 需要出生年份');
  year = Number(year);
  const mg = mingGua(year, gender);
  const gua = mg.卦;
  const you = younian(gua);
  const rows = Object.entries(you).map(([star, gongNum]) => {
    const g = GONG[gongNum] || { 方位: '中央', 卦: '中' };
    return {
      星: star,
      吉凶: XING_LUCK[star].吉凶,
      五行: XING_LUCK[star].五行,
      方位: g.方位,
      卦: g.卦,
    };
  });
  return {
    出生年: year,
    性别: gender,
    命卦: gua,
    命卦数: mg.命卦数,
    东西四命: (mg.东西命 || '') + '四命',
    八方: rows.sort((a, b) => (a.方位 < b.方位 ? -1 : 1)),
    口径: '命卦取出生年后两位叠加至一位数（男 11 减 / 女 4 加，得 5 男寄艮女寄坤）；大游年自伏位起排八星',
  };
}
