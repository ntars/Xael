/**
 * 八宅排布：命卦 → 八方位吉凶。
 * 兼容两种调用：eightMansionsChart(1985, '男') 与 eightMansionsChart({ y: 1985, gender: '男' })。
 * @returns {Object} {出生年, 性别, 命卦, 东西四命, 八方: [{星, 吉凶, 五行, 方位, 卦}], 口径}
 */
export function eightMansionsChart(year, gender) {
  if (year && typeof year === 'object') {
    gender = year.gender || year['性别'] || '男';
    year = year.y || year.year || year['出生年'];
  }
  if (!Number.isFinite(Number(year))) throw new Error('bazhaiChart 需要出生年份');
  year = Number(year);
  const mg = lifeGua(year, gender);
  const gua = mg.卦;
  const you = eightMansionsStars(gua);
  const rows = Object.entries(you).map(([star, gongNum]) => {
    const g = GONG[gongNum] || { 方位: '中央', 卦: '中' };
    return {
      星: star,
      吉凶: XING_LUCK[star].吉凶,
      五行: XING_LUCK[star].五行,
      方位: g.方位,
      卦: g.卦,
    };
  });
  const sy = lifeGuaSanYuan(year, gender);
  return {
    出生年: year,
    性别: gender,
    命卦: gua,
    命卦数: mg.命卦数,
    东西四命: (mg.东西命 || '') + '四命',
    八方: rows.sort((a, b) => (a.方位 < b.方位 ? -1 : 1)),
    三元命卦: sy,
    口径: '命卦取出生年后两位叠加至一位数（男 11 减 / 女 4 加，得 5 男寄艮女寄坤），此为阳宅通行捷法；'
      + '另附《协纪辨方书·卷三十四》引库外《三元经》三元九宫法（男逆行女顺行）作对照，两派不同源、不合并。'
      + '大游年按《协纪辨方书·卷二·大游年变卦》翻卦法自上爻起顺变八次排八星',
  };
}
