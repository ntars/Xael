/**
 * 命卦：出生年份 → {命卦数, 卦, 方位, 东西命, 年数字}。
 * 「年数字」取后两位反复相加至一位数（与参照实现一致）。
 */
export function lifeGua(year, gender) {
  const male = gender === '男' || gender === 'male';
  let s = year % 100;
  while (s >= 10) s = Math.floor(s / 10) + (s % 10);
  let r;
  if (male) {
    r = (11 - s) % 10;
    if (r === 0) r = 10;
    if (r === 5) r = 8;  // 男寄艮
    if (r === 10) r = 9; // 男得 10 寄离
  } else {
    r = (s + 4) % 10;
    if (r === 0) r = 10;
    if (r === 5) r = 2;  // 女寄坤
    if (r === 10) r = 1; // 女得 10 寄坎
  }
  const g = GONG[r] || { 卦: '中', 方位: '中央', 归: '' };
  return { 命卦数: r, 卦: g.卦, 方位: g.方位, 东西命: g.归, 年数字: s };
}

/**
 * 命卦·三元九宫法（《钦定协纪辨方书·卷三十四·男女九宫》引库外《三元经》）。
 * 男命逆行九宫、女命顺行九宫；三日元各六十年一周（上元甲子 1864、中元 1924、下元 1984）。
 * 洛书逆行序：1→9→8→7→6→5→4→3→2；顺行序：5→6→7→8→9→1→2→3→4。
 * @returns {{命卦数:number, 卦:string, 方位:string, 东西命:string, 元:string, 步数:number}}
 */
const LUOSHU_DESC = [1, 9, 8, 7, 6, 5, 4, 3, 2];
const LUOSHU_ASC = [5, 6, 7, 8, 9, 1, 2, 3, 4];
export function lifeGuaSanYuan(year, gender) {
  const male = gender === '男' || gender === 'male';
  const y = Number(year);
  const 元序 = Math.floor((y - 1864) / 60);
  const 元 = ['上元', '中元', '下元'][((元序 % 3) + 3) % 3];
  const 步数 = ((y - 1864) % 9 + 9) % 9;
  const r = male ? LUOSHU_DESC[步数] : LUOSHU_ASC[步数];
  const g = GONG[r] || { 卦: '中', 方位: '中央', 归: '' };
  return {
    命卦数: r,
    卦: g.卦,
    方位: g.方位,
    东西命: g.归,
    元,
    步数,
    说明: r === 5
      ? '五黄入中宫，无卦可寄。库外《三元经》原文只言「女命上元甲子起中五」，未给寄宫法，此处如实留空、不作推定。'
      : '',
  };
}

