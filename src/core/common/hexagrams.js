/** 按爻象（6 位，自下而上）查卦名 */
export function guaNameByBits(bits) {
  const tri = (b) => Object.keys(BAGUA).find((g) => BAGUA[g].爻.join('') === b.join(''));
  const upper = tri(bits.slice(3));
  const lower = tri(bits.slice(0, 3));
  return guaName(upper, lower);
}
