/**
 * 取某一卦的经文。
 * @param {string} name 卦名（通行本名或底本异写都可以）
 * @returns {{序:number, 卦辞:string, 大象:string, 爻:string[], 爻名:string[], 用:object|null}|null}
 */
export function hexagramText(name) {
  return ZHOUYI[ZHOUYI_ALIAS[name] || name] || null;
}

/**
 * 取某卦某一爻的爻辞（爻位 1~6，自下而上）。爻名照底本写法返回。
 * @param {string} name 卦名
 * @param {number} pos 爻位 1~6
 * @returns {{爻名:string, 辞:string}|null}
 */
export function yaoText(name, pos) {
  const g = hexagramText(name);
  if (!g || !g.爻[pos]) return null;
  return { 爻名: g.爻名[pos], 辞: g.爻[pos] };
}

/** 乾坤两卦的「用九 / 用六」，其余卦返回 null */
export function yongText(name) {
  const g = hexagramText(name);
  return g && g.用 ? g.用 : null;
}
