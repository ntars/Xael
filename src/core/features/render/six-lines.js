export function detectMatter(text) {
  const t = String(text || '');
  for (const [k, re] of MATTER_ALIAS) if (re.test(t)) return k;
  return null;
}

/**
 * 事类 + 性别 → 用神键。
 * 《增删卜易·婚姻章》：「男占以妻财为用神，女占以官鬼为用神」——婚姻／感情两类须看性别，
 * 其余事类与性别无关。性别取自问句（「女」/「男」），未写则按男占（妻财）并说明。
 */
function yongKeyOf(事, ent) {
  if (!事) return null;
  if (事 === '婚姻' || 事 === '感情') {
    const g = ent && ent.gender;
    if (g === 'female') return '丈夫';
    return '婚姻';
  }
  return 事;
}

/** 生辰实体 → 六爻入参（缺时辰按 14 时补，缺日按今天不行） */
function lqInput(ent) {
  const dep = ent && ent.date;
  if (!dep || !dep.year || !dep.month || !dep.day) return null;
  return { y: dep.year, m: dep.month, d: dep.day, h: ent.time && ent.time.hour != null ? ent.time.hour : 14 };
}

/**
 * 从问句里取「本命」（占者生年之支）——《增删卜易·随鬼入墓章第三十》四主体之一。
 * 只认显式的「本命X」或「属X」写法，不猜、不按问句里的出生年份反推。
 */
function lifeBranchOf(text) {
  const m = String(text || '').match(/本命\s*([子丑寅卯辰巳午未申酉戌亥])|属\s*([子丑寅卯辰巳午未申酉戌亥])/);
  return m ? (m[1] || m[2] || '') : '';
}

/* ------------------------------------------------------------------ *
 * 一、六爻纳甲（排六爻）
 * ------------------------------------------------------------------ */

export function sixLinesText(ent, text) {
  const inp = lqInput(ent);
  if (!inp) return { prompt: '六爻需要起卦时间（年月日时），例如「2026年10月27日14时 排六爻」。' };
  const 事 = detectMatter(text);
  const 取用 = yongKeyOf(事, ent);
  if (取用) inp.事 = 取用;
  const 本命 = lifeBranchOf(text);
  if (本命) inp.本命 = 本命;
  const c = sixLinesCast(inp);
  if (c.错误) return { prompt: c.错误 };

  const L = [];
  L.push('【六爻纳甲】' + inp.y + '年' + inp.m + '月' + inp.d + '日 ' + inp.h + '时起卦（' + c.月建 + '月 ' + c.日辰 + '日，日干 ' + (c.日干 || '—') + '）。');
  L.push('本卦：' + c.本卦 + '（' + c.宫 + '，' + c.上下卦 + '）。');
  L.push('变卦：' + (c.变卦 ? c.变卦 + '（' + c.变卦宫 + '）' : '无（六爻安静，以本卦世爻为用）。'));
  L.push('世应：世第 ' + c.世 + ' 爻，应第 ' + c.应 + ' 爻。');
  L.push('动爻：' + (c.动爻.length ? c.动爻.map((i) => '第' + i + '爻').join('，') : '无（静卦）。'));
  L.push('六爻（自下而上）：');
  c.爻线.forEach((x) => L.push(yaoLine(x)));
  if (c.变卦) L.push('变卦纳甲：' + (c.变卦纳甲 || []).join(' '));
  // 六亲发动诀（《卜筮正宗·六亲发动诀》原文四句）：谁的爻发动就出谁的原文，供按所问取用。
  if (c.动爻.length) {
    const 发亲 = [];
    c.动爻.forEach((i) => {
      const l = c.爻线[i - 1];
      if (l && l.六亲 && 发亲.indexOf(l.六亲) < 0) 发亲.push(l.六亲);
    });
    发亲.forEach((q) => {
      const verse = LIU_QIN_FA_DONG[q];
      if (verse) L.push('六亲发动诀·' + q + '（《卜筮正宗·六亲发动诀》原文）：' + verse.join('；') + '。');
    });
  }
  // 伏神只在「本卦缺此六亲」时才有意义——《增删卜易·飞伏神章第二十八》「卦中无用神，则于本宫首卦寻之」，
  // 本宫首卦六亲俱全，故缺哪个六亲就只伏哪一爻；本卦已有的六亲不列伏神，避免一行六条噪声。
  if (c.伏飞神 && c.伏飞神.length) {
    const 现有 = new Set(c.爻线.map((x) => x.六亲));
    const 缺 = c.伏飞神.filter((f) => !现有.has(f.伏神.六亲));
    if (缺.length) {
      L.push('伏神（本卦所缺六亲，取本宫首卦同位之爻）：' + 缺.map((f) => f.伏神.六亲 + '伏第' + f.爻 + '爻' + f.伏神.干支 + '（' + f.飞伏关系 + '）').join('；') + '。');
    }
  }
  L.push('旬空：' + ((c.旬空 || []).join('') || '—') + '。');
  if (c.星煞) {
    const xs = c.星煞;
    if (xs.命中.length) {
      L.push('星煞：' + xs.命中.map((x) => `${x.名}临第${x.爻.join('、')}爻（${x.位}）`).join('；')
        + `（${xs.依据}；${xs.说明}）。`);
    } else {
      L.push(`星煞：贵人、禄神、驿马、天喜俱不临本卦六爻（${xs.依据}；${xs.说明}）。`);
    }
  }
  if (c.取用) {
    L.push(`取用：${c.取用.取用}——${c.取用.说明}（${c.取用.依据}）`);
  }
  if (c.禄马贵人) {
    const g = c.禄马贵人;
    const parts = [];
    if (g.禄) parts.push(`禄在${g.禄.支}（第${g.禄.爻.map((x) => x.爻 != null ? x.爻 : x.位).join('、')}爻）`);
    if (g.驿马) parts.push(`驿马在${g.驿马.支}（第${g.驿马.爻.map((x) => x.爻 != null ? x.爻 : x.位).join('、')}爻）`);
    if (g.贵人 && g.贵人.length) {
      parts.push(`天乙贵人临第${g.贵人.map((x) => x.爻).join('、')}爻（${g.贵人.map((x) => x.支).join('、')}）`);
    }
    if (parts.length) {
      L.push(`禄马贵人：${parts.join('；')}（《卜筮正宗·禄马羊刃歌》《卜筮正宗·贵人歌诀》；${g.说明}）。`);
    } else {
      L.push('禄马贵人：日干禄位、占日驿马、天乙贵人均不临本卦六爻（《卜筮正宗·禄马羊刃歌》《卜筮正宗·贵人歌诀》）。');
    }
  }
  if (c.间爻 && c.间爻.判) {
    L.push(`间爻：${c.间爻.判}——${c.间爻.说明}（${c.间爻.依据}）。`);
  }
  if (c.卦身 && c.卦身.支) {
    L.push('卦身：' + c.卦身.支 + '（' + c.卦身.起例 + '，《卜筮正宗·安月卦身诀》；卦身为所占事之主，伤则事难成）。');
  }
  if (c.卦体 && c.卦体.标签) {
    L.push('卦体：' + c.卦体.标签 + '——' + c.卦体.说明 + '（' + c.卦体.依据 + '）。');
  }
  if (c.动静 && c.动静.名) {
    L.push('动静：' + c.动静.名 + '——' + c.动静.说明 + '（' + c.动静.依据 + '）。');
  }
  if (c.用神) L.push('用神：' + c.用神 + '。');
  if (c.类象) L.push('类象：' + c.类象 + '。');
  if (c.卦宫类象) {
    L.push('卦宫取象：' + c.卦宫类象.宫 + '宫（' + c.卦宫类象.五行 + '）——' + c.卦宫类象.象 + '（' + c.卦宫类象.依据 + '）。');
    if (String(c.卦宫类象.说明).includes('句读两可')) L.push('· ' + c.卦宫类象.说明);
  }
  if (c.年命卦宫) {
    L.push('年命与卦宫：' + c.年命卦宫.说明 + '（' + c.年命卦宫.吉凶 + '，' + c.年命卦宫.依据 + '）。');
  }

  if (c.断语 && c.断语.length) {
    L.push('断语：');
    c.断语.forEach((x) => L.push('· ' + x.项 + '——' + tidy(x.断)));
  }
  // 分门断法：《黄金策》各门赋文——问句点了事类才出（否则泛泛而谈没有意义）
  if (事) {
    const gv = goldenVerdictsOf(事, goldenContextOf(c, sixLinesStrengthOf(inp)));
    if (gv && gv.命中.length) {
      L.push('分门断法（' + gv.章 + '，《黄金策》）：');
      L.push('· 用神：' + gv.用神原文);
      // 先照录原文，再写这台卦如何落到该句上——原文与判词分开，避免同一句话出现两遍
      gv.命中.forEach((x) => L.push('· 原文「' + x.原文 + '」→ ' + x.断));
    } else if (gv) {
      // 门类已接入但此卦一条都不触：如实说明，不硬凑、不臆断
      L.push('分门断法（' + gv.章 + '，《黄金策》）：· 用神：' + gv.用神原文);
      L.push('· 本卦未触该门条款，按原书不作断语（原文只给条款，无款可依时不另立说法）。');
    }
  }
  // 应期：《增删卜易·各门类应期总注章》——先看用神状态套规则，再按远近定单位
  const tm = sixLinesTimingOf(inp);
  if (tm && tm.条目 && tm.条目.length) {
    const u = tm.用神 || {};
    L.push('应期（《增删卜易·各门类应期总注章》）：取' + (tm.取用 || '主事爻')
      + (u.爻 ? '（第' + u.爻 + '爻 ' + u.干支 + '·' + u.六亲 + '·' + u.强弱 + '）' : '')
      + '，' + (tm.远近 === '远' ? '远事定之以年月' : '近事应之于日时') + '。');
    tm.条目.forEach((x) => {
      const what = x.取 && x.取.length
        ? x.取.filter(Boolean).join(' 或 ') + ' ' + x.单位
        : (x.说明 || '待当令之时');
      L.push('· ' + x.规则 + '——' + what + (x.说明 && x.取 && x.取.length ? '（' + x.说明 + '）' : '') + '。');
    });
    L.push('说明：' + tm.说明);
  }
  // 六爻纳甲专用五行生克、不取《周易》卦爻辞——《增删卜易》两处明说：
  //   「伏羲观奇偶以判阴阳，文王以爻辞而断凶吉，周公之后，决祸福于五行，易道穷矣」；
  //   「祸福吉凶皆地支生克制化、克合刑冲以判之」。
  //   故本功能刻意不列卦辞爻辞（要读经文请用「排梅花」，梅花后天起卦本就以爻辞兼卦辞为断）。
  L.push('易辞口径：六爻纳甲以五行生克、世应、用神为断，不取《周易》卦爻辞（《增删卜易》「周公之后，决祸福于五行」）；要读经文请用「排梅花」。');
  if (c.缺料) L.push('缺口：' + dot(tidy(c.缺料)));
  return { text: L.join('\n') };
}

/* ------------------------------------------------------------------ *
 * 二、六爻旺衰进阶（解六爻旺衰）
 * ------------------------------------------------------------------ */

export function sixLinesStrengthText(ent, text) {
  const inp = lqInput(ent);
  if (!inp) return { prompt: '看旺衰需要起卦时间（年月日时），例如「2026年10月27日14时 解六爻旺衰」。' };
  const 事 = detectMatter(text); // 用神随事而取（《增删卜易·用神章》），问句里点了事类才立用神
  const 取用 = yongKeyOf(事, ent); // 婚姻／感情另按性别（男占妻财、女占官鬼）
  if (取用) inp.事 = 取用;
  const r = sixLinesStrengthOf(inp);

  const L = [];
  L.push('【六爻旺衰】' + inp.y + '年' + inp.m + '月' + inp.d + '日' + inp.h + '时，' + (r.本卦 || '') + '（' + (r.宫 || '') + '）。');
  L.push('月建 ' + (r.月建 || '') + '，日辰 ' + (r.日辰 || '') + '（日干 ' + (r.日干 || '') + '），旬空 ' + ((r.旬空 || []).join('') || '—') + '。');
  if (r.用神) {
    // 用神伏神是数组（可能多处伏藏），不能直接拼进字符串
    const fu = Array.isArray(r.用神伏神) ? r.用神伏神 : [];
    let line = '用神：' + r.用神 + (r.用神五行 ? '（' + r.用神五行 + '）' : '');
    if (fu.length) {
      line += '，不上卦，伏于' + fu.map((f) => '第' + f.爻 + '爻（' + (f.干支 || '') + '）').join('、');
    }
    L.push(line + '。');
    // 伏神可否出伏按《增删卜易·飞伏神章第二十八》六条/五条分判
    fu.forEach((f) => {
      if (!f || (!f.可用 && !f.无用)) return;
      const use = f.可用 || []; const un = f.无用 || [];
      // 原文「二者并存以无用者优先」——有「终不得出」条时直接判为不能出伏，不再并列说可用
      if (un.length) {
        L.push('伏神终不得出：' + un.join('、') + '（《增删卜易·飞伏神章第二十八》原文「虽有如无，终不能出」'
          + (use.length ? '；虽有' + use.join('、') + '，为无用者所掩' : '') + '）。');
      } else if (use.length) {
        L.push('伏神可用：' + use.join('、') + '（《增删卜易·飞伏神章第二十八》六条）。');
      } else {
        L.push('伏神出伏未定：六条五条皆不中，依原文宜另占一卦。');
      }
    });
  }
  if (r.元忌仇) {
    const yj = r.元忌仇;
    const one = (t) => `${t.六亲}（${t.五行}）${(t.爻 || []).length
      ? ' 现第' + t.爻.map((x) => x.爻 + '爻·' + (x.旺衰 || '') + (x.空亡 ? '·空' : '') + (x.月破 ? '·月破' : '')).join('、')
      : ' 不上卦'}`;
    L.push('原忌仇（以用神五行为轴，京房纳甲生克链）：原神 ' + one(yj.原神)
      + '；忌神 ' + one(yj.忌神) + '；仇神 ' + one(yj.仇神) + '。');
    // 《卜筮正宗·原神歌》《卜筮正宗·忌神歌》判词——只出定性吉凶与原文依据，不打分。
    [yuanShenVerdict(yj), jiShenVerdict(yj)].filter(Boolean).forEach((v) => {
      L.push(v.判 + '（' + v.吉凶 + '）：' + dot(v.说明) + '（' + v.依据 + '）');
    });
    // 《增删卜易·元神忌神衰旺章第十》五／六／五／七四条清单——逐条命中，不打分。
    const pctx = { 月支: r.月建, 日支: r.日辰 };
    [['原神', yuanShenPower(yj, pctx)], ['忌神', jiShenPower(yj, pctx)]].forEach(([名, pw]) => {
      if (!pw) return;
      const 条 = pw.条.map((x) => `其${x.号}「${x.原文}」（${x.类}）`).join('；');
      L.push(`${名}有力否：${pw.判}` + (条 ? `——${条}` : '') + `（${pw.依据}）`);
    });
  }
  if (r.用神五行 && r.日辰) {
    const rv = riChenVerdict(r.用神五行, r.日辰);
    if (rv) L.push('日辰与用神：' + rv.判 + '（' + rv.吉凶 + '）——' + dot(rv.说明));
  }
  if (r.暗动论) {
    const ad = r.暗动论;
    L.push('暗动：第' + ad.暗动爻.map((x) => `${x.爻}爻（${x.干支}·${x.六亲}）`).join('、')
      + '受日辰冲而旺相不动自动——' + ad.条.map((t) => `${t.判}（${t.吉凶}）`).join('；')
      + `。${dot(String(ad.说明).replace(/。+$/, ''))}（${ad.依据}）`);
  }

  if (r.用神爻) {
    const yv = yongFaDongVerdict(r.用神爻);
    if (yv) L.push('用神发动：' + yv.判 + '（' + yv.吉凶 + '）——' + dot(yv.说明));
  }
  if (r.四处) {
    const sf = r.四处;
    const 明 = (sf.明细 || []).map((x) => x.处 + x.关系 + (x.支 || '')).join('、');
    L.push('用神四处生克冲合（《增删卜易·用神章》总纲）：'
      + (明 ? 明 + '——生 ' + sf.生 + '、克 ' + sf.克 + '、冲 ' + sf.冲 + '、合 ' + sf.合 + '。' : '四处俱不临。')
      + dot(sf.断));
  }
  if (!r.用神) {
    L.push('用神：未指定所占事类，故不立用神。《增删卜易·用神章》「用神随事而取」——'
      + '求财问妻取妻财、功名问官取官鬼、文书长辈取父母、子女问子孙、自占与出行取世爻；'
      + '指明事类（如「解六爻旺衰 求财 …」）方可定用神。');
  }
  (r.爻 || []).forEach((x) => {
    const flags = [x.世应, x.动静].filter((v) => v && String(v).trim());
    L.push('第' + x.爻 + '爻 ' + (x.六亲 || '') + (x.干支 || '') + '（' + (x.五行 || '') + '，' + (x.六神 || '')
      + (flags.length ? '，' + flags.join('，') : '') + '）：' + (x.旺衰 || '—')
      + '｜月：' + ((x.月 && x.月.类) || '—') + '，日：' + ((x.日 && x.日.类) || '—')
      + (x.空判 ? '｜空亡：' + x.空判.类 : ''));
    if (x.变 && x.变.主判) {
      // 化墓/化绝、化空各有专章：不标篇名，读者会以为是本仓自撰的断语
      const nm = String(x.变.主判.name || '');
      const c = /化空/.test(nm) ? '（《增删卜易·空亡章》）'
        : /化墓|化绝/.test(nm) ? '（《增删卜易·生旺墓绝章》）' : '';
      L.push('  变爻' + x.变.变支 + '（' + x.变.变五行 + '）：' + x.变.主判.级 + '·' + nm + '——' + dot(tidy(x.变.主判.断)) + c);
    }
  });
  if (r.合局 && r.合局.length) {
    L.push('三合局：' + r.合局.map((g) => g.局 + (g.成立 ? '成立' : '不成（缺' + g.缺 + '）') + '·' + g.来源).join('；') + '。');
  }
  const gx = r.hexagramState || r.卦象 || {};
  const gxItems = (gx.项 || []).map((x) => x.name + '——' + tidy(x.断));
  L.push('卦象：' + (gx.本卦 || '—') + (gx.变卦 ? '之' + gx.变卦 : '')
    + (gxItems.length ? '；' + gxItems.map((t) => t.replace(/。+$/, '')).join('；') : '') + '。');
  if (r.注) {
    const notes = Array.isArray(r.注) ? r.注 : String(r.注).split('；');
    notes.map((t) => String(t).trim()).filter(Boolean)
      .forEach((t) => L.push('· ' + (/[。]$/.test(t) ? t : t + '。')));
  }
  if (r.缺料) L.push('缺口：' + dot(tidy(r.缺料)));
  return { text: L.join('\n') };
}

/* ------------------------------------------------------------------ *
 * 三、梅花易数（排梅花）
 * ------------------------------------------------------------------ */

export function plumBlossomText(ent) {
  const inp = lqInput(ent);
  if (!inp) return { prompt: '梅花易数需起卦时间，例如「2026年10月27日14时 排梅花」（缺时辰按 14 时补）。' };
  const c = plumBlossomChart(inp);

  const L = [];
  L.push('【梅花易数】' + inp.y + '年' + inp.m + '月' + inp.d + '日' + inp.h + '时起卦（' + c.起卦 + '起卦）。');
  L.push('本卦「' + c.本卦.name + '」（' + c.本卦.imageName + '，上' + c.本卦.上卦 + '下' + c.本卦.下卦 + '），动第 ' + c.动爻 + ' 爻。');
  // 《梅花易数·占法》：「大抵占卜之法，成卦之后先看《周易》爻辞，以断吉凶」；
  //   同书又辨先天后天：「先天卦断吉凶，止以卦论，不甚用《易》之爻辞；后天则用爻辞，兼用卦辞」。
  //   本实现按年月日时起卦，属后天起卦，故爻辞与卦辞并用。
  const beng = hexagramText(c.本卦.name);
  if (beng) {
    // 引用写成「《周易》+ 卦名」，不要写成《周易·卦名》：卦名是运行时变量，
    //   静态审计查不到具体篇名，会被判成「篇名未命中」。
    L.push('本卦卦辞：' + beng.卦辞 + '（《周易》' + c.本卦.name + '卦）');
    L.push('本卦大象：' + beng.大象 + '（《周易》' + c.本卦.name + '卦·象传）');
  }
  const dy = yaoText(c.本卦.name, c.动爻);
  if (dy) L.push('动爻爻辞：' + dy.爻名 + '——' + dy.辞 + '（《周易》' + c.本卦.name + '卦·' + dy.爻名 + '）');
  const yy = yongText(c.本卦.name);
  if (yy) L.push('（本卦为' + c.本卦.name + '，六爻皆动时另有' + Object.keys(yy)[0] + '：' + Object.values(yy)[0] + '）');
  L.push('互卦「' + c.互卦.name + '」（' + c.互卦.imageName + '）。');
  L.push('变卦「' + c.变卦.name + '」（' + c.变卦.imageName + '）。');
  const biang = hexagramText(c.变卦.name);
  if (biang) L.push('变卦卦辞：' + biang.卦辞 + '（《周易》' + c.变卦.name + '卦）');
  L.push('体用：体「' + c.体用.体卦 + '」用「' + c.体用.用卦 + '」，' + c.体用.关系 + '（体' + c.体用.体五行 + ' / 用' + c.体用.用五行 + '）→ ' + c.体用.吉凶 + '——《梅花易数·体用总诀》。');
  if (c.体气 && c.体气.说明) L.push('体气：' + c.体气.说明);
  if (c.互变合参) {
    L.push('互卦对体：' + c.互变合参.互卦 + '。');
    L.push('变卦对体：' + c.互变合参.变卦 + '。');
    if (c.互变合参.生体卦.length) L.push('生体之卦：' + c.互变合参.生体卦.join('、') + '（宜受他卦之生）。');
    if (c.互变合参.克体卦.length) L.push('克体之卦：' + c.互变合参.克体卦.join('、') + '（不宜他卦之克）。');
    if (c.互变合参.党势) L.push('党势：' + c.互变合参.党势 + '。');
  }
  const sk = c.类象生克 || {};
  if (sk.生体 && sk.生体.length) L.push('生体类象：' + sk.生体.map((x) => x.卦 + '——' + x.象).join(' '));
  if (sk.克体 && sk.克体.length) L.push('克体类象：' + sk.克体.map((x) => x.卦 + '——' + x.象).join(' ') + '（《梅花易数·体用总诀》生体克体类象条）');
  if (c.断语 && c.断语.体用) L.push('体用断语：' + c.断语.体用 + '（《梅花易数·体用总诀》）');
  if (c.断语 && c.断语.本卦) L.push('本卦断语：' + c.断语.本卦 + '（卦义概述，按卦名卦象概括，非底本原文）');
  const xiang = (c.断语 && c.断语.类象) || [];
  if (xiang.length) L.push('八卦类象：' + xiang.map((x) => String(x).replace(/。$/, '')).join('；') + '。');
  L.push('取象：上卦' + c.本卦.上卦 + '为外为事，下卦' + c.本卦.下卦 + '为内为己，动在' + c.动爻 + '爻；断语为单点参考，仍须与互变、应期合看。');
  // 先天应期：卦气（乾兑庚辛申酉、震巽甲乙卯辰……），与体用同看
  for (const key of ['体', '用']) {
    const gua = c.体用 && (c.体用[key + '卦'] || c.体用[key]);
    const qy = gua ? qiYingOf(gua) : null;
    if (qy) L.push('先天应期（' + key + '卦' + qy.卦 + '）：' + qy.应期 + '——' + qy.备注 + '（' + qy.依据 + '）');
  }
  L.push('易辞口径：以数起卦（年月日时、物数）为先天，先天断吉凶「止以卦论，不甚用《易》之爻辞」；见物取象为后天，后天乃用爻辞兼卦辞。本实现按年月日时起卦，属先天一路，故主断在体用生克与互变，下方《周易》卦爻辞仅列参考（《梅花易数·先天后天论》）。');
  L.push('口径：' + tidy(c.口径));
  return { text: L.join('\n') };
}
