/** 爻符：阳 —，阴 -- */
const yaoMark = (y) => (y === '阳' ? '—' : '--');

/** 一爻一行的写法（自下而上）：序号 爻符 纳甲 六亲 六神【世应/标记】 */
function yaoLine(x) {
  const flags = [x.世应, x.标记].filter((v) => v && String(v).trim());
  return '  ' + x.爻 + '爻 ' + yaoMark(x.阴阳) + ' ' + (x.干支 || '') + ' ' + (x.五行 || '') + ' '
    + (x.六亲 || '') + ' ' + (x.六神 || '') + (flags.length ? '【' + flags.join('/') + '】' : '');
}

