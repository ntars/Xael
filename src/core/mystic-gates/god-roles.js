/**
 * src/core/mystic-gates/god-roles.js —— 神盘八神的定名、所司与异说（自研，零依赖）
 *
 * 大白话：八神是奇门神盘那一层。它们「叫什么」、谁排第二、谁排第五，
 *   库内两部书给的答案并不一样；本文件把两个体系都摆出来，取《奇门宝鉴》为正。
 *
 * 依据一（正）：《奇门宝鉴·释八神》——
 *   「八神者；**天乙、螣蛇、太阴、六合、朱雀、白虎、九地、九天**也。天乙常随甲而加时干，
 *     故亦名直符。阳局顺行、阴局逆行，依次临方，不循宫次序。凡兵占以天乙所在、坐击其冲。
 *     **扬兵于九天、安营于九地、伏兵于太阴、匿形于六合。间谍用朱雀、侦探用白虎，惊扰用螣蛇，
 *     各有所司也**。或有用元武、勾陈者。**朱雀之下即可兼看玄武，勾陈之下即可兼看白虎**。」
 *
 * 依据二（异说）：《奇门遁甲统宗·卷之二·八神》——
 *   「八神：一值符、二腾蛇、三太阴、四六合、**五勾陈、六朱雀**、七九地、八九天，此谓阳遁也。
 *     阴遁则一值符、二九天、三九地、四朱雀、五勾陈、六六合、七太阴、八腾蛇
 *     （朱雀下有玄武，勾陈下又白虎）。」
 *
 * 两者只在**第五、六位**不同：《奇门宝鉴》作朱雀、白虎，《奇门遁甲统宗》作勾陈、朱雀。
 *   本仓取《奇门宝鉴》（御定本，且它自己已把《统宗》那套注为「或用」），
 *   并保留《统宗》序作为「异说」输出，读者要知道另派怎么排时不必去翻书。
 *
 * 不做的事：不按「哪套更吉」另造排序——两书都是径直给次序，没有吉凶加权。
 */

/** 正序（《奇门宝鉴·释八神》）：自值符起，阳遁顺布、阴遁逆布 */
export const GODS = ['值符', '螣蛇', '太阴', '六合', '朱雀', '白虎', '九地', '九天'];

/** 异说序（《奇门遁甲统宗·卷之二·八神》）：只第五、六位不同 */
export const GODS_ALT = ['值符', '螣蛇', '太阴', '六合', '勾陈', '朱雀', '九地', '九天'];

/** 各神所司（《奇门宝鉴·释八神》原文用语，兵占语境，逐条照录不改写） */
export const GOD_ROLES = {
  值符: '坐击其冲（天乙常随甲而加时干，兵占以所在坐击其冲）',
  螣蛇: '惊扰',
  太阴: '伏兵',
  六合: '匿形',
  朱雀: '间谍',
  白虎: '侦探',
  九地: '安营',
  九天: '扬兵',
};

/** 兼看关系（《奇门宝鉴·释八神》「朱雀之下即可兼看玄武，勾陈之下即可兼看白虎」） */
export const GOD_ALSO = { 朱雀: '玄武', 勾陈: '白虎' };

/** 异名（《奇门宝鉴·释八神》「天乙常随甲而加时干，故亦名直符」） */
export const GOD_ALIAS = { 值符: '天乙' };

/**
 * 八神所司一览（供出料层排一行）。
 * @param {Array<{宫:number,神:string}>} cells hour-chart 的 cells
 * @returns {{盘上:Array<{宫:number,神:string,所司:string}>, 异说:string, 依据:string}}
 */
export function godRolesOf(cells) {
  const 盘上 = (cells || [])
    .filter((c) => c.神 && GOD_ROLES[c.神])
    .map((c) => ({ 宫: +c.宫, 神: c.神, 所司: GOD_ROLES[c.神] }));
  return {
    盘上,
    异说: `《奇门遁甲统宗·卷之二·八神》第五、六位作「勾陈、朱雀」（余同），并注「朱雀下有玄武，勾陈下又白虎」；本盘从《奇门宝鉴·释八神》`,
    依据: '定名与所司均出《奇门宝鉴·释八神》',
  };
}
