/** 通则原文（放在输出末尾作口径，避免读者把「宜某」当成无条件吉） */
export const DUTY_NOTES = {
  门: '右八门最怕迫制，吉门有气益吉，无气减吉；凶门有气益凶，无气减凶。',
  星: '右九星有气而合奇门，吉者益吉，凶者减凶。若无气而不合奇门，凶者益凶，吉者不吉。',
};

/** 某门所主（宜/不宜/余论） */
export function gateDutyOf(door) {
  const d = GATE_DUTY[door];
  if (!d) return null;
  return { 门: door, 宜: d.宜.slice(), 不宜: d.不宜.slice(), 余论: d.注 || '', 依据: '《奇门遁甲统宗·卷之二》「' + door + '所主」条' };
}

/** 某星所主（宜/不宜/别名） */
export function starDutyOf(star) {
  const s = String(star || '').replace(/\(.*\)$/, '');
  const d = STAR_DUTY[s];
  if (!d) return null;
  return { 星: s, 别名: d.别名, 宜: d.宜.slice(), 不宜: d.不宜.slice(), 依据: '《奇门遁甲统宗·卷之二》「' + s + '所主」条' };
}

/** 三奇落宫喜怒：qi = 乙/丙/丁，palace = 1..9（中五不作奇位，调用方已寄坤二） */
export function qiMoodOf(qi, palace) {
  const m = (QI_MOOD[qi] || {})[palace];
  if (!m) return null;
  return { 奇: qi, 宫: palace, 名: m.名, 判: m.判, 说明: m.判 ? '' : '原书只给名目，未言吉凶' };
}

/**
 * 整盘「谁管什么事」：只取三处最相关的——值使门、值符星、三奇落宫。
 * 不把八门九星全列（那是一整页），要看全表请查 GATE_DUTY / STAR_DUTY。
 */
export function imageryOf(chart) {
  if (!chart || chart.err) return null;
  const 值使门 = gateDutyOf(chart['值使']);
  const 值符星 = starDutyOf(String(chart['值符'] || '').split('(')[0]);
  const 奇位 = [];
  (chart.cells || []).forEach((c) => {
    const g = c['天盘干'];
    if (['乙', '丙', '丁'].includes(g) && +c['宫'] !== 5) {
      const m = qiMoodOf(g, +c['宫']);
      if (m) 奇位.push(m);
    }
  });
  return {
    值使门, 值符星, 三奇落宫: 奇位,
    通则: DUTY_NOTES,
    依据: '《奇门遁甲统宗·卷之二》八门所主、九星所主、三奇喜怒三节',
  };
}
