/**
 * src/core/mystic-gates/day-profiles.js —— 遁甲择日的三项日级属性（自研，零依赖）
 *
 * 大白话：排完盘之后，古人还要问三件与「这一天 / 这一个时辰」本身有关的事——
 *   ① 这一天的干支相配属于哪一等（宝、和、义、制、伏），吉凶差多少；
 *   ② 当日节气落在哪一卦，该卦的「德神」与「刑神」各在哪一支；
 *   ③ 这一个时辰属「五阳时」还是「五阴时」，宜为主还是宜为客。
 *   三项都与盘面无关，只取决于日柱、节气、时干，故独立成模块，供奇门各家共用。
 *
 * 依据：《奇门遁甲统宗·卷之二》「德刑」「宝和义制伏」「五阳时」「五阴时」四节原文。
 */

/** 八节 → 卦（《奇门遁甲统宗·卷之二·八节》：立春甲子起艮、春分起震、立夏起巽、夏至起离、立秋起坤、秋分起兑、立冬起乾、冬至起坎） */
export const GUA_OF_TERM = {
  立春: '艮', 雨水: '艮', 惊蛰: '艮',
  春分: '震', 清明: '震', 谷雨: '震',
  立夏: '巽', 小满: '巽', 芒种: '巽',
  夏至: '离', 小暑: '离', 大暑: '离',
  立秋: '坤', 处暑: '坤', 白露: '坤',
  秋分: '兑', 寒露: '兑', 霜降: '兑',
  立冬: '乾', 小雪: '乾', 大雪: '乾',
  冬至: '坎', 小寒: '坎', 大寒: '坎',
};

/** 德刑表（《奇门遁甲统宗·卷之二·德刑》逐条照录） */
export const DE_XING = {
  艮: { 德: '辰', 刑: '戌' },
  震: { 德: '午', 刑: '子' },
  巽: { 德: '未', 刑: '丑' },
  离: { 德: '酉', 刑: '卯' },
  坤: { 德: '戌', 刑: '辰' },
  兑: { 德: '子', 刑: '午' },
  乾: { 德: '丑', 刑: '未' },
  坎: { 德: '卯', 刑: '酉' },
};

/**
 * 德刑（依当日节气所临之卦）。
 * 原文：「立春、雨水、惊蜇在艮，德辰刑戌；春分、清明、谷雨在震，德午刑子……冬至、小寒、大寒在坎，德卯刑酉。」
 * @param {string} term 节气名（如「冬至」）
 */
export function deXingOf(term) {
  const gua = GUA_OF_TERM[term];
  if (!gua) return null;
  const dx = DE_XING[gua];
  return {
    节: term, 卦: gua, 德: dx.德, 刑: dx.刑,
    依据: `《奇门遁甲统宗·卷之二·德刑》——${term}在${gua}，德${dx.德}刑${dx.刑}`,
  };
}

const SHENG = { 木: '火', 火: '土', 土: '金', 金: '水', 水: '木' };
const KE = { 木: '土', 土: '水', 水: '火', 火: '金', 金: '木' };
const GAN_WX = { 甲: '木', 乙: '木', 丙: '火', 丁: '火', 戊: '土', 己: '土', 庚: '金', 辛: '金', 壬: '水', 癸: '水' };
const ZHI_WX = { 子: '水', 丑: '土', 寅: '木', 卯: '木', 辰: '土', 巳: '火', 午: '火', 未: '土', 申: '金', 酉: '金', 戌: '土', 亥: '水' };

/**
 * 宝、和、义、制、伏（依日柱干支相配）。
 * 原文：「宝者，干生支也，如甲午、己酉之类；和者，干支比和也，如甲寅、戊辰之类；
 *   义者，支生干也，如甲子、戊午之类；制者，干克支也，如庚寅、壬午之类；伏者，支克干也，如乙酉、丙子之类。
 *   宝和义日吉，制日小凶，伏日大凶。历家以和日为专日，以伏日为伐日。」
 * @param {string} gan 日干
 * @param {string} zhi 日支
 */
export function dayClassNameOf(gan, zhi) {
  const g = GAN_WX[gan];
  const z = ZHI_WX[zhi];
  if (!g || !z) return null;
  let 类;
  if (SHENG[g] === z) 类 = '宝日';
  else if (g === z) 类 = '和日';
  else if (SHENG[z] === g) 类 = '义日';
  else if (KE[g] === z) 类 = '制日';
  else 类 = '伏日';
  const 吉凶 = (类 === '宝日' || 类 === '和日' || 类 === '义日') ? '吉' : (类 === '制日' ? '小凶' : '大凶');
  const 别名 = 类 === '和日' ? '专日' : (类 === '伏日' ? '伐日' : '');
  return {
    日干支: gan + zhi, 类, 吉凶, 别名,
    说明: 类 === '宝日' ? '干生支' : 类 === '和日' ? '干支比和' : 类 === '义日' ? '支生干'
      : 类 === '制日' ? '干克支' : '支克干',
    依据: '《奇门遁甲统宗·卷之二·宝和义制伏》——宝和义日吉、制日小凶、伏日大凶',
  };
}

/**
 * 五阳时 / 五阴时（依时干）。
 * 原文：「甲乙丙丁戊五时为阳……将兵利客，宜先举。凡出军、征伐、远行、求财、立国邑、安社稷、治人民、
 *   临武事、入宫见贵、移徙、嫁娶皆吉，惟逃亡难捕。」
 * 「己庚辛壬癸五时为阴……将兵利主宜后应。凡……皆不吉，惟逃亡可获。」
 * @param {string} hourGan 时干
 */
export function hourClassOf(hourGan) {
  if (!GAN_WX[hourGan]) return null;
  const yang = '甲乙丙丁戊'.indexOf(hourGan) >= 0;
  return yang
    ? {
      时干: hourGan, 类: '五阳时', 利: '利客、宜先举',
      断语: '出军、征伐、远行、求财、立国邑、安社稷、治人民、临武事、入宫见贵、移徙、嫁娶皆吉，惟逃亡难捕',
      依据: '《奇门遁甲统宗·卷之二·五阳时》——「阳时气升」，符使行阳利为客',
    }
    : {
      时干: hourGan, 类: '五阴时', 利: '利主、宜后应',
      断语: '出军、征伐、远行、求财、立国邑、安社稷、治人民、临武事、入宫见贵、移徙、嫁娶皆不吉，惟逃亡可获',
      依据: '《奇门遁甲统宗·卷之二·五阴时》——「阴干受西部之煞气」，符使行阴利为主',
    };
}

/**
 * 三项日级属性一次取齐，供 hour-chart / 各家盘面共用。
 * @param {{gan:string, zhi:string}} dayGz 日柱
 * @param {string} term 当日节气名
 * @param {string} hourGan 时干
 */
export function dayProfilesOf(dayGz, term, hourGan) {
  return {
    德刑: deXingOf(term),
    日家: dayGz ? dayClassNameOf(dayGz[0] || dayGz.gan, dayGz[1] || dayGz.zhi) : null,
    时家阴阳: hourGan ? hourClassOf(hourGan) : null,
    依据: '《奇门遁甲统宗·卷之二》德刑、宝和义制伏、五阳时、五阴时四节',
  };
}
