/**
 * 逐宫十干克应。
 * @param {object} pan mysticGatesHourChart 的输出
 */
export function keYingOf(pan) {
  const out = [];
  const cells = pan['cells'] || [];
  for (const c of cells) {
    const g = c['宫'];
    if (g === 5) continue; // 中五无实宫（寄坤二）
    const tg = c['天盘干'];
    const dg = c['地盘干'];
    if (!tg || !dg) continue;
    const k = KE_YING[tg + dg];
    out.push({
      宫: g, 天盘干: tg, 地盘干: dg, 门: c['门'] || '', 星: c['星'] || '', 神: c['神'] || '',
      patternName: k ? k[0] : '（未收录）', 吉凶: k ? k[1] : '平', 象意: k ? k[2] : '', aliasName: (k && k[3]) || '',
    });
  }
  return out;
}

