    if (men === '休门' && tg === '丁' && god === '太阴') 吉.push({ name: '人遁', 宫: p, 义: '休门+天盘丁奇+太阴：得星精之蔽。利藏形隐迹、择将选贤、说敌和仇（《奇门遁甲统宗·奇门四十格》「休门与丁奇临太阴」）' });
    if (men === '休门' && tg === '乙' && god === '九天') 吉.push({ name: '神遁', 宫: p, 义: '休门+乙奇+九天：利运筹祈祷、行兵谋略（《奇门遁甲统宗·奇门四十格》「休门与乙奇合九天」）' });
    if (men === '杜门' && tg === '乙' && god === '九地') 吉.push({ name: '鬼遁', 宫: p, 义: '杜门+乙奇+九地：多诈，利偷营劫寨、伏兵、侦察（《奇门遁甲统宗·奇门四十格》「乙奇合九地杜门」）' });
    if (tg === '乙' && JI_MEN.some((m) => men === m + '门') && p === 4) 吉.push({ name: '风遁', 宫: p, 义: '乙奇+三吉门临巽四宫：利行车航船、顺风击敌（《奇门遁甲统宗·奇门四十格》「休开生临乙奇，地盘巽四宫」）' });
    if (tg === '乙' && JI_MEN.some((m) => men === m + '门') && dg === '辛') 吉.push({ name: '云遁', 宫: p, 义: '乙奇+三吉门+地盘辛：利偷营劫寨、求雨求雪、藏匿（《奇门遁甲统宗·奇门四十格》「休开生与乙奇合奇，地盘六辛」）' });
    if (men === '休门' && tg === '乙' && p === 1) 吉.push({ name: '龙遁', 宫: p, 义: '休门+乙奇临坎一宫：通神，利水战渡江、祈雨、修桥凿井（《奇门遁甲统宗·奇门四十格》「休门与乙奇合坎」）' });
    // 虎遁「休门与乙奇合艮辛」（《奇门遁甲统宗·奇门四十格》）：休门、天盘乙奇、地盘辛三者同在艮八宫。
    //   ★ 旧注释曾断言「乙奇不会与辛同宫、全年 0 命中」——那是八门轮转尚未修正时的假象。
    //   修正后实测 2020–2026 抽样命中 73 次（首例 2020-01-19 7 时），故照原文实现。
    if (men === '休门' && tg === '乙' && dg === '辛' && p === 8) 吉.push({ name: '虎遁', 宫: p, 义: '休门+天盘乙奇+地盘辛临艮八宫：得虎威之蔽。利招安讨叛、设伏守险、扬威耀武（《奇门遁甲统宗·奇门四十格》「休门与乙奇合艮辛」）' });

    // —— 三奇得使 / 升殿 / 三诈 / 五假 / 交泰等 ——
    // 三奇游六仪（《奇门宝鉴·释三奇游六仪》：「三奇游六仪者，谓奇间于仪中，**仪加奇**、
    //   而奇复游其仪也。左仪加奇，则奇游于右仪；右仪加奇，则奇游于左仪。乙游己辛，
    //   丙游戊庚，丁游壬癸，**必为当旬直符来加方是**。」
    //   原书算例：「假如阳一局，乙奇在九宫、甲午辛在四宫居右、甲戌己在二宫居左；
    //   若乙亥时，甲戌直符来加乙于九宫，则乙游于右仪之辛。」
    //   → 方向是「天盘六仪（且必须是本旬直符）加地盘三奇」，不是「天盘奇加地盘仪」。
    //   旧实现判 `SAN_QI.includes(tg) && YOU_LIU_YI[tg].includes(dg)` 把主客颠倒了，已按原文改正。
    //   条件严格说是「当旬直符来加」——直符必落值符宫，故等价于：本宫是值符宫 + 地盘为三奇 +
    //   本旬旬首仪正是该奇所游之仪。不用「天盘干 === 旬首仪」比对，是因为旬首仪为壬/癸（居
    //   中五、天禽所携）时，本盘天盘干按星之本位排，该宫显示的是天芮之己/庚而非中五的壬/癸。
    if (p === pan['值符宫'] && SAN_QI.includes(dg) && YOU_LIU_YI[dg] && YOU_LIU_YI[dg].includes(zhiFuYi)) {
      const 游 = YOU_LIU_YI[dg].filter((x) => x !== zhiFuYi).join('、');
      const 侧 = YOU_LIU_YI[dg].indexOf(zhiFuYi) === 0 ? '左仪加奇，奇游于右仪' : '右仪加奇，奇游于左仪';
      吉.push({ name: '三奇游六仪', 宫: p, 义: `当旬直符${zhiFuYi}加地盘${dg}奇（${侧}）：${dg}游于${游}，利为百事；得吉门更利。` });
    }
    // 三奇得使（《奇门宝鉴·释三奇得使》：「谓得三吉门、直使加奇也。凡开、休、生加乙、丙、丁
    // 为吉门合三奇，利为百事。更得吉门作直使为得使，谋为尤利。」）
    // 即：三吉门与三奇同宫，且该门正是本局值使门。
    if (SAN_QI.includes(tg) && JI_MEN.some((m) => men === m + '门')) {
      // 原文分两层：①「凡开、休、生加乙、丙、丁为吉门合三奇，利为百事」——吉门与三奇同宫即成立；
      // ②「更得吉门作直使为得使，谋为尤利」——该门恰为本局值使才是「得使」。两层分开报，不合并。
      const isZhiShi = pan && pan['值使'] === men;
      if (isZhiShi) {
        吉.push({ name: '三奇得使', 宫: p, 义: `${men}（值使）合天盘${tg}奇：得三吉门且为直使，谋为尤利。` });
      } else {
        吉.push({ name: '三奇合吉门', 宫: p, 义: `${men}合天盘${tg}奇：吉门合三奇，利为百事（未作直使，不作「得使」论）。` });
      }
    }
    // 三奇升殿：通行口诀（乙临震三、丙临离九、丁临兑七），库内文献无此格名，标通行
    if (tg === '乙' && p === 3) 吉.push({ name: '三奇升殿', 宫: p, 义: '乙奇临震3（日出扶桑·有禄之乡），贵人升乙卯正殿（通行口诀）。' });
    if (tg === '丙' && p === 9) 吉.push({ name: '三奇升殿', 宫: p, 义: '丙奇临离9（月照端门·火旺之地），贵人升丙午正殿（通行口诀）。' });
    if (tg === '丁' && p === 7) 吉.push({ name: '三奇升殿', 宫: p, 义: '丁奇临兑7（天之神位），贵人升丁酉正殿（通行口诀）。' });
    if (JI_MEN.some((m) => men === m + '门') && SAN_QI.includes(tg)) {
      if (god === '太阴') 吉.push({ name: '真诈', 宫: p, 义: men + '+' + tg + '奇+太阴：宜施恩、隐遁、求道，经商远行嫁娶百事吉。' });
      else if (god === '九地') 吉.push({ name: '重诈', 宫: p, 义: men + '+' + tg + '奇+九地：宜生子、求财、谋职、晋升。' });
      else if (god === '六合') 吉.push({ name: '休诈', 宫: p, 义: men + '+' + tg + '奇+六合：宜合葬、治病、祈福、消灾。' });
    }
    if (men === '景门' && SAN_QI.includes(tg) && god === '九天') 吉.push({ name: '天假', 宫: p, 义: '景门+三奇+九天：宜求道、参悟玄机、学习预测术（三诈五假库内二书均无逐条定义，近世通行口诀，待考）。' });
    if (men === '杜门' && '丁己癸'.includes(tg) && ['九地', '六合', '太阴'].includes(god)) 吉.push({ name: '地假', 宫: p, 义: '杜门+丁己癸+九地/六合/太阴：利谋略、藏形（近世通行口诀，待考）。' });
    if (men === '惊门' && tg === '壬' && god === '九天') 吉.push({ name: '人假', 宫: p, 义: '惊门+壬+九天：宜拘捕逃犯、寻找失散之人（近世通行口诀，待考）。' });
    if (men === '伤门' && '丁己癸'.includes(tg) && god === '六合') 吉.push({ name: '神假（物假）', 宫: p, 义: '伤门+丁己癸+六合：宜贸易、合约（异名「物假」；近世通行口诀，待考）。' });
    if (men === '死门' && '丁己癸'.includes(tg) && god === '九地') 吉.push({ name: '鬼假', 宫: p, 义: '死门+丁己癸+九地：宜合作、求财（近世通行口诀，待考）。' });
    if (tg === '乙' && (dg === '丁' || dg === '丙')) 吉.push({ name: '交泰格', 宫: p, 义: '乙奇加' + dg + '奇：大吉。' });
    if (tg === '丁' && dg === '乙') 吉.push({ name: '天遇昌气', 宫: p, 义: '六丁加六乙：百事兴。' });
    if ((tg === '乙' && dg === '庚') || (tg === '丙' && dg === '辛') || (tg === '丁' && dg === '壬')) {
      吉.push({ name: '奇仪相合', 宫: p, 义: tg + dg + '奇合：得吉门则凡事有和解、了结、平分之象。' });
    }

    // —— 凶格 ——
    if (JI_XING[tg] === p) 凶.push({ name: '六仪击刑', 宫: p, 义: '天盘' + tg + '加' + p + '宫：击刑，大凶（' + tg + '落' + p + '宫受刑）。' });
    if (QI_RU_MU[tg] && QI_RU_MU[tg].includes(p)) 凶.push({ name: '三奇入墓', 宫: p, 义: `天盘${tg}奇临${p}宫入墓（${tg === '乙' ? '二宫藏未，乙木墓于未' : '六宫藏戌，丙丁火墓于戌'}）：奇失灵，吉事不吉。` });
