/**
 * src/core/mystic-gates/star-states.js —— 九星的本等吉凶与气应旺衰（自研，零依赖）
 *
 * 大白话：八门有「得时得地」，九星也一样——「天辅是大吉星」只是它的本等，
 *   落到某个月的盘上还要看它**当月有没有气**：本等吉的失气要打折，本等凶的失气反而减凶。
 *
 * 依据（库内两部原书各有直证，且互不冲突）：
 *
 * ① 本等吉凶 —— 《奇门遁甲统宗·奇门秘诀总赋》：
 *    「**蓬任冲辅禽阳星，英芮柱心阴宿益。辅禽心星为大吉，冲任小吉未全亨。
 *      大凶蓬芮不堪遇，小凶英柱在中宫。大凶无气交为小，小凶有气亦丁忧。
 *      吉宿更能逢旺相，万举万全功必成。**」
 *    同书注：「凡时下得辅禽心大吉，任冲小吉，蓬芮大凶，英柱小凶。」
 *    → 大吉：天辅、天禽、天心；小吉：天任、天冲；大凶：天蓬、天芮；小凶：天英、天柱。
 *
 * ② 气应旺衰 —— 《奇门宝鉴·释气应》：
 *    「九星蓬水、英火、冲辅木、任芮禽土、柱心金，**皆以我生之月为旺，我同之月为相，
 *      我克之月为休，克我之月为囚，生我之月为废**。如水星旺于寅卯月、相于亥子月、
 *      休于四五月、囚于辰戌丑未月、废于申酉月是也。」
 *    《奇门遁甲统宗》另一处说得同一件事（只是把「休」称作「废」）：
 *    「九星旺于子月，相于本月，死于父母月，囚于鬼月，废于妻月。如天蓬水星，
 *      正二月旺，十月十一月相，七月八月死，三六九十二月囚，四五月废。」
 *
 * ★ 注意：九星的旺衰**与常法相反**——常法是「当令者旺」，九星是「**我生之月为旺**」
 *   （水星旺于木月，因为水生木、气泄于外而为用）。故本模块**不能**复用 seasonal 旺衰表，
 *   必须单列。这也是奇门里最容易抄错的一张表。
 *
 * 不做的事：不给分值、不改盘面、不改门与奇仪的判断，只在星旁标本等与气应。
 */

/** 九星五行（《奇门宝鉴·释气应》「蓬水、英火、冲辅木、任芮禽土、柱心金」） */
export const STAR_ELEMENT = {
  天蓬: '水', 天芮: '土', 天冲: '木', 天辅: '木', 天禽: '土', 天心: '金', 天柱: '金', 天任: '土', 天英: '火',
};

/** 本等吉凶（《奇门遁甲统宗·奇门秘诀总赋》注） */
export const STAR_BASE = {
  天辅: '大吉', 天禽: '大吉', 天心: '大吉',
  天任: '小吉', 天冲: '小吉',
  天蓬: '大凶', 天芮: '大凶',
  天英: '小凶', 天柱: '小凶',
};

const SHENG = { 木: '火', 火: '土', 土: '金', 金: '水', 水: '木' };
const KE = { 木: '土', 土: '水', 水: '火', 火: '金', 金: '木' };
const ZHI_WX = {
  子: '水', 丑: '土', 寅: '木', 卯: '木', 辰: '土', 巳: '火',
  午: '火', 未: '土', 申: '金', 酉: '金', 戌: '土', 亥: '水',
};

/**
 * 九星气应：以「我生之月为旺、我同之月为相、我克之月为休、克我之月为囚、生我之月为废」。
 * @param {string} wx 星之五行
 * @param {string} monthZhi 月支
 * @returns {{气:string, 依据:string}}
 */
export function starSeasonOf(wx, monthZhi) {
  const mw = ZHI_WX[monthZhi];
  if (!mw || !wx) return { 气: '', 依据: '' };
  let 气;
  if (SHENG[wx] === mw) 气 = '旺';        // 我生之月
  else if (wx === mw) 气 = '相';           // 我同之月
  else if (KE[wx] === mw) 气 = '休';       // 我克之月
  else if (KE[mw] === wx) 气 = '囚';       // 克我之月
  else 气 = '废';                          // 生我之月
  return { 气, 依据: `${wx}星在${monthZhi}月（${mw}）为「${气}」` };
}

/**
 * 单星总判：本等吉凶 + 气应修正。
 *
 * 修正依《统宗》「大凶无气交为小，小凶有气亦丁忧，吉宿更能逢旺相，万举万全功必成」：
 *   · 大吉星得气（旺/相）→ 大吉·万举万全；失气 → 吉力减
 *   · 小吉星得气 → 小吉（可用）；失气 → 吉力薄
 *   · 大凶星失气 → 降为小凶（「交为小」）；得气 → 仍大凶
 *   · 小凶星得气 → 加重为「忧」（「亦丁忧」）；失气 → 仍小凶
 */
export function starVerdictOf(star, monthZhi) {
  const wx = STAR_ELEMENT[star];
  const base = STAR_BASE[star];
  if (!wx || !base) return null;
  const { 气, 依据: 气依据 } = starSeasonOf(wx, monthZhi);
  const 得气 = 气 === '旺' || 气 === '相';
  let 判;
  let 说明;
  if (base === '大吉') {
    判 = 得气 ? '大吉' : '吉减';
    说明 = 得气 ? '吉星逢旺相，原文「万举万全功必成」' : '吉星失气，吉力打折';
  } else if (base === '小吉') {
    判 = 得气 ? '小吉' : '小吉（力薄）';
    说明 = 得气 ? '小吉星得气，可用' : '小吉星失气，仅可小事';
  } else if (base === '大凶') {
    判 = 得气 ? '大凶' : '小凶';
    说明 = 得气 ? '大凶星得气，凶势仍盛' : '原文「大凶无气交为小」，降为小凶';
  } else {
    判 = 得气 ? '忧' : '小凶';
    说明 = 得气 ? '原文「小凶有气亦丁忧」，加重为忧' : '小凶星失气，仍为小凶';
  }
  return {
    名: star, 五行: wx, 本等: base, 气, 得气, 判, 说明,
    依据: '《奇门遁甲统宗·奇门秘诀总赋》「辅禽心星为大吉，冲任小吉未全亨，大凶蓬芮不堪遇，小凶英柱在中宫」；'
      + '气应按《奇门宝鉴·释气应》「以我生之月为旺，我同之月为相」（' + 气依据 + '）',
  };
}

/**
 * 整盘汇总：盘上每个九星的本等与气应。
 * @param {Array<{宫:number,星?:string}>} cells hour-chart / quarter-chart 的 cells
 * @param {string} monthZhi 月支
 */
export function starStatesOf(cells, monthZhi) {
  const 列 = [];
  (cells || []).forEach((c) => {
    // 天禽寄天芮时该宫星显示「天芮(禽)」，此处按主星取，禽星另标
    const raw = String(c.星 || '');
    const name = raw.replace(/\(.*$/, '');
    if (!STAR_ELEMENT[name]) return;
    const v = starVerdictOf(name, monthZhi);
    if (!v) return;
    列.push({ ...v, 宫: +c.宫, 同宫禽星: raw.includes('禽') ? '天禽' : '' });
  });
  return { 月令: monthZhi, 星: 列, 依据: '九星本等见《奇门遁甲统宗·奇门秘诀总赋》，气应见《奇门宝鉴·释气应》' };
}
