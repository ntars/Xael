/**
 * 碎金赋制化判词。
 *
 * @param {string} 动 发动之六亲
 * @param {string[]} 卦中动亲 本卦中所有发动爻的六亲（不含自己）
 * @param {string[]} [卦中现亲] 本卦出现的六亲（不上卦者不参与生克）
 * @returns {{判:string, 吉凶:string, 依据:string, 说明:string}|null}
 */
export function suiJinVerdict(动, 卦中动亲 = [], 卦中现亲 = []) {
  if (!动) return null;
  const 忌亲 = qinKeWo(动);
  const 解亲 = qinKeWo(忌亲);
  const 生亲 = qinSheng(动);
  const 动者 = 卦中动亲.filter((q) => q !== 动);
  const 忌在 = 动者.indexOf(忌亲) >= 0;
  const 解在 = 动者.indexOf(解亲) >= 0;
  const 生现 = !卦中现亲.length || 卦中现亲.indexOf(生亲) >= 0;
  const 依据 = '《卜筮正宗·碎金赋》';
  const 原句 = (SUI_JIN.find((x) => x.动 === 动 && x.忌 === 忌亲) || {}).原文 || '';
  if (忌在 && 解在) {
    return {
      判: `${动}动生${生亲}，${忌亲}亦动来克，得${解亲}动制${忌亲}`,
      吉凶: '凶中藏吉',
      依据,
      原文: 原句,
      说明: `按原文「贪生忘克」之义，${解亲}动则${忌亲}贪生${qinSheng(忌亲)}而忘克${动}，${动}反得全，故凶中藏吉。`,
    };
  }
  if (忌在) {
    return {
      判: `${动}动生${生亲}，${忌亲}发动来克`,
      吉凶: '凶',
      依据,
      原文: 原句,
      说明: `${忌亲}克${动}，好事被拦；须待${解亲}动、或日辰制${忌亲}方解。`,
    };
  }
  if (解在) {
    return {
      判: `${动}动生${生亲}，${解亲}动制其忌${忌亲}`,
      吉凶: '吉',
      依据,
      原文: 原句,
      说明: `${解亲}克${忌亲}，为${动}去其害，${动}得全其生。`,
    };
  }
  if (!生现) {
    return {
      判: `${动}动而所生${生亲}不上卦`,
      吉凶: '平',
      依据,
      原文: 原句,
      说明: '动而无所生，其力不落地，只作本气论。',
    };
  }
  return {
    判: `${动}动生${生亲}，卦中${忌亲}不动`,
    吉凶: '吉',
    依据,
    原文: 原句,
    说明: `忌神不动则${动}得全其生。`,
  };
}

