/** 六亲顺序：生克链循环（父 → 兄 → 子 → 财 → 鬼 → 父） */
export const QIN_CYCLE = ['父母', '兄弟', '子孙', '妻财', '官鬼'];

/** 某六亲所生之六亲 */
export function qinSheng(qin) {
  const i = QIN_CYCLE.indexOf(qin);
  return i < 0 ? '' : QIN_CYCLE[(i + 1) % 5];
}

/** 某六亲所克之六亲 */
export function qinKe(qin) {
  const i = QIN_CYCLE.indexOf(qin);
  return i < 0 ? '' : QIN_CYCLE[(i + 2) % 5];
}

/** 克某六亲者（忌神） */
export function qinKeWo(qin) {
  const i = QIN_CYCLE.indexOf(qin);
  return i < 0 ? '' : QIN_CYCLE[(i + 3) % 5];
}

/** 生某六亲者（原神） */
export function qinShengWo(qin) {
  const i = QIN_CYCLE.indexOf(qin);
  return i < 0 ? '' : QIN_CYCLE[(i + 4) % 5];
}

