/**
 * 用神不上卦时的取用次序。
 *
 * 《增删卜易·飞伏神章第二十八》：「若用神不现，即以日月为用神，倘日月非用神者，
 * 则于宫首卦寻之，因本宫首卦，父子财官六亲俱全之故耳。」
 * 原书举例：「若占妻财，取财爻为神……今六爻无寅卯，即是用神不上卦，如于寅卯月占者，
 * 则以日月为用神，倘非寅卯月，须在宫首卦，乾为天卦内寻之。」
 *
 * @param {string} 用神 用神六亲
 * @param {string} 宫五行 本卦宫五行
 * @param {string} 月支
 * @param {string} 日支
 * @returns {{取用:string, 依据:string, 说明:string, 五行:string}}
 */
export function yongAbsentOf(用神, 宫五行, 月支, 日支) {
  const wx = qinWxOf(用神, 宫五行);
  const 据 = '《增删卜易·飞伏神章第二十八》';
  if (wx && ((月支 && ZHI_WX_MAP[月支] === wx) || (日支 && ZHI_WX_MAP[日支] === wx))) {
    const which = 月支 && ZHI_WX_MAP[月支] === wx ? `月建${月支}` : `日辰${日支}`;
    return {
      取用: '日月为用神',
      五行: wx,
      依据: 据,
      说明: `${用神}属${wx}，${which}正是${wx}，原书「若用神不现，即以日月为用神」——`
        + `日月本身即是用神，其旺衰即事之休咎，不必再寻伏神。`,
    };
  }
  return {
    取用: '宫首卦寻伏神',
    五行: wx,
    依据: 据,
    说明: `${用神}属${wx}，月建日辰皆非${wx}，按原书「倘日月非用神者，则于宫首卦寻之」，`
      + `故取本宫首卦同位之爻为伏神；飞伏生克之吉凶另见飞伏判。`,
  };
}

/* ───────────────────────── 月破的动与不动 ───────────────────────── */

/**
 * 月破三态。
 *
 * 《增删卜易·月破章第二十七》：「诸书皆以用神临月破如悖时也……虽有日辰之生，亦不能生，
 * 动而作忌神者不能为害。」野鹤则曰：「神兆机于动。事之无吉无凶则不动矣，既动则有祸福之基，
 * 目下虽破，出月则不破，今日虽破，实破之日则不破，合之日则不破，近应日远应年月。
 * 惟而不动又无日辰动爻生助者，则到底而破矣。」
 *
 * @param {{动:boolean, 有生助:boolean}} o
 * @returns {{判:string, 吉凶:string, 依据:string, 说明:string}}
 */
export function monthBreakVerdict(o = {}) {
  const 据 = '《增删卜易·月破章第二十七》';
  if (o.动) {
    return {
      判: '月破而动',
      吉凶: '半',
      依据: 据,
      说明: '野鹤之说「神兆机于动……目下虽破，出月则不破，今日虽破，实破之日则不破，合之日则不破」——'
        + '破而动者仍能伤爻，不可作「百无所用」看；应期在出月、实破或逢合之日月。',
    };
  }
  if (o.有生助) {
    return {
      判: '月破而得生助',
      吉凶: '半',
      依据: 据,
      说明: '破而静，幸有日辰或动爻生助——「虽有如无」之说不可尽拘，仍作有气论，待填实之期。',
    };
  }
  return {
    判: '月破到底',
    吉凶: '凶',
    依据: 据,
    说明: '破而不动、又无日辰动爻生助，「则到底而破矣」——此爻失力已尽，诸事难凭。',
  };
}

