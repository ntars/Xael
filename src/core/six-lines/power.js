/**
 * 六爻·元神忌神的有力与无力
 *
 * 来源：《增删卜易·元神忌神衰旺章第十》（refs-texts/《增删卜易》-清·野鹤老人.md 第 546–558 行）。
 *
 * 原书用四张清单把「元神能不能生用神」「忌神能不能克用神」逐条列出：
 *   ① 元神能生用神者五  ② 元神不能生用神者六
 *   ③ 忌神动而克害用神者五  ④ 忌神虽动不能克用神者七
 * 末句还立了一个总闸：「亦要用神有气，倘若用神无根，谓之元神有力亦难生，忌神无力何足喜。」
 *
 * 本模块只做「逐条命中」的定性判断——命中的条件照原文写出来，不打分、不加权。
 * 这与本项目「剔除自定权重」的口径一致：原书本来就没有权重，只有条件是否成立。
 */



import { ZHI_WX_MAP as ZHI_WX } from '../common/constants.js';
/** 五行相生：生我者 / 我生者 */
const SHENG_ME = { 木: '水', 火: '木', 土: '火', 金: '土', 水: '金' };
const SHENG = { 木: '火', 火: '土', 土: '金', 金: '水', 水: '木' };
const KE = { 木: '土', 火: '金', 土: '水', 金: '木', 水: '火' };
const WX_TOMB = { 木: '未', 火: '戌', 土: '辰', 金: '丑', 水: '辰' };
/** 生旺墓绝四位（《增删卜易·生旺墓绝章第又二十六》）：用于「长生帝旺于日辰」 */
const SHENG_WANG = {
  木: { 长生: '亥', 帝旺: '卯' },
  火: { 长生: '寅', 帝旺: '午' },
  金: { 长生: '巳', 帝旺: '酉' },
  水: { 长生: '申', 帝旺: '子' },
  土: { 长生: '申', 帝旺: '子' },
};

const 强弱档 = (t) => String((t && t.强弱) || '');
const 旺 = (t) => ['相'].indexOf(强弱档(t)) >= 0;
const 休 = (t) => ['衰', '弱有救'].indexOf(强弱档(t)) >= 0;
const 空破 = (t) => {
  const m = String((t && t.标记) || '');
  return { 空: m.indexOf('空') >= 0, 破: m.indexOf('破') >= 0 };
};
const 变支 = (t) => {
  const b = t && t.变;
  if (!b) return '';
  return String(b.变支 || b.支 || '').charAt(1) || String(b.变支 || b.支 || '');
};

/** 元神（或忌神）这一亲在卦中的一支（六亲可能两现，取动者优先，其次旺者） */
function pickLine(list) {
  const arr = (list && list.爻) || [];
  if (!arr.length) return null;
  return arr.filter((x) => x.动)[0] || arr.filter(旺)[0] || arr[0];
}

/**
 * 元神有力 / 无力
 *
 * @param {{原神:{五行:string,六亲:string,爻:Array}, 忌神:Object, 用神五行:string}} yj strength.js 的「元忌仇」
 * @param {{月支?:string, 日支?:string}} ctx
 */
export function yuanShenPower(yj, ctx = {}) {
  const t = pickLine(yj && yj.原神);
  if (!t) {
    return {
      判: '原神不上卦',
      力: '无',
      条: [{ 号: '无', 原文: '元神不上卦，须于宫首卦寻伏神', 命中: true }],
      依据: '《增删卜易·飞伏神章第二十八》',
      说明: '原神不上卦，卦中无生用神之爻，须寻伏神；伏神不生飞神者虽有如无。',
    };
  }
  const wx = (yj.原神 && yj.原神.五行) || ZHI_WX[String(t.干支 || '').charAt(1)];
  const zhi = String(t.干支 || '').charAt(1);
  const { 空, 破 } = 空破(t);
  const 日支 = ctx.日支 || '';
  const 月支 = ctx.月支 || '';
  const 日同 = 日支 && (ZHI_WX[日支] === wx || SHENG[ZHI_WX[日支]] === wx);
  const 月同 = 月支 && (ZHI_WX[月支] === wx || SHENG[ZHI_WX[月支]] === wx);
  // 「长生帝旺于日辰」＝该爻之支正落在本五行长生或帝旺之位（非「日支等于墓」）
  const 长生帝旺于日 = !!zhi && !!SHENG_WANG[wx] && (SHENG_WANG[wx].长生 === zhi || SHENG_WANG[wx].帝旺 === zhi);

  const 生条 = [
    { 号: '一', 原文: '元神旺相，或临日月，或日月动爻生扶者', 命中: 旺(t) || 日同 || 月同 },
    { 号: '二', 原文: '元神动化回头生，及化进神者', 命中: !!t.动 && (String((t.变 && t.变.标签) || '').indexOf('回头生') >= 0 || String((t.变 && t.变.标签) || '').indexOf('化进') >= 0) },
    { 号: '三', 原文: '元神长生帝旺于日辰', 命中: 长生帝旺于日 },
    { 号: '四', 原文: '元神与忌神同动', 命中: !!t.动 && ((yj.忌神 && yj.忌神.爻) || []).some((x) => x.动) },
    { 号: '五', 原文: '元神旺动，临空化空', 命中: !!t.动 && 旺(t) && 空 },
  ];
  const 不生条 = [
    { 号: '一', 原文: '元神休囚，不动，或动而休囚又被伤克者', 命中: 休(t) && (!t.动 || String(t.标记 || '').indexOf('克') >= 0) },
    { 号: '二', 原文: '元神休囚，又逢自空、月破', 命中: 休(t) && (空 || 破) },
    { 号: '三', 原文: '元神休囚，动化退神', 命中: 休(t) && !!t.动 && String((t.变 && t.变.标签) || '').indexOf('化退') >= 0 },
    { 号: '四', 原文: '元神衰而又绝', 命中: 休(t) && String(t.标记 || '').indexOf('绝') >= 0 },
    { 号: '五', 原文: '元神入三墓', 命中: String(t.标记 || '').indexOf('墓') >= 0 },
    { 号: '六', 原文: '元神休囚，动而化绝、化克、化破、化散', 命中: 休(t) && !!t.动 && /化绝|化克|化破|化散/.test(String((t.变 && t.变.标签) || '')) },
  ];
  const 有 = 生条.filter((x) => x.命中);
  const 无 = 不生条.filter((x) => x.命中);
  const 力 = 有.length && !无.length ? '有力' : (!有.length && 无.length ? '无力' : (有.length && 无.length ? '两见（须并看用神有无气）' : '平'));
  return {
    判: 力 === '有力' ? '原神有力，能生用神'
      : 力 === '无力' ? '原神无力，无用之元神（虽有如无）'
        : 力 === '两见（须并看用神有无气）' ? '原神吉凶条件两见，须并看用神有无根气'
          : '原神平（原文五条六条皆未全中，按旺衰参看）',
    力,
    条: 有.map((x) => ({ ...x, 类: '能生' })).concat(无.map((x) => ({ ...x, 类: '不能生' }))),
    依据: '《增删卜易·元神忌神衰旺章第十》',
    说明: '原文末句：「亦要用神有气，倘若用神无根，谓之元神有力亦难生，忌神无力何足喜。」',
  };
}

/**
 * 忌神有力 / 无力（原文作「忌神动而克害用神者五」「忌神虽动不能克用神者七」）
 *
 * @param {Object} yj strength.js 的「元忌仇」
 * @param {{月支?:string, 日支?:string}} ctx
 */
export function jiShenPower(yj, ctx = {}) {
  const t = pickLine(yj && yj.忌神);
  if (!t) {
    return {
      判: '忌神不上卦',
      力: '无',
      条: [{ 号: '无', 原文: '忌神不上卦', 命中: true }],
      依据: '《增删卜易·元神忌神衰旺章第十》',
      说明: '卦中无克用神之爻，用神不受忌神之害。',
    };
  }
  const wx = (yj.忌神 && yj.忌神.五行) || ZHI_WX[String(t.干支 || '').charAt(1)];
  const zhi = String(t.干支 || '').charAt(1);
  const { 空, 破 } = 空破(t);
  const 日支 = ctx.日支 || '';
  const 月支 = ctx.月支 || '';
  const 日同 = 日支 && (ZHI_WX[日支] === wx || SHENG[ZHI_WX[日支]] === wx);
  const 月同 = 月支 && (ZHI_WX[月支] === wx || SHENG[ZHI_WX[月支]] === wx);
  const 长生帝旺于日 = !!zhi && !!SHENG_WANG[wx] && (SHENG_WANG[wx].长生 === zhi || SHENG_WANG[wx].帝旺 === zhi);

  const 克条 = [
    { 号: '一', 原文: '忌神旺相，或遇日月动爻生扶，或临日月者', 命中: 旺(t) || 日同 || 月同 },
    { 号: '二', 原文: '忌神动化回头生扶', 命中: !!t.动 && String((t.变 && t.变.标签) || '').indexOf('回头生') >= 0 },
    { 号: '三', 原文: '忌神旺动，动临空、化空', 命中: !!t.动 && 旺(t) && 空 },
    { 号: '四', 原文: '忌神长生帝旺于日辰', 命中: 长生帝旺于日 },
    { 号: '五', 原文: '忌神与仇神同动', 命中: !!t.动 && ((yj.仇神 && yj.仇神.爻) || []).some((x) => x.动) },
  ];
  const 不克条 = [
    { 号: '一', 原文: '忌神休囚不动，而动休囚被日、月、动爻克者', 命中: 休(t) && (!t.动 || String(t.标记 || '').indexOf('克') >= 0) },
    { 号: '二', 原文: '忌神静临空破', 命中: !t.动 && (空 || 破) },
    { 号: '三', 原文: '忌神入三墓', 命中: String(t.标记 || '').indexOf('墓') >= 0 },
    { 号: '四', 原文: '忌神衰动化退神', 命中: 休(t) && !!t.动 && String((t.变 && t.变.标签) || '').indexOf('化退') >= 0 },
    { 号: '五', 原文: '忌神衰而又绝', 命中: 休(t) && String(t.标记 || '').indexOf('绝') >= 0 },
    { 号: '六', 原文: '忌神动化绝、化破、化克、化散', 命中: !!t.动 && /化绝|化破|化克|化散/.test(String((t.变 && t.变.标签) || '')) },
    { 号: '七', 原文: '忌神与元神同动', 命中: !!t.动 && ((yj.原神 && yj.原神.爻) || []).some((x) => x.动) },
  ];
  const 克 = 克条.filter((x) => x.命中);
  const 不克 = 不克条.filter((x) => x.命中);
  const 力 = 克.length && !不克.length ? '有力' : (!克.length && 不克.length ? '无力' : (克.length && 不克.length ? '两见（须并看用神有无气）' : '平'));
  return {
    判: 力 === '有力' ? '忌神有力，如斧戟之忌神（诸占大凶）'
      : 力 === '无力' ? '忌神无力，诸占化凶为吉'
        : 力 === '两见（须并看用神有无气）' ? '忌神吉凶条件两见，须并看用神有无根气'
          : '忌神平（原文五条七条皆未全中，按旺衰参看）',
    力,
    条: 克.map((x) => ({ ...x, 类: '能克' })).concat(不克.map((x) => ({ ...x, 类: '不能克' }))),
    依据: '《增删卜易·元神忌神衰旺章第十》',
    说明: '原文末句：「亦要用神有气，倘若用神无根，谓之元神有力亦难生，忌神无力何足喜。」',
  };
}

