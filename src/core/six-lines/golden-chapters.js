/**
 * src/core/six-lines/golden-chapters.js —— 六爻分门断法（据《黄金策》各门赋文）
 *
 * 大白话：六爻只讲「用神旺不旺」还不够——问财、问病、问官司，各有一套自己的看家口诀。
 * 这里把《黄金策》十九门里的赋文摘出来，做成「什么情况 → 怎么说」的对照表：
 * 程序先看卦里财爻、鬼爻、父母爻的真实状态，再挑出对得上的那几句原文。
 *
 * 原文出处：refs-texts/《黄金策》-明·刘基（题）.md，逐句照录书名与篇名（第 19 求财、
 *   第 24 词讼、第 10 疾病、第 28 出行、第 17 求名、第 7 婚姻）。赋文之后括号里的旧注
 *   一律不改写，只在需要解释判定口径时另写「说明」字段，不与原文混排。
 *
 * 设计原则：
 *   ① 只做定性判断（旺/衰/空/破/动/静），不打分、不加权；
 *   ② 同一门内多条同时成立时全部列出，不互相覆盖——原书本就并列陈述；
 *   ③ 认不出的门类返回 null，宁缺勿造。
 */

import { guaQiOf, guaQiGrade } from './gua-qi.js';

/** 六亲固定顺序（用于遍历） */
const QIN6 = ['父母', '兄弟', '子孙', '妻财', '官鬼'];

/** 地支五行（与六爻纳甲同表；不 import 免得循环依赖） */
const ZHI_WX = {
  子: '水', 丑: '土', 寅: '木', 卯: '木', 辰: '土', 巳: '火',
  午: '火', 未: '土', 申: '金', 酉: '金', 戌: '土', 亥: '水',
};
/** 五行相生：木生火、火生土、土生金、金生水、水生木 */
const SHENG = { 木: '火', 火: '土', 土: '金', 金: '水', 水: '木' };
/** 五行相克：木克土、土克水、水克火、火克金、金克木 */
const KE = { 木: '土', 土: '水', 水: '火', 火: '金', 金: '木' };
/** 取爻的五行的兜底：先看记录的五行，没有再按地支推 */
const wxOf = (x) => (x && (x.五行 || ZHI_WX[String(x.干支 || '').charAt(1)] || '')) || '';

/**
 * 把卦面整理成「每个六亲怎么样」的查表结果。
 * @param {object} cast  六爻排盘结果（sixLinesCast 的返回）
 * @param {object} st    旺衰结果（sixLinesStrengthOf 的返回）
 * @returns {{qin:object, 卦体:string, 世空:boolean, 应空:boolean, 世强:string, 应强:string}}
 */
export function goldenContextOf(cast, st) {
  const 爻 = (st && st.爻) || [];
  const qin = {};
  QIN6.forEach((q) => {
    const rows = 爻.filter((x) => x.六亲 === q);
    const 动 = rows.some((x) => x.动 || x.动静 === '动' || x.动静 === '发');
    // 强弱档：相／旺 = 强；衰／弱有救 = 弱；平居中；空亡、月破单独标
    const 强 = rows.some((x) => x.强弱 === '相' || x.强弱 === '旺');
    const 弱 = rows.some((x) => x.强弱 === '衰' || x.强弱 === '弱有救');
    qin[q] = {
      有: rows.length > 0,
      数量: rows.length,
      动,
      强,
      弱,
      空: rows.some((x) => x.空亡 || x.旬空),
      破: rows.some((x) => x.月破),
    };
  });
  const 世爻 = 爻.find((x) => x.世应 === '世') || {};
  const 应爻 = 爻.find((x) => x.世应 === '应') || {};
  const isDong = (x) => !!(x && (x.动 || x.动静 === '动' || x.动静 === '发'));
  const gw = cast && cast.卦体 ? cast.卦体 : {};
  const 世Wx = wxOf(世爻);
  const 应Wx = wxOf(应爻);
  // 世应关系照五行生克定名（《黄金策·词讼》「相克相冲，乃是欺凌之象；相生相合，终成和好之情」）
  let 世应 = '';
  if (世Wx && 应Wx) {
    if (SHENG[世Wx] === 应Wx) 世应 = '世生应';
    else if (SHENG[应Wx] === 世Wx) 世应 = '应生世';
    else if (KE[世Wx] === 应Wx) 世应 = '世克应';
    else if (KE[应Wx] === 世Wx) 世应 = '应克世';
    else 世应 = '比和';
  }
  const 官鬼爻 = 爻.find((x) => x.六亲 === '官鬼') || {};
  // 用神（占问之主爻）：取 strength 的首选用神爻，供《黄金策·逃亡》定「所临之方」用
  // 用神为「世」「应」时 st.用神爻 为空数组，须回落到世爻/应爻本身
  const 用爻 = (st && st.用神爻 && st.用神爻[0])
    || (st && st.用神 === '世' ? 世爻 : null)
    || (st && st.用神 === '应' ? 应爻 : null)
    || (st && st.用神伏神 && st.用神伏神[0]) // 用神不上卦时取伏神（其位仍有方向可论）
    || null;
  const 用支 = 用爻 ? String(用爻.干支 || '').charAt(1) : '';
  const 方位 = { 子: '正北', 丑: '东北', 寅: '东北', 卯: '正东', 辰: '东南', 巳: '东南',
    午: '正南', 未: '西南', 申: '西南', 酉: '正西', 戌: '西北', 亥: '西北' };
  const out = {
    qin,
    卦体: gw.标签 || '',
    六冲: !!gw.六冲卦,
    六合: !!gw.六合卦,
    世空: !!世爻.空亡,
    应空: !!应爻.空亡,
    世动: isDong(世爻),
    应动: isDong(应爻),
    世理: String(世爻.强弱 || ''),
    应理: String(应爻.强弱 || ''),
    世强: String(世爻.强弱 || ''),
    应强: String(应爻.强弱 || ''),
    世亲: String(世爻.六亲 || ''),
    应亲: String(应爻.六亲 || ''),
    世Wx,
    应Wx,
    世应,
    // 卦宫：cast.宫 形如「兑宫(金)」，取宫名为单字「兑」
    宫: String((cast && cast.宫) || '').replace(/宫.*$/, ''),
    // 卦气旺衰（八宫卦气，依《黄金策·身命》自注的八等顺推）
    卦气: (() => {
      const g = String((cast && cast.宫) || '').replace(/宫.*$/, '');
      const t = guaQiOf(String((st && st.月建) || (cast && cast.月建) || ''));
      return t ? (t.表[g] || '') : '';
    })(),
    // 事类未落到《增删卜易·用神章》表里时 st.用神 为 null，此时以世爻为用（自占以世为先）
    // 各亲的五行（取该亲首爻），《黄金策·天时》「须配五行参决」要用
    qinWx: QIN6.reduce((a, name) => {
      const row = 爻.find((x) => x.六亲 === name);
      a[name] = row ? String(wxOf(row) || '') : '';
      return a;
    }, {}),
    爻位: 爻.map((x) => ({
      爻: x.爻,
      六亲: String(x.六亲 || ''),
      空: !!(x.空亡 || x.旬空),
      破: !!x.月破,
      动: !!(x.动 || x.动静 === '动' || x.动静 === '发'),
      强: String(x.强弱 || ''),
      // 五行与六神：《黄金策·蚕桑》「初论火爻」「坎寻水位」与《黄金策·进人口》「临玄武」「遇青龙」要用
      五行: String(wxOf(x) || ''),
      六神: String(x.六神 || ''),
      世应: String(x.世应 || ''),
      标记: String(x.标记 || ''),
      // 变爻六亲：《黄金策·娼家》「财化福爻，家出从良之妓」要判「财动而变出子孙」
      变亲: (() => {
        const b = x.变;
        if (!b) return '';
        return String(b.六亲 || b.变亲 || '') || '';
      })(),
    })),
    // 火爻／水爻之有无与动静（《黄金策·蚕桑》：无火爻蚕必不旺、水爻当权发动则寒湿多灾）
    火爻有: 爻.some((x) => wxOf(x) === '火'),
    水爻有: 爻.some((x) => wxOf(x) === '水'),
    水动: 爻.some((x) => wxOf(x) === '水' && isDong(x)),
    火动: 爻.some((x) => wxOf(x) === '火' && isDong(x)),
    // 用神爻的六神与同亲数量（《黄金策·进人口》「临玄武」「遇青龙」「太过」）
    用神六神: 用爻 ? String(用爻.六神 || '') : '',
    用神数量: 用爻 ? 爻.filter((x) => x.六亲 === 用爻.六亲).length : 0,
    用神: (st && st.用神) || (用爻 && 用爻 === 世爻 ? '世' : (用爻 ? String(用爻.六亲 || '') : '')),
    用神支: 用支,
    用神方位: 方位[用支] || '',
    用神动: !!(用爻 && (用爻.动 || 用爻.动静 === '动' || 用爻.动静 === '发')),
    用神变支: (() => {
      const b = 用爻 && 用爻.变;
      if (!b) return '';
      return String(b.变支 || b.支 || '').charAt(1) || String(b.变支 || b.支 || '');
    })(),
    用神变方位: '',
    用神标记: 用爻 ? String(用爻.标记 || '') : '',
    用神强弱: 用爻 ? String(用爻.强弱 || '') : '',
    // 「鬼克身爻」「鬼作问官克应」都要看官鬼之五行是否真克世/应
    鬼Wx: String(wxOf(官鬼爻) || ''),
    鬼动: isDong(官鬼爻),
    // 《黄金策·舟船》以螣蛇为索缆、白虎为帆樯，故单列两神之状态
    蛇空: (() => {
      const x = 爻.find((r) => String(r.六神 || '') === '螣蛇');
      return !!(x && (x.空亡 || x.旬空));
    })(),
    虎动: (() => {
      const x = 爻.find((r) => String(r.六神 || '') === '白虎');
      return !!(x && isDong(x));
    })(),
    虎克世: (() => {
      const x = 爻.find((r) => String(r.六神 || '') === '白虎');
      return !!(x && 世Wx && KE[wxOf(x)] === 世Wx);
    })(),
    // 世爻是否受动爻（他爻）克——「世为大块，受克则天变非常」
    世受克: 爻.some((x) => isDong(x) && x !== 世爻 && 世Wx && KE[wxOf(x)] === 世Wx),
    // 《黄金策·鬼神》要按官鬼所乘六神、所带标记（墓/绝/刑）与在卦与否断鬼神情状
    鬼有: !!官鬼爻.六亲,
    鬼空: !!(官鬼爻.空亡 || 官鬼爻.旬空),
    鬼六神: String(官鬼爻.六神 || ''),
    鬼标记: String(官鬼爻.标记 || ''),
    // 《黄金策·坟墓》「绝嗣无人，端为世居五六」要看世爻位次
    世位: Number(世爻.爻 || 0),
    // 《黄金策·娼家》「财化福爻」：妻财发动而变出子孙
    财化福: 爻.some((x) => x.六亲 === '妻财' && isDong(x) && String((x.变 && (x.变.六亲 || x.变.变亲)) || '') === '子孙'),
    // 《黄金策·年时》「发动妻财，旱若成汤之日」「交重父母，涝如尧帝之时」
    财动: 爻.some((x) => x.六亲 === '妻财' && isDong(x)),
    父动: 爻.some((x) => x.六亲 === '父母' && isDong(x)),
    兄强: 爻.some((x) => x.六亲 === '兄弟' && String(x.强弱 || '') === '相'),
    // 「猛烈火官」「汪洋水鬼」「尤怕属金」「更嫌值土」——按官鬼五行取（已在鬼Wx）
    // 「遇勾陈而加世位」「因螣蛇之御世」「由玄武之当官」——看世爻所乘与官鬼所乘
    勾世: String(世爻.六神 || '') === '勾陈',
    蛇世: String(世爻.六神 || '') === '螣蛇',
    玄官: String(官鬼爻.六神 || '') === '玄武',
    // 「逢朱雀而化福爻，财动则旱蝗相继」——朱雀爻发动而变出子孙
    朱化福: 爻.some((x) => String(x.六神 || '') === '朱雀' && isDong(x) && String((x.变 && (x.变.六亲 || x.变.变亲)) || '') === '子孙'),
    // 《黄金策·年时》「冬暖夏凉，水火休囚而莫助」——《黄金策·坟墓》「死绝之鬼」「长生之爻」
    火有: 爻.some((x) => wxOf(x) === '火'),
    水有: 爻.some((x) => wxOf(x) === '水'),
    火强: 爻.some((x) => wxOf(x) === '火' && /相|旺/.test(String(x.强弱 || ''))),
    水强: 爻.some((x) => wxOf(x) === '水' && /相|旺/.test(String(x.强弱 || ''))),
    游魂: !!(cast && cast.卦体 && cast.卦体.游魂),
    归魂: !!(cast && cast.卦体 && cast.卦体.归魂),
    // 世爻所乘六亲（「持世则未酬旧愿」「世持兄弟」等）——已在世亲
    鬼死绝: /死|绝/.test(String(官鬼爻.标记 || '')),
    // 《黄金策·年时》「应亦为天，克世则天心不顺」
    应克世: !!世Wx && !!应Wx && KE[应Wx] === 世Wx,
    // 《黄金策·坟墓》「长生之爻，中有寿穴」「穴中为日冲开」
    有长生: 爻.some((x) => String(x.标记 || '').indexOf('长生') >= 0),
    世逢冲: String(世爻.标记 || '').indexOf('冲') >= 0,
    // 《黄金策·娼家》「财兴克世」要判妻财之五行是否克世
    财Wx: String(wxOf(爻.find((x) => x.六亲 === '妻财')) || ''),
    官鬼克世: !!官鬼爻.六亲 && !!世Wx && KE[wxOf(官鬼爻)] === 世Wx,
    官鬼克应: !!官鬼爻.六亲 && !!应Wx && KE[wxOf(官鬼爻)] === 应Wx,
  };
  out.用神变方位 = 方位[out.用神变支] || '';
  return out;
}

/** 取某亲的状态；卦中不上此亲时给一个空壳，避免调用处到处判空 */
function q(ctx, name) {
  return (ctx.qin && ctx.qin[name]) || { 有: false, 数量: 0, 动: false, 强: false, 弱: false, 空: false, 破: false };
}

const 六冲 = (ctx) => !!ctx.六冲;
const 六合 = (ctx) => !!ctx.六合;

