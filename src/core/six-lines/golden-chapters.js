/**
 * 取某门的分门断法。
 * @param {string} 事  事类（财运／官司／疾病／出行／学业／婚姻…）
 * @param {object} ctx goldenContextOf() 的结果
 * @returns {{章:string, 用神原文:string, 命中:Array<{断:string, 原文:string}>}|null}
 */
export function goldenVerdictsOf(事, ctx) {
  const key = MATTER_TO_CHAPTER[事];
  if (!key || !CHAPTERS[key] || !ctx || !ctx.qin) return null;
  const ch = CHAPTERS[key];
  const 命中 = [];
  ch.条目.forEach((it) => {
    let ok = false;
    try {
      ok = !!it.判(ctx);
    } catch (e) {
      ok = false; // 单条判定异常不影响其余条目
    }
    if (ok) 命中.push({ 断: it.断, 原文: it.原文 });
  });
  return { 章: ch.章, 用神原文: ch.用神原文, 命中 };
}

/** 供测试与文档用：列出全部已接入的门类 */
export function goldenChapterNames() {
  return Object.keys(CHAPTERS).map((k) => ({ 事: k, 章: CHAPTERS[k].章, 条数: CHAPTERS[k].条目.length }));
}

export default { goldenContextOf, goldenVerdictsOf, goldenChapterNames };
