/* ============================== 六亲 / 六神 ============================== */
/**
 * 六亲：以卦宫五行为「我」。
 *   同我 = 兄弟；我生 = 子孙；生我 = 父母；我克 = 妻财；克我 = 官鬼。
 */
export function qinOf(爻五行, 宫五行) {
  if (爻五行 === 宫五行) return '兄弟';
  if (WX_SHENG[宫五行] === 爻五行) return '子孙';
  if (WX_SHENG[爻五行] === 宫五行) return '父母';
  if (WX_KE[宫五行] === 爻五行) return '妻财';
  if (WX_KE[爻五行] === 宫五行) return '官鬼';
  return '兄弟';
}

/** 六亲 → 五行（qinOf 的反函数） */
export function qinWx(六亲, 宫五行) {
  if (六亲 === '兄弟') return 宫五行;
  if (六亲 === '父母') return wxShengWo(宫五行);
  if (六亲 === '子孙') return WX_SHENG[宫五行];
  if (六亲 === '妻财') return WX_KE[宫五行];
  if (六亲 === '官鬼') return wxKeWo(宫五行);
  return '';
}

/** 五行 → 六亲 */
export function qinOfWx(五行, 宫五行) {
  if (!五行 || !宫五行) return '';
  if (五行 === 宫五行) return '兄弟';
  if (五行 === wxShengWo(宫五行)) return '父母';
  if (五行 === WX_SHENG[宫五行]) return '子孙';
  if (五行 === WX_KE[宫五行]) return '妻财';
  if (五行 === wxKeWo(宫五行)) return '官鬼';
  return '';
}

