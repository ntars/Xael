/** 六十四卦须齐全、八宫各八卦、世应不重 */
export function assertTables() {
  const names = Object.keys(GUA_INDEX);
  if (names.length !== 64) throw new Error(`six-lines/tables: 卦数应为 64，实为 ${names.length}`);
  Object.keys(PALACES).forEach((p) => {
    if (PALACES[p].length !== 8) throw new Error(`six-lines/tables: ${p} 宫应为 8 卦`);
  });
  if (SHI_YING.length !== 8) throw new Error('six-lines/tables: SHI_YING 应为 8 项');
  if (Object.keys(NAJIA).length !== 8) throw new Error('six-lines/tables: NAJIA 应为 8 卦');
  // 乾为天：纳甲须为 甲子…壬戌
  const q = yaGanZhi('乾', '乾');
  if (q[0] !== '甲子' || q[5] !== '壬戌') throw new Error('six-lines/tables: 乾卦纳甲不对');
  // 六亲和反函数互验
  if (qinWx('官鬼', '金') !== '火') throw new Error('six-lines/tables: qinWx 官鬼(金) 应为 火');
  if (qinOfWx('火', '金') !== '官鬼') throw new Error('six-lines/tables: qinOfWx 火/金 应为 官鬼');
  return true;
}

