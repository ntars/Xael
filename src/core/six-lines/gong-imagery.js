/**
 * src/core/six-lines/gong-imagery.js —— 六爻「以八卦参之」：八宫类象 + 年命与卦宫之鬼（自研，零依赖）
 *
 * 大白话：六爻本来以五行生克为主，但原书明说还要「再以八卦参之」——
 *   占到乾、兑两宫，事情常与寺庙、金属器物有关；占到震宫，常与车船有关。
 *   另一层是「年命」：卦宫有一个克它的神（卦宫之鬼），这个鬼若与本命相生相克，吉凶就落到人身上。
 *
 * 依据（库内原文）：
 *   · 《增删卜易》-清·野鹤老人 refs-texts 第 2446 行——
 *     「既以五行六神而定，**再以八卦参之，乾兑为寺，又属金形，坎兑以水为灾，离以火，
 *       震有舟车，巽防妇女之奸，坤艮郊野山林，又为老妇妖童之惑**，诸类多门，在人通变。」
 *   · 《黄金策·家宅》refs-texts 第 2653–2654 行——
 *     「**木金年命，最嫌乾兑卦之火爻**」
 *     注：「木金年命人占得乾兑卦，以火为鬼爻，木生火爻为鬼能助火克金为杀伤身，但本命生鬼为助。
 *       本命受鬼克为伤身，金年木命皆然。木命人忌震巽宫鬼，水命忌坎宫鬼是也。」
 *
 * 不做的事（不臆造）：
 *   · 「坎兑以水为灾」一句句读两可（可读作「坎以水为灾、兑以…」，也可连读为「坎、兑以水为灾」），
 *     本仓**照录原文不改**，并把两可处写进说明，不替读者断句；
 *   · 八宫类象只是「象」，不加吉凶分、不与六神合并打分；
 *   · 未给本命时年命判整块不出，不默认任何本命。
 */

import { ZHI_WX, WX_KE, WX_SHENG, ZHI_Z } from './tables.js';

/** 八宫类象：照录《增删卜易》原文用语，不做现代意译 */
export const GONG_IMAGERY = {
  乾: { 象: '寺、金形', 原文: '乾兑为寺，又属金形' },
  兑: { 象: '寺、金形（另有「水为灾」一说）', 原文: '乾兑为寺，又属金形；坎兑以水为灾' },
  坎: { 象: '水为灾', 原文: '坎兑以水为灾' },
  离: { 象: '火', 原文: '离以火' },
  震: { 象: '舟车', 原文: '震有舟车' },
  巽: { 象: '妇女之奸', 原文: '巽防妇女之奸' },
  坤: { 象: '郊野山林、老妇之惑', 原文: '坤艮郊野山林，又为老妇妖童之惑' },
  艮: { 象: '郊野山林、妖童之惑', 原文: '坤艮郊野山林，又为老妇妖童之惑' },
};

export const GONG_IMAGERY_NOTE = '「坎兑以水为灾」句读两可（可读作「坎以水为灾、兑以…」或连读为「坎、兑」），此处照录原文不断句，读者自择。';

/** 八卦宫五行（乾兑金、震巽木、坎水、离火、坤艮土） */
const GONG_WX = { 乾: '金', 兑: '金', 震: '木', 巽: '木', 坎: '水', 离: '火', 坤: '土', 艮: '土' };

/**
 * 卦宫类象。
 * @param {string} gong 单字宫名（乾/兑/震/巽/坎/离/坤/艮），可传入 chart['宫'] 那种「坎宫(水)」形式
 */
export function gongImageryOf(gong) {
  const g = String(gong || '').replace(/宫.*$/, '').trim();
  const hit = GONG_IMAGERY[g];
  if (!hit) return null;
  return {
    宫: g,
    五行: GONG_WX[g],
    象: hit.象,
    原文: hit.原文,
    说明: (g === '兑' || g === '坎') ? GONG_IMAGERY_NOTE : '',
    依据: '《增删卜易》——「既以五行六神而定，再以八卦参之」',
  };
}

/**
 * 年命与卦宫之鬼。
 * 卦宫之鬼 = 克宫五行的那个五行（乾兑金 → 火为鬼，如《黄金策》注「以火为鬼爻」）。
 * @param {string} benMing 本命地支或干支（如 '子' 或 '甲子'）
 * @param {string} gong 宫名
 */
export function benMingGuiOf(benMing, gong) {
  const g = String(gong || '').replace(/宫.*$/, '').trim();
  const z = String(benMing || '').match(/([子丑寅卯辰巳午未申酉戌亥])$/);
  if (!GONG_WX[g] || !z) return null;
  const 宫Wx = GONG_WX[g];
  const 命Wx = ZHI_WX[z[1]];
  if (!命Wx) return null;
  // 卦宫之鬼＝克宫五行者（乾兑金 → 火为鬼，与《黄金策》注「以火为鬼爻」一致）
  const 鬼Wx = Object.keys(WX_KE).find((k) => WX_KE[k] === 宫Wx);

  let 判 = '';
  let 吉凶 = '平';
  if (WX_SHENG[命Wx] === 鬼Wx) {
    判 = '本命助鬼'; 吉凶 = '凶';
  } else if (WX_KE[鬼Wx] === 命Wx) {
    判 = '鬼克身（伤身）'; 吉凶 = '凶';
  } else if (WX_KE[命Wx] === 鬼Wx) {
    判 = '本命制鬼'; 吉凶 = '吉';
  } else {
    判 = '本命与卦宫之鬼无生克'; 吉凶 = '平';
  }

  return {
    本命: z[1], 宫: g, 宫五行: 宫Wx, 鬼五行: 鬼Wx,
    判, 吉凶,
    说明: `本命${z[1]}属${命Wx}，${g}宫属${宫Wx}，其鬼为${鬼Wx}；${判}`,
    依据: '《黄金策·家宅》——「木金年命，最嫌乾兑卦之火爻」及其注',
  };
}
