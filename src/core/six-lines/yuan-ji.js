/**
 * 原神 / 忌神 吉凶判（《卜筮正宗·原神歌》《卜筮正宗·忌神歌》原文落地）
 *
 * 库内原文（refs-texts/《卜筮正宗》-清·王洪绪.md 第 350–358 行）：
 *   忌神歌：看卦先须看忌神，忌神宜静不宜兴，忌神急要逢伤克，若遇生扶用受刑。
 *   原神歌：原神发动志扬扬，用伏藏兮也不妨，须要生扶兼旺相，最嫌化克及逢伤。
 *   用神发动诀：用爻发动在宫中，纵值休囚亦不凶，更得生扶兼旺相，管教作事永亨通。
 *   日辰诀：问卦先须看日辰，日辰克用不堪亲，日辰与用相生合，作事何愁不起心。
 *
 * 大白话：原神是「帮用神的那一方」，忌神是「打用神的那一方」。
 *   · 原神越好用神越有靠山——发动、得日月生扶、旺相皆吉；最怕它自己化出回头克、或受日月伤克。
 *   · 忌神越静越好——宜静不宜兴；它若发动、又得日月生扶，用神就受刑；它若被日月冲克，反是好事。
 *   · 用神自己发动不算坏（「纵值休囚亦不凶」），得生扶旺相更好。
 *   · 日辰最要紧：日辰克用=不堪亲；日辰与用相生相合=吉。
 *
 * 本模块只做「按原文语序」的定性判断，不打分、不算权重。
 */

const SHENG = { 木: '火', 火: '土', 土: '金', 金: '水', 水: '木' };
const KE = { 木: '土', 土: '水', 水: '火', 火: '金', 金: '木' };
/** 冲我者（取该五行的克我者） */
const KE_WO = Object.keys(KE).reduce((m, k) => { m[KE[k]] = k; return m; }, {});

/** 某一爻的「动静 + 变爻吉凶」摘要 */
function lineState(t) {
  if (!t) return null;
  const 变项 = (t.变 && t.变.项) || [];
  const 回头克 = 变项.some((x) => x.name === '回头克');
  const 回头生 = 变项.some((x) => x.name === '回头生');
  // ★ 衰弱不可查「旺衰」字段：其取值为「休囚有气（有救）／相（有气）／月破失力／
  //   休囚（无根无助）／平（得日辰之助）」，一个「衰」字也没有。
  //   真正的强弱档在「强弱」字段（衰／弱有救／平／相），故此处两字段并看。
  const 强弱 = String(t.强弱 || '');
  const 衰 = 强弱 === '衰' || 强弱 === '弱有救' || !!t.月破;
  return { 动: !!t.动, 回头克, 回头生, 旺衰: t.旺衰 || '', 强弱, 衰, 空亡: !!t.空亡, 月破: !!t.月破 };
}

/**
 * 原神是否得用（据《卜筮正宗·原神歌》）
 * @param {object} yj 元忌仇对象（strength.js 输出）
 * @returns {object|null} {判, 吉凶, 依据, 说明}
 */
export function yuanShenVerdict(yj) {
  const ys = yj && yj.原神;
  if (!ys) return null;
  const 爻们 = (ys.爻 || []).map(lineState).filter(Boolean);
  if (!爻们.length) {
    return {
      判: '原神不上卦', 吉凶: '平',
      依据: '《卜筮正宗·原神歌》',
      说明: `原神${ys.六亲}（${ys.五行}）不上卦——用神无现成之靠，须看伏神或待其值日、出空之时；`
        + '原歌「原神发动志扬扬，用伏藏兮也不妨」，指原神若现而旺动，用神纵伏亦无妨。',
    };
  }
  const 动者 = 爻们.filter((x) => x.动);
  const 被克 = 爻们.filter((x) => x.回头克);
  const 得生 = 爻们.filter((x) => x.回头生);
  const 衰者 = 爻们.filter((x) => x.衰);
  if (被克.length) {
    return {
      判: '原神受伤', 吉凶: '凶',
      依据: '《卜筮正宗·原神歌》「最嫌化克及逢伤」',
      说明: `原神${ys.六亲}发动而化出回头克，是「化克」——靠山自身受伤，用神失援；`
        + '宜待克神受制之期，或另择时再占。',
    };
  }
  if (动者.length && (得生.length || !衰者.length)) {
    return {
      判: '原神发动得势', 吉凶: '吉',
      依据: '《卜筮正宗·原神歌》「原神发动志扬扬……须要生扶兼旺相」',
      说明: `原神${ys.六亲}发动${得生.length ? '、又化回头生' : ''}，旺相有力——`
        + '用神得靠，谋事有援，虽用神伏藏亦不妨。',
    };
  }
  if (!衰者.length) {
    return {
      判: '原神安静有气', 吉凶: '吉',
      依据: '《卜筮正宗·原神歌》',
      说明: `原神${ys.六亲}安静而旺相，虽未发动亦能生扶用神；事有依托，不必急进。`,
    };
  }
  return {
    判: '原神衰弱', 吉凶: '凶',
    依据: '《卜筮正宗·原神歌》「须要生扶兼旺相」',
    说明: `原神${ys.六亲}休囚无气（${爻们.map((x) => x.旺衰).filter(Boolean).join('、') || '衰弱'}），`
      + '生扶之力不足，用神少靠；宜待原神得生扶之月日。',
  };
}

/**
 * 忌神是否得势（据《卜筮正宗·忌神歌》）
 * @param {object} yj 元忌仇对象
 * @returns {object|null} {判, 吉凶, 依据, 说明}
 */
export function jiShenVerdict(yj) {
  const js = yj && yj.忌神;
  if (!js) return null;
  const 爻们 = (js.爻 || []).map(lineState).filter(Boolean);
  if (!爻们.length) {
    return {
      判: '忌神不上卦', 吉凶: '吉',
      依据: '《卜筮正宗·忌神歌》',
      说明: `忌神${js.六亲}（${js.五行}）不上卦——克用神者未现，用神无当面之敌，事少阻碍。`,
    };
  }
  const 兴者 = 爻们.filter((x) => x.动);
  const 被伤 = 爻们.filter((x) => x.回头克 || x.月破);
  const 衰者 = 爻们.filter((x) => x.衰);
  if (被伤.length) {
    return {
      判: '忌神受伤', 吉凶: '吉',
      依据: '《卜筮正宗·忌神歌》「忌神急要逢伤克」',
      说明: `忌神${js.六亲}${爻们.some((x) => x.月破) ? '临月破' : '化回头克'}——正合原歌「忌神急要逢伤克」，`
        + '克用之力自损，用神反得其便。',
    };
  }
  if (兴者.length) {
    return {
      判: '忌神发动', 吉凶: '凶',
      依据: '《卜筮正宗·忌神歌》「忌神宜静不宜兴……若遇生扶用受刑」',
      说明: `忌神${js.六亲}发动，是「兴」——${衰者.length ? '虽现衰弱，仍须防其得生扶之期' : '旺相有力'}，`
        + '用神受刑；宜避其锋，待忌神受制之月日再图。',
    };
  }
  if (衰者.length) {
    return {
      判: '忌神衰弱安静', 吉凶: '吉',
      依据: '《卜筮正宗·忌神歌》「忌神宜静不宜兴」',
      说明: `忌神${js.六亲}安静且休囚无气，克用无力，事无大碍。`,
    };
  }
  return {
    判: '忌神安静有气', 吉凶: '平',
    依据: '《卜筮正宗·忌神歌》',
    说明: `忌神${js.六亲}安静未动，暂不为害；然其气未衰，若逢生扶之月日仍须防之。`,
  };
}

/**
 * 用神发动（据《卜筮正宗·用神发动诀》）
 * @param {Array} 用神爻 用神各爻（strength 输出 用神爻）
 */
export function yongFaDongVerdict(用神爻) {
  const 爻们 = (用神爻 || []).map((t) => ({
    动: !!t.动, 回头克: !!((t.变 && t.变.项) || []).some((x) => x.name === '回头克'),
    旺衰: t.旺衰 || '', 空亡: !!t.空亡, 月破: !!t.月破,
  })).filter(Boolean);
  if (!爻们.length) return null;
  const 动者 = 爻们.filter((x) => x.动);
  if (!动者.length) return null;
  const 有伤 = 动者.some((x) => x.回头克 || x.月破 || x.空亡);
  return {
    判: 有伤 ? '用神发动而有伤' : '用神发动',
    吉凶: 有伤 ? '平' : '吉',
    依据: '《卜筮正宗·用神发动诀》「用爻发动在宫中，纵值休囚亦不凶；更得生扶兼旺相，管教作事永亨通」',
    说明: 有伤
      ? '用神发动，原诀「纵值休囚亦不凶」；然此爻另有空破或化克之伤，旺相时可冲散，休囚则难免拖累。'
      : '用神发动，纵使休囚亦不为凶——动则有力，事在推动之中；若更得日月生扶、卦中旺相，则作事亨通。',
  };
}

/**
 * 日辰与用神（据《卜筮正宗·日辰诀》）
 * @param {string} 用神五行
 * @param {string} 日支
 */
export function riChenVerdict(用神五行, 日支) {
  if (!用神五行 || !日支) return null;
  const ZHI_WX = { 子: '水', 丑: '土', 寅: '木', 卯: '木', 辰: '土', 巳: '火', 午: '火', 未: '土', 申: '金', 酉: '金', 戌: '土', 亥: '水' };
  const 日Wx = ZHI_WX[日支];
  if (!日Wx) return null;
  const 生合 = SHENG[日Wx] === 用神五行 || 日Wx === 用神五行
    || (SHENG[用神五行] === 日Wx ? false : false);
  if (KE[日Wx] === 用神五行) {
    return {
      判: '日辰克用', 吉凶: '凶',
      依据: '《卜筮正宗·日辰诀》「日辰克用不堪亲」',
      说明: `日辰${日支}（${日Wx}）克用神（${用神五行}）——原诀直断「不堪亲」，眼下强求无益，宜待日辰相生或值日之时。`,
    };
  }
  if (生合) {
    return {
      判: '日辰生用', 吉凶: '吉',
      依据: '《卜筮正宗·日辰诀》「日辰与用相生合，作事何愁不起心」',
      说明: `日辰${日支}（${日Wx}）${日Wx === 用神五行 ? '与用神同气（扶）' : '生用神'}——原诀「作事何愁不起心」，当日即为得力之期。`,
    };
  }
  if (KE[用神五行] === 日Wx) {
    return {
      判: '用神克日', 吉凶: '平',
      依据: '《卜筮正宗·日辰诀》',
      说明: `用神（${用神五行}）克日辰${日支}（${日Wx}）——用神耗力，成事要费力；原诀未列此格，只作中性看。`,
    };
  }
  if (SHENG[用神五行] === 日Wx) {
    return {
      判: '用神生日', 吉凶: '平',
      依据: '《卜筮正宗·日辰诀》',
      说明: `用神（${用神五行}）生日辰${日支}（${日Wx}）——用神泄气，力减；原诀未列此格，只作中性看。`,
    };
  }
  return null;
}

