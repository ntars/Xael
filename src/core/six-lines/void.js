/**
 * src/core/six-lines/void.js —— 六爻·空亡真假（真空 / 假空）的判定
 * 本文件只做空亡真假的归类，不含任何权重算式，也不参与吉凶打分。
 *
 * 文献依据：《卜筮正宗·用神空亡诀》（清·王洪绪）与《增删卜易·旬空章》。
 */

import { ZHI_Z, ZHI_WX, WX_SHENG as SHENG, WX_KE as KE } from './tables.js';

const BRANCHES = ZHI_Z.join('');
const zIdx = (z) => BRANCHES.indexOf(z);
/** 六冲：地支序 +6 */
const clash = (a, b) => !!(a && b) && BRANCHES[(zIdx(a) + 6) % 12] === b;

/* ===================== 空亡真假（真空 / 假空） ===================== */
/**
 * 《卜筮正宗·用神空亡诀》（清·王洪绪）把空亡分成「真空」与「非真空」两类，给了可判的判据：
 *   「发动逢冲不谓空，静空遇克却为空，忌神最喜逢空吉，用与原神不可空，
 *     春土夏金秋树木，三冬逢火是真空，旬空又值真空象，再遇爻伤到底空。」
 *
 * 逐句落实（只判真假，不掺任何分值）：
 *   · 「发动逢冲不谓空」——爻既发动，又得日辰/动爻冲起，不作空论（冲空则实）。
 *   · 「静空遇克却为空」——安静之爻逢空、又被日月动爻所克，才是真空。
 *   · 「春土夏金秋树木，三冬逢火是真空」——当令之气反来克它（春木克土、夏火克金、
 *     秋金克木、冬水克火），是「真空」的典型：空而逢克，克者当令，到底成空。
 *   · 「旬空又值真空象，再遇爻伤到底空」——既真空、又被爻克，为「到底空」，无可救。
 * 反向（假空/不作空）：旺相、发动、得日辰或动爻生扶——见《增删卜易·旬空章》
 *   「旺不为空，动不为空，有日建动爻生扶者不为空」。
 *
 * @param {string} 爻支   该爻地支
 * @param {string} 爻五行 该爻五行
 * @param {string} 月支   月建地支
 * @param {string} 日支   日辰地支
 * @param {boolean} 发动  该爻是否发动
 * @param {string[]} 动支 卦中其余动爻的地支（用于判「动爻冲起」）
 * @returns {{真空:boolean, 到底空:boolean, 类:string, 依据:string}}
 */
export function voidVerdict(爻支, 爻五行, 月支, 日支, 发动, 动支) {
  const 月Wx = ZHI_WX[月支];
  const 日Wx = ZHI_WX[日支];
  const 动 = Array.isArray(动支) ? 动支.filter((z) => z && z !== 爻支) : [];
  const 日冲 = clash(爻支, 日支);
  const 动冲 = 动.some((z) => clash(爻支, z));
  const 有生 = (!!月Wx && SHENG[月Wx] === 爻五行) || (!!日Wx && SHENG[日Wx] === 爻五行);
  const 得扶 = (!!月Wx && 月Wx === 爻五行) || (!!日Wx && 日Wx === 爻五行);
  const 受克 = (!!月Wx && KE[月Wx] === 爻五行) || (!!日Wx && KE[日Wx] === 爻五行);
  // 当令之气反克（春土夏金秋树木、三冬逢火）：月建克它即为当令之克
  const 当令克 = !!月Wx && KE[月Wx] === 爻五行;

  // 「冲空则实」优先于一切：《增删卜易·旬空章》「爻遇旬空，日辰冲起而有用，谓之冲空则实」，
  //   同篇又列「冲空、填空」为旬空诸名之一；《卜筮正宗·用神空亡诀》「发动逢冲不谓空」
  //   是同一件事在发动爻上的说法。故日辰冲、或卦中动爻冲，皆作「冲空则实」。
  if (日冲 || 动冲) {
    return {
      真空: false, 到底空: false, 类: '冲空则实（不作空论）',
      依据: '《增删卜易·旬空章》「爻遇旬空，日辰冲起而有用，谓之冲空则实」；《卜筮正宗·用神空亡诀》「发动逢冲不谓空」',
    };
  }
  // 《增删卜易·旬空章》「旺不为空，动不为空，有日建动爻生扶者不为空」
  if (发动) {
    return { 真空: false, 到底空: false, 类: '动不为空', 依据: '《增删卜易·旬空章》「动不为空」' };
  }
  if (得扶 || 有生) {
    return { 真空: false, 到底空: false, 类: '假空（有扶）', 依据: '《增删卜易·旬空章》「旺不为空，有日建动爻生扶者不为空」' };
  }
  // 「静空遇克却为空」+「三冬逢火是真空」
  if (受克 || 当令克) {
    // 「旬空又值真空象，再遇爻伤到底空」——既已真空，卦中动爻又来克它（爻伤），更无解
    const 爻伤 = 动.some((z) => ZHI_WX[z] && KE[ZHI_WX[z]] === 爻五行);
    if (爻伤) {
      return { 真空: true, 到底空: true, 类: '到底空', 依据: '《卜筮正宗·用神空亡诀》「旬空又值真空象，再遇爻伤到底空」' };
    }
    return {
      真空: true, 到底空: false, 类: '真空',
      依据: 当令克
        ? '《卜筮正宗·用神空亡诀》「春土夏金秋树木，三冬逢火是真空」——空而逢当令之克'
        : '《卜筮正宗·用神空亡诀》「静空遇克却为空」',
    };
  }
  return { 真空: false, 到底空: false, 类: '空而未受克', 依据: '《增删卜易·旬空章》「旺不为空，动不为空」——未受克，出旬可实' };
}

