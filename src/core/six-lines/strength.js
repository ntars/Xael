  if (JIN[本支] === 变支) tags.push({ name: '化进神', 级: '吉', 断: `动爻化进神（${本支}→${变支}）：势增，吉事倍增其势，凶事亦加其凶。` });
  if (TUI[本支] === 变支) tags.push({ name: '化退神', 级: '凶', 断: `动爻化退神（${本支}→${变支}）：势减，吉凶皆渐减其威，虎头蛇尾。` });


