/** ③ vigorLevel（《增删卜易》日月权衡表直接落地，只出定性档位） */
export function vigorLevel(月类, 日类) {
  if (月类 === '月破' && (日类 === '日克' || 日类 === '日耗' || 日类 === '日泄')) return '衰败已极';
  if (月类 === '月破' && 日类 === '临日辰') return '月破反作暗动（值日不破）';
  if (月类 === '月破') return '月破失力';
  if (月类 === '月克' && 日类 === '日克') return '休囚无救';
  if (月类 === '月克' && (日类 === '日生' || 日类 === '日扶' || 日类 === '临日辰')) return '休囚有气（有救）';
  if (月类 === '临月建' && 日类 === '临日辰') return '旺上加旺';
  if (月类 === '临月建' && (日类 === '日生' || 日类 === '日扶')) return '旺（有根有力）';
  if ((月类 === '月生' || 月类 === '月扶') && 日类 === '临日辰') return '得时得地';
  if (月类 === '临月建') return '旺（有根）';
  if (月类 === '月生' || 月类 === '月扶') return '相（有气）';
  if (日类 === '临日辰' || 日类 === '日生' || 日类 === '日扶') return '平（得日辰之助）';
  if (月类 === '未定' && 日类 === '未定') return '未定';
  return '休囚（无根无助）';
}

/** 档位 → 强弱分档（定性，不打分） */
export function levelStrength(档) {
  if (/旺上加旺|有根有力|得时得地/.test(档)) return '旺';
  if (/旺（有根）|相（有气）/.test(档)) return '相';
  if (/平（/.test(档)) return '平';
  if (/休囚有气/.test(档)) return '弱有救';
  if (/休囚无救|无根无助|月破失力|衰败已极/.test(档)) return '衰';
  if (/冲散|日破/.test(档)) return '衰';
  if (/暗动/.test(档)) return '暗动（力增）';
  return '未定';
}

/* ========================= 用神四处生克冲合（总纲） ========================= */
/**
 * 《增删卜易·用神章》以「四处生克冲合」为断卦总纲（原文逐条列举）：
 *   「此世爻戌土有四处生克冲合：一、月建能生克冲合；二、日辰能生克冲合；
 *     三、卦中之动爻能生克冲合；四、世爻发动变出之爻能回头生、克、冲、合。」
 * 并给结论：「以上四处若得全来生合用神者，诸占全吉。倘有三处相生一处相克，也以吉断。
 *   若有两处克两处生者，须看旺衰……尚遇三处相克一处相生，若得相生之爻旺相者也可断为
 *   克处逢凶中得解。若值休囚者有生之名无生之实，与四处俱来克者同断，诸占大凶。」
 *
 * 本函数只做**汇总**，不另立判据：四个来源各自的关系都已由 monthRelation / dayRelation /
 * 动爻生克 / changedRelation 算出，这里按原文归类为「生、合、克、冲」四类并给出多寡结论。
 * 不引入任何分值——原文只讲「三处相生一处相克」「两处克两处生」，是计数与旺衰，不是权重。
 */
export function fourFoldOf(用支, 用五行, rows, 月支, 日支, 变支) {
  const src = [];
  const relOf = (wx) => {
    if (!wx) return null;
    if (wx === 用五行) return '扶';
    if (SHENG[wx] === 用五行) return '生';
    if (KE[wx] === 用五行) return '克';
    return null;
  };
  // 一、月建
  if (月支) {
    if (用支 && branchClash(用支, 月支)) src.push({ 处: '月建', 关系: '冲（月破）', 支: 月支 });
    else if (用支 && branchCombine(用支, 月支)) src.push({ 处: '月建', 关系: '合', 支: 月支 });
    else {
      const r = relOf(ZHI_WX[月支]);
      if (r) src.push({ 处: '月建', 关系: r, 支: 月支 });
    }
  }
  // 二、日辰
  if (日支) {
    if (用支 && branchClash(用支, 日支)) src.push({ 处: '日辰', 关系: '冲', 支: 日支 });
    else if (用支 && branchCombine(用支, 日支)) src.push({ 处: '日辰', 关系: '合', 支: 日支 });
    else {
      const r = relOf(ZHI_WX[日支]);
      if (r) src.push({ 处: '日辰', 关系: r, 支: 日支 });
    }
  }
  // 三、卦中动爻（动爻生克用神；不含用神自身）
  (rows || []).forEach((r) => {
    if (!r.动) return;
    if (用支 && r.支 === 用支) return;
    if (用支 && branchClash(r.支, 用支)) { src.push({ 处: `动爻${r.爻}`, 关系: '冲', 支: r.支 }); return; }
    if (用支 && branchCombine(r.支, 用支)) { src.push({ 处: `动爻${r.爻}`, 关系: '合', 支: r.支 }); return; }
    const rr = relOf(ZHI_WX[r.支]);
    if (rr && rr !== '扶') src.push({ 处: `动爻${r.爻}`, 关系: rr, 支: r.支 });
  });
  // 四、用神自身发动、变出之爻回头生克冲合
  if (变支 && 用支) {
    if (branchClash(变支, 用支)) src.push({ 处: '变爻', 关系: '冲（回头冲）', 支: 变支 });
    else if (branchCombine(变支, 用支)) src.push({ 处: '变爻', 关系: '合（回头合）', 支: 变支 });
    else {
      const rr = relOf(ZHI_WX[变支]);
      if (rr) src.push({ 处: '变爻', 关系: rr === '生' ? '生（回头生）' : rr === '克' ? '克（回头克）' : rr, 支: 变支 });
    }
  }

  const 生 = src.filter((x) => x.关系 === '生' || x.关系 === '生（回头生）' || x.关系 === '扶').length;
  const 克 = src.filter((x) => x.关系 === '克' || x.关系 === '克（回头克）').length;
  const 冲 = src.filter((x) => x.关系.indexOf('冲') >= 0).length;
  const 合 = src.filter((x) => x.关系.indexOf('合') >= 0).length;

  // 原文结论按「生/克两类的多寡」判，冲合只作附记（原文未把冲合计入吉凶计数）。
  // 措辞按实际命中的处数生成——原文「三处相生一处相克」「两处克两处生」是举例，
  // 不是固定四处都必须有值（如用神静而不动时第四处本就不存在）。
  const 总 = 生 + 克;
  let 断 = '';
  if (!src.length) 断 = '四处俱不生克，只以本卦本爻旺衰论。';
  else if (克 === 0) 断 = `生合共 ${生} 处、无一克，诸占全吉。`;
  else if (生 === 0) 断 = `克共 ${克} 处、无一相生，诸占大凶。`;
  else if (生 > 克) 断 = `生 ${生} 处、克 ${克} 处，相生者多，以吉断（若相生之爻旺相，克处逢凶中得解）。`;
  else if (生 === 克) 断 = `生 ${生} 处、克 ${克} 处，两相抵，须看旺衰：生用神之神旺相者以吉断，克用神之神旺相者以凶推。`;
  else 断 = `克 ${克} 处、生 ${生} 处，克多生少；若相生之爻休囚则「有生之名无生之实」，与俱来克者同断。`;

  return { 生, 克, 冲, 合, 总, 明细: src, 断 };
}

