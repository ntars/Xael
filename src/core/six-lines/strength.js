  if (SHENG[日Wx] === 爻五行) return { 类: '日生', note: '日辰生爻，有气得力。' };
  if (日Wx === 爻五行) return { 类: '日扶', note: '日辰与爻同五行，得扶得力。' };
  if (SHENG[爻五行] === 日Wx) return { 类: '日泄', note: '爻生日辰，泄气。' };
