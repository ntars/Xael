/**
 * 六兽歌断（六神发动断）
 * ------------------------------------------------------------------
 * 出处：《卜筮正宗》-清·王洪绪（refs-texts/《卜筮正宗》-清·王洪绪.md 第 378 行「六兽歌断」）：
 *
 *   发动青龙附用通，进财进禄福无穷，临仇遇忌都无益，酒色成灾在此中。
 *   朱雀交重文印旺，煞神相并漫劳功，是非口舌皆因此，动出生身却利公。
 *   勾陈发动忧田土，累岁迍邅为忌逢，生用有情方是吉，若然安静不迷蒙。
 *   螣袉鬼克忧萦綷，怪梦阴魔暗里攻，持木落空休道吉，逢冲之日莫逃凶。
 *   白虎交重丧恶事，官司病患必成凶，持金动克妨人口，遇火生身便不同。
 *   玄武动摇多暗昧，若临官鬼贼交攻，有情生世邪无犯，仇忌临之奸盗凶。
 *
 * 大白话：六神本身不分吉凶，要看它「附在谁身上、动不动」。
 *   青龙动且所附为用神／原神 → 进财进禄；附在仇神忌神上则无益（反主酒色之灾）。
 *   朱雀动主文书口舌——临父母（文印）是好事，临忌神（煞神相并）就白费力气。
 *   勾陈动主田土迟滞——只有生用神才算吉，安静则无妨。
 *   螣蛇动主惊忧怪梦——临官鬼最凶，所持之爻属木又落空亡，吉断不可信；逢冲之日必见凶。
 *   白虎动主丧病——临官鬼、临官讼病患必凶；所持属金又动而克世，妨人口；若得火来生身则可解。
 *   玄武动主暗昧——临官鬼主盗贼，生世则邪不侵，临仇忌则奸盗之凶。
 *
 * 本模块只做定性归类，不打分、不加权。
 */

/** 六神所主（《卜筮正宗·六兽歌断》各句提炼，仅用于补足文案） */
const SHEN_ZHU = {
  青龙: '财禄喜庆', 朱雀: '文书口舌', 勾陈: '田土迟滞',
  螣蛇: '惊忧怪梦', 白虎: '丧病官讼', 玄武: '暗昧盗贼',
};

/**
 * 六神发动判词。
 * @param {object} o
 * @param {string} o.神 六神名（青龙／朱雀／勾陈／螣蛇／白虎／玄武）
 * @param {string} o.六亲 该爻六亲
 * @param {string} o.五行 该爻五行
 * @param {boolean} o.动 是否发动
 * @param {boolean} [o.空亡] 是否旬空
 * @param {boolean} [o.月破]
 * @param {boolean} [o.逢冲] 是否逢日辰或动爻之冲
 * @param {string} [o.世五行] 世爻五行（判「生世」「克世」用）
 * @param {string} [o.用神六亲] 用神六亲（判「附用」）
 * @param {string} [o.忌神六亲] 忌神六亲（判「临仇遇忌」）
 * @param {string} [o.仇神六亲]
 * @returns {{判:string, 吉凶:string, 依据:string, 说明:string}|null}
 */
export function shenDongVerdict(o) {
  const 神 = o && o.神;
  if (!SHEN_ZHU[神]) return null;
  const 六亲 = o.六亲 || '';
  const 五行 = o.五行 || '';
  const 依据 = `《卜筮正宗·六兽歌断》「${神}」条`;
  const 附 = (k) => !!k && k === 六亲;
  const 是用 = 附(o.用神六亲);
  const 是忌 = 附(o.忌神六亲);
  const 是仇 = 附(o.仇神六亲);
  const 仇忌 = 是忌 || 是仇;

  if (!o.动) {
    // 原文六句都以「发动／交重／动摇」起，安静者不在断内。
    return null;
  }

  switch (神) {
    case '青龙':
      if (是用) {
        return {
          判: '青龙发动附用', 吉凶: '吉', 依据,
          说明: '青龙发动而附于用神——原歌「发动青龙附用通，进财进禄福无穷」，主财禄喜庆、谋事顺遂。',
        };
      }
      if (仇忌) {
        return {
          判: '青龙发动临仇忌', 吉凶: '凶', 依据,
          说明: '青龙虽为吉神，然所附为仇神忌神——原歌「临仇遇忌都无益，酒色成灾在此中」，吉神反助其势，宜防酒色破财。',
        };
      }
      return {
        判: '青龙发动', 吉凶: '平', 依据,
        说明: `青龙发动主${SHEN_ZHU.青龙}，然未附用神、亦未临仇忌，吉意须与用神旺衰合看。`,
      };
    case '朱雀':
      if (是忌) {
        return {
          判: '朱雀发动临忌（煞神相并）', 吉凶: '凶', 依据,
          说明: '原歌「朱雀交重文印旺，煞神相并漫劳功，是非口舌皆因此」——朱雀临忌神为煞神相并，主是非口舌、白费力气。',
        };
      }
      if (六亲 === '父母') {
        return {
          判: '朱雀发动临父母（文印旺）', 吉凶: '吉', 依据,
          说明: '原歌「朱雀交重文印旺」——朱雀临父母，文书印信之事旺相，占文书、考试、契约得吉。',
        };
      }
      return {
        判: '朱雀发动', 吉凶: '平', 依据,
        说明: '朱雀发动主文书口舌，吉凶看所临六亲：临父母为文印旺之吉，临忌神则口舌是非。',
      };
    case '勾陈': {
      const 生世 = o.世五行 && 五行 && shengOf(五行) === o.世五行;
      if (是用) {
        return {
          判: '勾陈发动生用', 吉凶: '吉', 依据,
          说明: '原歌「勾陈发动忧田土……生用有情方是吉」——勾陈虽主田土迟滞，既生用神则为有情，事虽缓而终吉。',
        };
      }
      if (生世) {
        return {
          判: '勾陈发动生世', 吉凶: '吉', 依据,
          说明: '勾陈发动而生世爻，于己有情；原歌「生用有情方是吉」，生世同此义，主田土房产之事得利。',
        };
      }
      return {
        判: 仇忌 ? '勾陈发动临仇忌' : '勾陈发动', 吉凶: 仇忌 ? '凶' : '平', 依据,
        说明: '原歌「勾陈发动忧田土，累岁迍邅为忌逢」——勾陈发动主田土房产之事缠绵迟滞；临忌神则累岁迍邅。',
      };
    }
    case '螣蛇': {
      if (六亲 === '官鬼') {
        return {
          判: '螣蛇发动临官鬼', 吉凶: '凶', 依据,
          说明: '原歌「螣袉鬼克忧萦綷，怪梦阴魔暗里攻」——螣蛇临官鬼而发动，主忧疑缠绕、怪梦阴祟，占病尤忌。',
        };
      }
      if (五行 === '木' && (o.空亡 || o.月破)) {
        return {
          判: '螣蛇发动持木落空', 吉凶: '凶', 依据,
          说明: '原歌「持木落空休道吉」——螣蛇所持属木而又落空破，纵有吉象亦不可信，宜防虚惊。',
        };
      }
      if (o.逢冲) {
        return {
          判: '螣蛇发动逢冲', 吉凶: '凶', 依据,
          说明: '原歌「逢冲之日莫逃凶」——螣蛇发动而逢冲，怪异之事应于冲日，宜静守避之。',
        };
      }
      return {
        判: '螣蛇发动', 吉凶: '平', 依据,
        说明: '螣蛇发动主惊忧怪异、梦寐阴私；未临官鬼、未落空破，只作虚惊看。',
      };
    }
    case '白虎':
      if (六亲 === '官鬼') {
        return {
          判: '白虎发动临官鬼', 吉凶: '凶', 依据,
          说明: '原歌「白虎交重丧恶事，官司病患必成凶」——白虎临官鬼而发动，占官司病患必凶，占产尤须留意。',
        };
      }
      if (五行 === '金' && o.世五行 && shengOf('金') !== o.世五行 && keOf('金') === o.世五行) {
        return {
          判: '白虎发动持金克世', 吉凶: '凶', 依据,
          说明: '原歌「持金动克妨人口」——白虎所持属金、动而克世，主损伤人口、血光之患。',
        };
      }
      if (o.世五行 === '火') {
        return {
          判: '白虎发动遇火生身', 吉凶: '平', 依据,
          说明: '原歌「遇火生身便不同」——世属火，白虎之金受制，凶意大减，可从容处之。',
        };
      }
      return {
        判: '白虎发动', 吉凶: 仇忌 ? '凶' : '平', 依据,
        说明: '白虎发动主丧病官讼、血光损伤；临忌神更凶，临用神须看旺衰。',
      };
    case '玄武': {
      const 生世 = o.世五行 && 五行 && shengOf(五行) === o.世五行;
      if (六亲 === '官鬼') {
        return {
          判: '玄武发动临官鬼', 吉凶: '凶', 依据,
          说明: '原歌「玄武动摇多暗昧，若临官鬼贼交攻」——玄武临官鬼而发动，主盗贼、暗害、欺骗之事。',
        };
      }
      if (仇忌) {
        return {
          判: '玄武发动临仇忌', 吉凶: '凶', 依据,
          说明: '原歌「仇忌临之奸盗凶」——玄武临仇神忌神，主奸盗之患，宜防小人暗算。',
        };
      }
      if (生世 || 是用) {
        return {
          判: '玄武发动生世（有情）', 吉凶: '平', 依据,
          说明: '原歌「有情生世邪无犯」——玄武虽主暗昧，既生世爻／用神则为有情，邪不侵正。',
        };
      }
      return {
        判: '玄武发动', 吉凶: '平', 依据,
        说明: '玄武发动主暗昧不明、隐私欺瞒之事；未临官鬼仇忌，只作暗中留意看。',
      };
    }
    default:
      return null;
  }
}

/** 五行相生：x 生谁 */
function shengOf(x) {
  return { 木: '火', 火: '土', 土: '金', 金: '水', 水: '木' }[x] || null;
}

/** 五行相克：x 克谁 */
function keOf(x) {
  return { 木: '土', 土: '水', 水: '火', 火: '金', 金: '木' }[x] || null;
}

/**
 * 日月建传符（《卜筮正宗·日月建传符》原文）：
 *   日建加青龙，财禄喜重重，朱雀宜施用，勾陈事未通，螣蛇多怪异，
 *   白虎破财凶，玄武阴私扰，应在日时中，月建如临此，断法亦相同。
 *
 * 大白话：某一爻的支正好是今天的日支（临日辰）或本月的月支（临月建），
 *   这一爻就等于串上了日／月之权，再看它所临的六神是什么，就按原歌那八句断。
 *   青龙＝财禄、朱雀＝宜施用、勾陈＝事未通、螣蛇＝多怪异、白虎＝破财、
 *   玄武＝阴私；月建临爻断法完全相同。
 *
 * @param {string} 爻支 该爻地支
 * @param {string} 神 该爻六神
 * @param {{日支?:string, 月支?:string}} ctx
 * @returns {{判:string, 吉凶:string, 依据:string, 说明:string}|null}
 */
export function buildTransmitVerdict(爻支, 神, ctx) {
  if (!爻支 || !SHEN_ZHU[神]) return null;
  const 日支 = ctx && ctx.日支;
  const 月支 = ctx && ctx.月支;
  const 临日 = !!日支 && 爻支 === 日支;
  const 临月 = !!月支 && 爻支 === 月支;
  if (!临日 && !临月) return null;
  const 依据 = '《卜筮正宗·日月建传符》';
  const 谁 = 临日 && 临月 ? '日月建' : (临日 ? '日建' : '月建');
  const 表 = {
    青龙: { 断: '财禄喜重重', 吉凶: '吉' },
    朱雀: { 断: '宜施用（文书口舌之事当令）', 吉凶: '平' },
    勾陈: { 断: '事未通（田土房产之事迟滞）', 吉凶: '平' },
    螣蛇: { 断: '多怪异（惊忧虚诈之事当令）', 吉凶: '凶' },
    白虎: { 断: '破财凶（丧病损伤之事当令）', 吉凶: '凶' },
    玄武: { 断: '阴私扰（暗昧盗贼之事当令）', 吉凶: '凶' },
  }[神];
  if (!表) return null;
  return {
    判: `${谁}临${神}`, 吉凶: 表.吉凶, 依据,
    说明: `${爻支}支正临${谁}，所临${神}为「${表.断}」；原歌「应在日时中」，应期即在此日此月。`
      + (临日 && 临月 ? '（日建月建同临此爻，其权最重。）' : ''),
  };
}
