/**
 * 卦气旺衰（八宫卦气）
 *
 * 依据：《黄金策·身命》自注——
 *   「卦宫衰弱根基浅，爻象丰隆命运高。……如立春节艮旺、震相、巽胎、离没、坤死、兑囚、乾休、坎废类。
 *     大抵旺胜相胎、没胜休囚也。」
 * 这条自注把八宫的旺衰次序说全了：立春以艮为旺，其后依
 *   艮 → 震 → 巽 → 离 → 坤 → 兑 → 乾 → 坎
 * 一环顺推，配「旺、相、胎、没、死、囚、休、废」八等。
 * 八节各以其卦当旺（卦气说）：冬至坎、立春艮、春分震、立夏巽、夏至离、立秋坤、秋分兑、立冬乾。
 *
 * 本模块只做「给定月支 → 八卦各自的旺衰等第」这一层，不涉五行生克（那是另一套，见 strength.js）。
 */

/** 卦气顺推环：自冬至坎起，一环八宫 */
export const GUA_QI_RING = ['坎', '艮', '震', '巽', '离', '坤', '兑', '乾'];

/** 八等：旺 相 胎 没 死 囚 休 废 */
export const GUA_QI_STATES = ['旺', '相', '胎', '没', '死', '囚', '休', '废'];

/**
 * 当月当旺之卦（以「节」为界，月支定之）：
 *   寅（立春）艮、卯（春分）震、巳（立夏）巽、午（夏至）离、
 *   申（立秋）坤、酉（秋分）兑、亥（立冬）乾、子（冬至）坎。
 * 四季月（辰未戌丑）承前一个「节」，故辰归震、未归离、戌归兑、丑归坎。
 */
export const MONTH_TO_GUA = {
  寅: '艮', 卯: '震', 辰: '震',
  巳: '巽', 午: '离', 未: '离',
  申: '坤', 酉: '兑', 戌: '兑',
  亥: '乾', 子: '坎', 丑: '坎',
};

/** 卦 → 五行（八宫卦气用其本卦五行） */
export const GUA_WX = { 乾: '金', 兑: '金', 离: '火', 震: '木', 巽: '木', 坎: '水', 艮: '土', 坤: '土' };

/**
 * guaQiOf(月支) → { 当旺卦, 表: { 乾: '休', 兑: '囚', … } }
 * 表按 GUA_QI_RING 顺推八等，旺胜相胎、没胜休囚（原文自注）。
 */
export function guaQiOf(monthBranch) {
  const lead = MONTH_TO_GUA[String(monthBranch || '')];
  if (!lead) return null;
  const i0 = GUA_QI_RING.indexOf(lead);
  const 表 = {};
  GUA_QI_RING.forEach((g, k) => {
    表[g] = GUA_QI_STATES[((k - i0) % 8 + 8) % 8];
  });
  return { 当旺卦: lead, 表 };
}

/** 旺衰等第的强弱三分：旺相胎＝有力，没＝中，死囚休废＝无气 */
export function guaQiGrade(state) {
  const s = String(state || '');
  if (s === '旺' || s === '相' || s === '胎') return '有力';
  if (s === '没') return '中';
  if (s === '死' || s === '囚' || s === '休' || s === '废') return '无气';
  return '';
}
