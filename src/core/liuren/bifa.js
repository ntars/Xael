/** 供外部构造四柱文本用（'丁酉' 形式） */
export function gzTextOf(arr) { return Array.isArray(arr) ? arr[0] + arr[1] : String(arr || ''); }

/** 供外部换算天盘映射（支→支），liurenChart 的天地盘是 [{地盘,天盘}] 数组形式 */
export function tianPanMapOf(c) {
  const tp = (c && c.天地盘) || null;
  if (!tp) return null;
  if (!Array.isArray(tp) && tp.天盘) return tp.天盘;                       // {地盘,天盘} 对象形式
  const map = {};
  if (Array.isArray(tp)) tp.forEach((x) => { if (x && x.地盘) map[x.地盘] = x.天盘; });
  return Object.keys(map).length ? map : null;
}

