/** 五不遇时：时干克日干（阳克阳、阴克阴） */
const KE_GAN = { 甲: '戊', 乙: '己', 丙: '庚', 丁: '辛', 戊: '壬', 己: '癸', 庚: '甲', 辛: '乙', 壬: '丙', 癸: '丁' };

/**
 * 奇门格局判读。
 * @param {object} input {y,m,d,h}
 */
export function qimenGeOf(input) {
  const pan = qimenChart(input);
  const [dayGz, hourGz] = [pan['干支']['日'], pan['干支']['时']];

  const 命中 = [];
  for (const c of pan.cells) {
    const tian = c['天盘干'];
    const di = c['地盘干'];
    if (!tian || !di) continue;
    const key = tian + di;
    const ge = GE.find((g) => g[0] === key);
    if (ge) {
      命中.push({ 名: ge[1], 宫: c['宫'], 组合: `${tian}+${di}`, 说明: ge[2], 门: c['门'], 星: c['星'] });
    }
    // 飞干格：天盘庚 + 地盘日干
    if (tian === '庚' && di === dayGz[0]) {
      命中.push({ 名: '飞干格', 宫: c['宫'], 组合: `庚+${dayGz[0]}`, 说明: '日干受压，谋事不遂', 门: c['门'], 星: c['星'] });
    }
  }

  // 五不遇时
  const 日干 = dayGz[0];
  const 时干 = hourGz[0];
  if (KE_GAN[日干] === 时干) {
    命中.push({ 名: '五不遇时', 宫: '—', 组合: `${时干}克${日干}`, 说明: '时干克日干，事多阻滞', 门: '—', 星: '—' });
  }

  return {
    局: `${pan['遁']} ${pan['局']}`,
    值符: pan['值符'],
    值使: pan['值使'],
    命中,
    判读: 命中.length ? 命中.map((h) => h.名).join('、') : '未见典型凶格吉格',
    说明: '格局按十干克应与经典口诀检出，仅列盘中实际出现的组合，不作吉凶定论。',
  };
}
