/**
 * src/core/bazi/pattern.js —— 八字格局·喜用神（自研，零依赖）
 *
 * 大白话：格局是给八字「定主调」——月令（出生月的地支）里藏着哪几个天干，
 * 哪一个透到了天干上，就以它为格；再据此判断成格条件、破格之忌，配合调候与
 * 通关给出喜用神。本模块只做结构化判定，不作吉凶断语。
 *
 * 取格口径（《子平真诠》「八字用神，专求月令」）：
 *   ① 月令本气透干 → 取该十神为格（正官格、偏财格…）；
 *   ② 本气未透而所藏中气/余气透干 → 取透出者；
 *   ③ 藏干皆不透 → 取月令本气十神为格（标注「不透」）；
 *   ④ 比劫不取格：本气为比劫时，月令是日主禄位 → 建禄格；是阳干帝旺 → 阳刃格、
 *      是阴干帝旺 → 月劫格；否则继续看中气余气，仍无则归外格。
 *
 * 旺衰口径（得令 50% / 得地 30% / 得势 20% 加权，五档）：
 *   得令 = 月令五行同于日主或生日主；
 *   得地 = 四柱地支本气同五行计 1，其藏干同五行计 0.5，上限折满 4 为 1；
 *   得势 = 年/月/时三干中比劫或印星各计 1，上限折满 3 为 1；
 *   分数 = 50×得令 + 30×得地 + 20×得势 → ≥85 极旺、≥60 身旺、≥45 中和偏弱、
 *   ≥25 身弱、其余极弱。这是本项目自定的展示性指标，不是命理定论。
 *
 * 其余部件：调候（《穷通宝鉴》十干十二月）、通关（两行相战取泄者）、
 * 扶抑（旺则克泄、弱则生扶）、外格提示（从格/专旺/化气，简化判定）。
 */

