/**
 * src/core/bazi/shensha.js —— 八字神煞全表（自研，零依赖）
 *
 * 大白话：神煞是传统命理里的一批「标签」，按日干、年支、月支、日柱等查表得出，
 * 例如「天乙贵人」「桃花」「驿马」。口诀属公有领域知识（《三命通会》《渊海子平》等），
 * 本模块按口诀自行落表实现，不收第三方数据文件，输出只给「命中什么、按哪条口诀」，
 * 不作吉凶断言。
 *
 * 收录 34 类：
 *   以日干查四支：天乙贵人、太极贵人、文昌、禄神、羊刃、金舆、福星贵人、红艳煞
 *   以年支或日支查：驿马、桃花、华盖、将星、劫煞、灾煞、亡神
 *   以年支查：红鸾、天喜、孤辰、寡宿
 *   以月支查：天德贵人（值可能是天干也可能是地支）、月德贵人、天医
 *   以日柱（日干支）查：天赦日、十恶大败、阴阳差错、四废、魁罡、日德、日贵、孤鸾
 *   四柱天干连续三柱：三奇贵人
 *   年柱纳音：天罗（火见戌亥）、地网（水土见辰巳）
 *   日柱旬空：空亡
 *
 * 已知分歧（不合并，如实并列）：
 *   · 羊刃：阳干取帝旺（甲卯丙午庚酉壬子）无争议；阴干（乙辰丁未己未辛戌癸丑）有一派称「阴刃」，
 *     另一派作「乙刃在寅」，本模块取前者并注明。
 *   · 天德贵人：卯月「申」、午月「亥」、酉月「寅」、子月「巳」是地支天德，其余为天干天德，
 *     故必须「干查干、支查支」，不能混查。
 *   · 孤鸾：口诀「木火逢蛇、金猪、土猴、木虎」只明指五日，本模块只取这五日；
 *     另派并收「丙午、戊午、壬子」，不合并。
 *   · 天罗地网：以年柱纳音定（火见戌亥为天罗、水土见辰巳为地网），不走「见戌亥即天罗」的泛论。
 *   · 金神、童子煞：口诀流传但古籍正文无载或口径未定，只记不判。
 */

