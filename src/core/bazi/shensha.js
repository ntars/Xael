function tianxiOf(z) {
  return ZHIS[(ZHIS.indexOf(HONGLUAN[z]) + 6) % 12];
}

/**
 * 八字神煞全盘。
 * @param {object} input {y,m,d,h,minute,gender,name}
 * @returns {{四柱:string, 日主:string, 神煞:Array, 命中:Array, 汇总:string, 缺口:string}}
 */
export function shenshaOf(input) {
  const c = chart(input);
  const P = c.pillars;
  const gans = PILLARS.map((k) => P[k].干);
  const zhis = PILLARS.map((k) => P[k].支);
  const 日干 = P.日.干;
  const 月支 = P.月.支;
  const 年支 = P.年.支;
  const 日支 = P.日.支;
  const 日干支 = 日干 + 日支;

  const out = [];
  /** 记一条神煞：pos 为命中柱名数组 */
  const push = (名, pos, 查法, 义) => {
    out.push({ 名, 位: pos.length ? pos.join('、') + '柱' : '无', 查法, 义 });
  };
  /** 查地支类神煞命中哪几柱 */
  const hitZhi = (targets) => {
    const arr = [].concat(targets);
    const res = [];
    for (let i = 0; i < 4; i += 1) if (arr.indexOf(zhis[i]) >= 0) res.push(PILLARS[i]);
    return res;
  };
  /** 查天干类神煞命中哪几柱 */
  const hitGan = (target) => {
    const res = [];
    for (let i = 0; i < 4; i += 1) if (gans[i] === target) res.push(PILLARS[i]);
    return res;
  };
  /** 只判日柱的神煞（曾用「扫四柱干支」写法，会把时柱误判成魁罡，命中率虚高） */
  const riHit = (list) => (list.indexOf(日干支) >= 0 ? ['日'] : []);

  // ── 1 天乙贵人（日干查四支，兼年干）
  const gui = GUI_REN[日干] || GUI_REN[gans[0]] || [];
  push('天乙贵人', hitZhi(gui), '日干（兼年干）查四支：甲戊丑未、乙己子申、丙丁亥酉、庚辛午寅、壬癸卯巳（《金函玉镜》）', '命中第一吉神，主逢难有救、遇贵得助');

  // ── 2 太极贵人
  push('太极贵人', hitZhi(TAIJI[日干] || []), '日干查支：甲乙子午、丙丁卯酉、戊己辰戌丑未、庚辛寅亥、壬癸巳申', '主好玄学、有始有终，喜文史哲与术数');

  // ── 3 文昌贵人
  push('文昌贵人', hitZhi(WENCHANG[日干] ? [WENCHANG[日干]] : []), '日干查支：甲巳乙午丙戊申、丁己酉、庚亥辛子壬寅癸卯', '主聪明好学、文书清贵，利考试与文职');

  // ── 4 天德贵人（月支 → 天干或地支，故干查干、支查支）
  const td = TIANDE[月支];
  if (td) {
    const isGan = GAN.some((g) => g.z === td);
    push('天德贵人', isGan ? hitGan(td) : hitZhi([td]),
      `月支查「${isGan ? '天干' : '地支'}」：正月丁、二月申、三月壬、四月辛、五月亥、六月甲、七月癸、八月寅、九月丙、十月乙、冬月巳、腊月庚`,
      '主逢凶化吉、心地慈善，解厄之神');
  }

  // ── 5 月德贵人（月支三合局查天干）
  const yd = YUEDE[月支];
  if (yd) push('月德贵人', hitGan(yd), '月支三合局查天干：寅午戌见丙、申子辰见壬、亥卯未见甲、巳酉丑见庚', '主福厚安泰、处事圆融，与天德并称「二德」');

  // ── 6 驿马
  push('驿马', hitZhi([YIMA[年支], YIMA[日支]]), '年支或日支三合局查：申子辰马在寅、寅午戌马在申、巳酉丑马在亥、亥卯未马在巳', '主奔波迁动、出行远游，喜动不喜静');

  // ── 7 桃花（咸池）
  push('桃花', hitZhi([TAOHUA[年支], TAOHUA[日支]]), '年支或日支三合局查：申子辰在酉、寅午戌在卯、巳酉丑在午、亥卯未在子', '主人缘情缘、才艺风雅，过则主情困');

  // ── 8 红鸾 / 9 天喜
  push('红鸾', hitZhi([HONGLUAN[年支]]), '年支查：子卯、丑寅、寅丑、卯子、辰亥、巳戌、午酉、未申、申未、酉午、戌巳、亥辰', '主婚喜、添丁、喜庆之事');
  push('天喜', hitZhi([tianxiOf(年支)]), '年支查红鸾之对宫（红鸾 + 6 位）', '主喜庆、得子、逢凶化吉');

  // ── 10 华盖
  push('华盖', hitZhi([HUAGAI[年支], HUAGAI[日支]]), '年支或日支三合局查：申子辰在辰、寅午戌在戌、巳酉丑在丑、亥卯未在未', '主孤高清雅、好艺术宗教，喜独处');

  // ── 11 将星
  push('将星', hitZhi([JIANGXING[年支], JIANGXING[日支]]), '年支或日支三合局「帝旺」位：申子辰在子、寅午戌在午、巳酉丑在酉、亥卯未在卯', '主统御之才、居中掌权');

  // ── 12 劫煞 / 13 灾煞 / 14 亡神
  push('劫煞', hitZhi([JIESHA[年支], JIESHA[日支]]), '年支或日支三合局「绝」位：申子辰在巳、寅午戌在亥、巳酉丑在寅、亥卯未在申', '主刚烈敢为、亦主耗财与意外');
  push('灾煞', hitZhi([ZAISHA[年支], ZAISHA[日支]]), '年支或日支三合局「胎」位：申子辰在午、寅午戌在子、巳酉丑在卯、亥卯未在酉', '主灾厄惊险，宜防冲动行事');
  push('亡神', hitZhi([WANGSHEN[年支], WANGSHEN[日支]]), '年支或日支三合局「临官」前位：申子辰在亥、寅午戌在巳、巳酉丑在申、亥卯未在寅', '主心机深沉、城府，亦主失落遗亡');

  // ── 15 孤辰 / 16 寡宿
  push('孤辰', hitZhi([GUCHEN[年支]]), '年支查：亥子丑见寅、寅卯辰见巳、巳午未见申、申酉戌见亥', '主孤独自立，男怕孤辰');
  push('寡宿', hitZhi([GUASU[年支]]), '年支查：亥子丑见戌、寅卯辰见丑、巳午未见辰、申酉戌见未', '主独处寡合，女怕寡宿');

  // ── 17 禄神
  push('禄神', hitZhi([LU[日干]]), '日干查临官位：甲寅、乙卯、丙戊巳、丁己午、庚申、辛酉、壬亥、癸子', '主衣食丰足、自立根基');

  // ── 18 羊刃
  push('羊刃', hitZhi([YANGREN[日干]]), '日干查帝旺位：甲卯、乙辰、丙戊午、丁己未、庚酉、辛戌、壬子、癸丑（阴干一派另作「乙刃在寅」，此处取前一派）', '主刚强果决，过则主刑伤争竞');

  // ── 19 金舆
  push('金舆', hitZhi([JINYU[日干]]), '日干查：甲辰、乙巳、丙戊未、丁己申、庚戌、辛亥、壬丑、癸寅', '主富贵安逸、得配偶之助，古称「金舆扶身」');

  // ── 20 空亡（日柱旬空）
  const dayIdx = dayGanZhiIndex(c.input.y, c.input.m, c.input.d);
  const kw = xunkongOf(dayIdx);
  push('空亡', hitZhi(kw), `日柱旬空（本盘日柱${JIAZI[dayIdx].join('')}属旬，旬空${kw.join('')}）`, '主虚而不实、事多落空；吉神空则减力，凶神空则减凶');

  // ── 21 天医
  push('天医', hitZhi([tianyiOf(月支)]), '月支前一位：正月见卯、二月见辰…（依次顺推）', '主健康医疗、宜从医或得医药之助');

  // ── 22 天赦日（按月支季节查日柱）
  const ji = JI[月支];
  push('天赦日', 日干支 === TIAN_SHE[ji] ? ['日'] : [], '月支季节查日柱：春戊寅、夏甲午、秋戊申、冬甲子（《三命通会·论天赦》）', '主赦过宥罪，古以为解厄之日');

  // ── 23 十恶大败
  push('十恶大败', riHit(SHI_E), '日柱为十干之禄落旬空之日：甲辰、乙巳、壬申、丙申、丁亥、庚辰、戊戌、癸亥、辛巳、己丑（《三命通会》）', '主耗散破败，古法以为理财宜慎');

  // ── 24 阴阳差错
  push('阴阳差错', riHit(YIN_YANG_CUO), '日柱为阴阳差错日：丙子、丁丑、戊寅、辛卯、壬辰、癸巳、丙午、丁未、戊申、辛酉、壬戌、癸亥（《三命通会》）', '主婚姻多波折，古以为配偶宫错位');

  // ── 25 四废
  push('四废', (SI_FEI[ji] || []).indexOf(日干支) >= 0 ? ['日'] : [], '月支季节查日柱：春庚申辛酉、夏壬子癸亥、秋甲寅乙卯、冬丙午丁巳（《三命通会·论四废》）', '主作事少成，当令者旺而被克者废');

  // ── 26 魁罡
  push('魁罡', riHit(KUI_GANG), '日柱为壬辰、庚戌、庚辰、戊戌四日（《三命通会·论魁罡》）', '主性刚果断、聪敏好权，忌刑冲');

  // ── 27 日德
  push('日德', riHit(RI_DE), '日柱为甲寅、丙辰、戊辰、庚辰、壬戌五日（《三命通会·论日德》）', '主慈祥宽厚，古称「日德」');

  // ── 28 日贵
  push('日贵', riHit(RI_GUI), '日柱为丁酉、丁亥、癸卯、癸巳四日（《三命通会·论日贵》）', '主为人清贵，得人敬重');

  // ── 29 天罗 / 30 地网（按年柱纳音，不走「见戌亥即天罗」泛论）
  const nyWx = (P.年.纳音 || '').slice(-1);
  push('天罗', nyWx === '火' ? hitZhi(['戌', '亥']) : [], '年柱纳音属火，四支见戌亥（《三命通会》：戌亥为天罗）', '主束缚阻滞，古有「男怕天罗」之说');
  push('地网', (nyWx === '水' || nyWx === '土') ? hitZhi(['辰', '巳']) : [], '年柱纳音属水或土，四支见辰巳（《三命通会》：辰巳为地网）', '主牵缠难脱，古有「女怕地网」之说');

  // ── 31 三奇贵人（连续三柱顺布，位记三柱而非单柱）
  const sq = [];
  SAN_QI.forEach((p) => {
    for (let i = 0; i + 2 < 4; i += 1) {
      if (gans[i] === p[0].charAt(0) && gans[i + 1] === p[0].charAt(1) && gans[i + 2] === p[0].charAt(2)) {
        sq.push(`${PILLARS[i]}${PILLARS[i + 1]}${PILLARS[i + 2]}三柱（${p[1]}）`);
      }
    }
  });
  out.push({
    名: '三奇贵人',
    位: sq.length ? sq.join('、') : '无',
    查法: '四柱天干连续三柱顺布：甲戊庚（天上三奇）、乙丙丁（地下三奇）、壬癸辛（人中三奇）（《三命通会·论三奇》）',
    义: '主胸怀卓异、博学多能，须顺布不乱方为真',
  });

  // ── 32 福星贵人
  push('福星贵人', hitZhi(FU_XING[日干] || []), '日干查四支：甲丙见寅子、乙见丑、丁见亥、戊见申、己见未、庚见午、辛见巳、壬见辰、癸见卯（《三命通会》）', '主福禄绵长、一生少忧');

  // ── 33 红艳煞
  push('红艳煞', HONG_YAN[日干] ? hitZhi([HONG_YAN[日干]]) : [], '日干查支：甲午、乙申、丙寅、丁未、戊辰、己辰、庚戌、辛酉、壬子、癸申（《三命通会》）', '主情多貌美、异性缘重，过则牵累');

  // ── 34 孤鸾
  push('孤鸾', riHit(GU_LUAN), '日柱为乙巳、丁巳、辛亥、戊申、甲寅（《三命通会》：木火逢蛇、金猪、土猴、木虎）', '主夫妻缘薄，古称「孤鸾」');

  // ── 汇总输出
  const 命中 = out.filter((x) => x.位 !== '无');
  return {
    四柱: PILLARS.map((k) => `${k}柱${P[k].干支}`).join(' '),
    日主: `${日干}（${c.日主.五行}）`,
    神煞: out,
    命中,
    汇总: `共查 ${out.length} 类神煞，命中 ${命中.length} 类：${命中.length ? 命中.map((x) => x.名).join('、') : '无'}`,
    缺口: '神煞为传统「象法」辅助，不作定性断言；羊刃阴干取法、天德干/支取法、孤鸾另派并收丙午戊午壬子三处流派并存已在各行注明。'
      + '另有两类「口诀可查而口径未定」故只记不判：金神（三时乙丑己巳癸酉，须甲日方是，另有「甲己日」一派且部分流派更要求月令配合）；'
      + '童子煞（口诀「春秋寅子贵、冬夏卯未辰…」仅见民俗流传，不见于《三命通会》《渊海子平》正文，出处存疑）。',
  };
}

